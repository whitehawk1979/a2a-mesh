#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Generated by runa via A2A Mesh delegation

Version-drift auto-heal: diagnostics.py
"accepted" státuszú drift-eknél a régi node kapjon 1 automatikus sync-promptot.

Ez a modul a A2A Mesh hálózatban detektált verzió-eltolódásokat (version drift)
követi nyomon. Amikor egy drift "accepted" státuszba kerül (a node elfogadja,
hogy elavult), a modul automatikusan küld egy sync-promptot a régi node-nak,
hogy frissítse magát a hálózat aktuális verziójára.

Futtatható a repó gyökeréből:
    python diagnostics.py
"""

import json
import os
import time
import hashlib
import logging
import threading
from dataclasses import dataclass, field, asdict
from enum import Enum
from typing import Dict, List, Optional, Tuple
from datetime import datetime, timezone

# ---------------------------------------------------------------------------
# Logging
# ---------------------------------------------------------------------------
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] [diagnostics] %(message)s",
)
logger = logging.getLogger("a2a_mesh.diagnostics")

# ---------------------------------------------------------------------------
# Constants & paths
# ---------------------------------------------------------------------------
REPO_ROOT = os.path.dirname(os.path.abspath(__file__))
DATA_DIR = os.path.join(REPO_ROOT, "data")
DRIFT_STATE_FILE = os.path.join(DATA_DIR, "drift_state.json")
SYNC_PROMPT_LOG = os.path.join(DATA_DIR, "sync_prompts.jsonl")

MAX_SYNC_PROMPTS_PER_DRIFT = 1  # csak 1 automatikus sync-prompt a régi node-nak
SYNC_PROMPT_COOLDOWN_SEC = 300  # 5 perc cooldown duplikáció elkerülésére

# ---------------------------------------------------------------------------
# Enums
# ---------------------------------------------------------------------------
class DriftStatus(Enum):
    DETECTED = "detected"
    ACCEPTED = "accepted"
    RESOLVED = "resolved"
    IGNORED = "ignored"

# ---------------------------------------------------------------------------
# Data classes
# ---------------------------------------------------------------------------
@dataclass
class NodeInfo:
    """Egy mesh node alapvető információi."""
    node_id: str
    version: str
    endpoint: str
    last_seen: float = field(default_factory=time.time)

@dataclass
class VersionDrift:
    """Egy verzió-eltolódás eseménye."""
    drift_id: str
    old_node_id: str
    old_version: str
    reference_node_id: str
    reference_version: str
    status: str = DriftStatus.DETECTED.value
    detected_at: float = field(default_factory=time.time)
    accepted_at: Optional[float] = None
    sync_prompt_sent: bool = False
    sync_prompt_sent_at: Optional[float] = None
    sync_prompt_count: int = 0
    resolved_at: Optional[float] = None

    def to_dict(self) -> dict:
        return asdict(self)

    @classmethod
    def from_dict(cls, d: dict) -> "VersionDrift":
        return cls(**d)

# ---------------------------------------------------------------------------
# DriftStore — perzisztens drift-állapot
# ---------------------------------------------------------------------------
class DriftStore:
    """A drift-állomány perzisztens tárolása JSON fájlban."""

    def __init__(self, path: str = DRIFT_STATE_FILE):
        self.path = path
        self._lock = threading.Lock()
        self._drifts: Dict[str, VersionDrift] = {}
        self._load()

    def _load(self):
        if os.path.exists(self.path):
            try:
                with open(self.path, "r", encoding="utf-8") as f:
                    data = json.load(f)
                for drift_id, d in data.items():
                    self._drifts[drift_id] = VersionDrift.from_dict(d)
                logger.info("Loaded %d drift records from %s", len(self._drifts), self.path)
            except (json.JSONDecodeError, TypeError, KeyError) as e:
                logger.warning("Failed to load drift state: %s — starting fresh", e)
                self._drifts = {}

    def _save(self):
        os.makedirs(os.path.dirname(self.path), exist_ok=True)
        tmp = self.path + ".tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            json.dump({k: v.to_dict() for k, v in self._drifts.items()}, f,
                      indent=2, ensure_ascii=False)
        os.replace(tmp, self.path)

    def add_or_update(self, drift: VersionDrift) -> None:
        with self._lock:
            self._drifts[drift.drift_id] = drift
            self._save()

    def get(self, drift_id: str) -> Optional[VersionDrift]:
        with self._lock:
            return self._drifts.get(drift_id)

    def get_all(self) -> List[VersionDrift]:
        with self._lock:
            return list(self._drifts.values())

    def get_by_status(self, status: DriftStatus) -> List[VersionDrift]:
        with self._lock:
            return [d for d in self._drifts.values() if d.status == status.value]

    def remove(self, drift_id: str) -> None:
        with self._lock:
            self._drifts.pop(drift_id, None)
            self._save()

# ---------------------------------------------------------------------------
# SyncPromptSender — sync-prompt küldése a régi node-nak
# ---------------------------------------------------------------------------
class SyncPromptSender:
    """
    Felelős egy sync-prompt elküldéséért a régi (elavult) node-nak.

    A valódi A2A Mesh-ben ez egy A2A üzenetet küldene a node endpoint-jára.
    Itt a promptot perzisztáljuk egy JSONL naplóba, és szimuláljuk a küldést.
    """

    def __init__(self, log_path: str = SYNC_PROMPT_LOG):
        self.log_path = log_path
        os.makedirs(os.path.dirname(self.log_path), exist_ok=True)

    def send_sync_prompt(self, drift: VersionDrift, old_node: NodeInfo,
                         ref_node: NodeInfo) -> bool:
        """
        Küld egy sync-promptot a régi node-nak.

        Visszatér True-val, ha a küldés sikeres (vagy szimulált sikeres).
        """
        prompt = {
            "type": "sync_prompt",
            "drift_id": drift.drift_id,
            "target_node_id": old_node.node_id,
            "target_endpoint": old_node.endpoint,
            "current_version": old_node.version,
            "expected_version": ref_node.version,
            "reference_node_id": ref_node.node_id,
            "reference_endpoint": ref_node.endpoint,
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "message": (
                f"Version drift detected and accepted. "
                f"Your node '{old_node.node_id}' is running v{old_node.version}, "
                f"but the mesh reference is v{ref_node.version}. "
                f"Please sync/update to v{ref_node.version}."
            ),
        }

        # JSONL naplóba írás
        try:
            with open(self.log_path, "a", encoding="utf-8") as f:
                f.write(json.dumps(prompt, ensure_ascii=False) + "\n")
            logger.info(
                "Sync-prompt sent to node '%s' (v%s -> v%s) for drift %s",
                old_node.node_id, old_node.version, ref_node.version, drift.drift_id
            )
            return True
        except OSError as e:
            logger.error("Failed to write sync-prompt log: %s", e)
            return False

# ---------------------------------------------------------------------------
# DiagnosticsEngine — fő logika
# ---------------------------------------------------------------------------
class DiagnosticsEngine:
    """
    A diagnosztikai motor, amely:
    1. Detektálja a verzió-eltolódásokat a mesh node-ok között.
    2. Kezeli a drift státuszokat (detected -> accepted -> resolved).
    3. "accepted" státuszú drift-eknél automatikusan küld 1 sync-promptot
       a régi node-nak (auto-heal).
    """

    def __init__(self,
                 store: Optional[DriftStore] = None,
                 sender: Optional[SyncPromptSender] = None):
        self.store = store or DriftStore()
        self.sender = sender or SyncPromptSender()
        self._node_registry: Dict[str, NodeInfo] = {}

    # --- Node registry ---

    def register_node(self, node: NodeInfo) -> None:
        self._node_registry[node.node_id] = node
        logger.debug("Registered node %s (v%s)", node.node_id, node.version)

    def unregister_node(self, node_id: str) -> None:
        self._node_registry.pop(node_id, None)

    def get_nodes(self) -> List[NodeInfo]:
        return list(self._node_registry.values())

    # --- Drift detection ---

    @staticmethod
    def _compute_drift_id(old_node_id: str, old_version: str,
                          ref_version: str) -> str:
        raw = f"{old_node_id}:{old_version}:{ref_version}"
        return "drift_" + hashlib.sha256(raw.encode()).hexdigest()[:16]

    def detect_drifts(self) -> List[VersionDrift]:
        """
        Összehasonlítja a regisztrált node-ok verzióit.
        A leggyakoribb verzió a referencia. Minden ettől eltérő node
        esetén drift jön létre (ha még nem létezik).
        """
        if not self._node_registry:
            return []

        # Verzió-szavazás: a legnépszerűbb verzió a referencia
        version_counts: Dict[str, int] = {}
        for node in self._node_registry.values():
            version_counts[node.version] = version_counts.get(node.version, 0) + 1

        ref_version = max(version_counts, key=version_counts.get)
        ref_nodes = [n for n in self._node_registry.values() if n.version == ref_version]

        if not ref_nodes:
            return []

        ref_node = ref_nodes[0]  # első referencia node

        new_drifts: List[VersionDrift] = []
        for node in self._node_registry.values():
            if node.version != ref_version:
                drift_id = self._compute_drift_id(node.node_id, node.version, ref_version)
                existing = self.store.get(drift_id)
                if existing is None:
                    drift = VersionDrift(
                        drift_id=drift_id,
                        old_node_id=node.node_id,
                        old_version=node.version,
                        reference_node_id=ref_node.node_id,
                        reference_version=ref_version,
                        status=DriftStatus.DETECTED.value,
                    )
                    self.store.add_or_update(drift)
                    new_drifts.append(drift)
                    logger.info(
                        "Drift detected: node '%s' v%s vs reference v%s (id=%s)",
                        node.node_id, node.version, ref_version, drift_id
                    )
                elif existing.status == DriftStatus.RESOLVED.value:
                    # Ha korábban resolved volt, de a node még mindig régi,
                    # újra detected-be tesszük
                    existing.status = DriftStatus.DETECTED.value
                    existing.resolved_at = None
                    self.store.add_or_update(existing)
                    new_drifts.append(existing)

        return new_drifts

    # --- Státusz átmenetek ---

    def accept_drift(self, drift_id: str) -> Optional[VersionDrift]:
        """
        Egy drift "accepted" státuszba helyezése.
        Ez jelzi, hogy a régi node tudomásul vette az elavultságát.
        """
        drift = self.store.get(drift_id)
        if drift is None:
            logger.warning("Cannot accept drift %s — not found", drift_id)
            return None

        if drift.status == DriftStatus.RESOLVED.value:
            logger.info("Drift %s already resolved — skipping accept", drift_id)
            return drift

        drift.status = DriftStatus.ACCEPTED.value
        drift.accepted_at = time.time()
        self.store.add_or_update(drift)
        logger.info("Drift %s accepted by node '%s'", drift_id, drift.old_node_id)
        return drift

    def resolve_drift(self, drift_id: str) -> Optional[VersionDrift]:
        """Drift megoldottnak jelölése (a node frissítette magát)."""
        drift = self.store.get(drift_id)
        if drift is None:
            return None
        drift.status = DriftStatus.RESOLVED.value
        drift.resolved_at = time.time()
        self.store.add_or_update(drift)
        logger.info("Drift %s resolved", drift_id)
        return drift

    def ignore_drift(self, drift_id: str) -> Optional[VersionDrift]:
        drift = self.store.get(drift_id)
        if drift is None:
            return None
        drift.status = DriftStatus.IGNORED.value
        self.store.add_or_update(drift)
        logger.info("Drift %s ignored", drift_id)
        return drift

    # --- Auto-heal: sync-prompt küldése accepted drift-eknél ---

    def auto_heal_accepted_drifts(self) -> List[VersionDrift]:
        """
        Az összes "accepted" státuszú drift esetén a régi node kap
        1 automatikus sync-promptot (ha még nem kapott, vagy a cooldown
        lejárt és a count még nem érte el a MAX_SYNC_PROMPTS_PER_DRIFT-et).
        """
        accepted = self.store.get_by_status(DriftStatus.ACCEPTED)
        healed: List[VersionDrift] = []

        for drift in accepted:
            # Csak 1 sync-promptot küldünk (MAX_SYNC_PROMPTS_PER_DRIFT = 1)
            if drift.sync_prompt_count >= MAX_SYNC_PROMPTS_PER_DRIFT:
                logger.debug(
                    "Drift %s already received %d sync-prompt(s) — skipping",
                    drift.drift_id, drift.sync_prompt_count
                )
                continue

            # Cooldown ellenőrzése (ha már küldtünk, de még nem érte el a limitet)
            if drift.sync_prompt_sent_at is not None:
                elapsed = time.time() - drift.sync_prompt_sent_at
                if elapsed < SYNC_PROMPT_COOLDOWN_SEC:
                    logger.debug(
                        "Drift %s in cooldown (%.0fs remaining) — skipping",
                        drift.drift_id, SYNC_PROMPT_COOLDOWN_SEC - elapsed
                    )
                    continue

            # Node-ok lookup
            old_node = self._node_registry.get(drift.old_node_id)
            ref_node = self._node_registry.get(drift.reference_node_id)

            if old_node is None:
                logger.warning(
                    "Cannot send sync-prompt for drift %s — old node '%s' not registered",
                    drift.drift_id, drift.old_node_id
                )
                continue

            if ref_node is None:
                # Ha a ref node nincs bent, akkor egy placeholder-t használunk
                ref_node = NodeInfo(
                    node_id=drift.reference_node_id,
                    version=drift.reference_version,
                    endpoint="unknown",
                )

            # Sync-prompt küldése
            success = self.sender.send_sync_prompt(drift, old_node, ref_node)
            if success:
                drift.sync_prompt_sent = True
                drift.sync_prompt_sent_at = time.time()
                drift.sync_prompt_count += 1
                self.store.add_or_update(drift)
                healed.append(drift)
                logger.info(
                    "Auto-heal: sync-prompt #%d sent to node '%s' for drift %s",
                    drift.sync_prompt_count, drift.old_node_id, drift.drift_id
                )

        return healed

    # --- Teljes diagnosztikai ciklus ---

    def run_diagnostics_cycle(self) -> Dict:
        """
        Egy teljes diagnosztikai ciklus futtatása:
        1. Drift detektálás
        2. Auto-heal (sync-prompt küldése accepted drift-eknél)
        3. Jelentés
        """
        logger.info("=== Diagnostics cycle started ===")

        new_drifts = self.detect_drifts()
        healed = self.auto_heal_accepted_drifts()

        all_drifts = self.store.get_all()
        status_summary: Dict[str, int] = {}
        for d in all_drifts:
            status_summary[d.status] = status_summary.get(d.status, 0) + 1

        report = {
            "cycle_at": datetime.now(timezone.utc).isoformat(),
            "registered_nodes": len(self._node_registry),
            "new_drifts": len(new_drifts),
            "auto_healed": len(healed),
            "total_drifts": len(all_drifts),
            "status_summary": status_summary,
            "healed_drift_ids": [d.drift_id for d in healed],
            "new_drift_ids": [d.drift_id for d in new_drifts],
        }

        logger.info("Diagnostics cycle complete: %s", json.dumps(report, ensure_ascii=False))
        return report

    # --- Jelentés ---

    def generate_report(self) -> str:
        drifts = self.store.get_all()
        lines = [
            "=" * 70,
            "A2A Mesh — Diagnostics Report",
            f"Generated: {datetime.now(timezone.utc).isoformat()}",
            f"Registered nodes: {len(self._node_registry)}",
            f"Total drifts: {len(drifts)}",
            "=" * 70,
        ]

        status_counts: Dict[str, int] = {}
        for d in drifts:
            status_counts[d.status] = status_counts.get(d.status, 0) + 1
        for status, count in sorted(status_counts.items()):
            lines.append(f"  {status}: {count}")

        lines.append("-" * 70)
        lines.append("Drift details:")
        for d in drifts:
            lines.append(
                f"  [{d.status.upper():>9}] {d.drift_id}  "
                f"node='{d.old_node_id}' v{d.old_version} -> v{d.reference_version}  "
                f"sync_prompts={d.sync_prompt_count}"
            )

        lines.append("=" * 70)
        return "\n".join(lines)


# ---------------------------------------------------------------------------
# Demo / CLI entry point
# ---------------------------------------------------------------------------
def _demo():
    """
    Bemutató: szimulál egy mesh hálózatot verzió-eltolódással,
    és megmutatja az auto-heal működését.
    """
    engine = DiagnosticsEngine()

    # Tiszta állapot a demo-hoz
    if os.path.exists(DRIFT_STATE_FILE):
        os.remove(DRIFT_STATE_FILE)
    if os.path.exists(SYNC_PROMPT_LOG):
        os.remove(SYNC_PROMPT_LOG)
    engine.store = DriftStore()

    # Node-ok regisztrálása — 3 node v2.1.0, 1 node v2.0.8 (elavult)
    nodes = [
        NodeInfo("node-alpha", "2.1.0", "tcp://10.0.0.1:7001"),
        NodeInfo("node-beta",  "2.1.0", "tcp://10.0.0.2:7001"),
        NodeInfo("node-gamma", "2.1.0", "tcp://10.0.0.3:7001"),
        NodeInfo("node-delta", "2.0.8", "tcp://10.0.0.4:7001"),  # elavult
    ]
    for n in nodes:
        engine.register_node(n)

    print("\n" + "=" * 70)
    print("STEP 1: Detect drifts")
    print("=" * 70)
    new_drifts = engine.detect_drifts()
    print(f"New drifts detected: {len(new_drifts)}")
    for d in new_drifts:
        print(f"  {d.drift_id}: node='{d.old_node_id}' "
              f"v{d.old_version} -> v{d.reference_version} [{d.status}]")

    print("\n" + "=" * 70)
    print("STEP 2: Accept the drift (node-delta acknowledges it's outdated)")
    print("=" * 70)
    if new_drifts:
        accepted = engine.accept_drift(new_drifts[0].drift_id)
        if accepted:
            print(f"Drift accepted: {accepted.drift_id} -> status={accepted.status}")

    print("\n" + "=" * 70)
    print("STEP 3: Auto-heal — send 1 sync-prompt to the old node")
    print("=" * 70)
    healed = engine.auto_heal_accepted_drifts()
    print(f"Auto-healed drifts: {len(healed)}")
    for d in healed:
        print(f"  {d.drift_id}: sync_prompt_sent={d.sync_prompt_sent} "
              f"count={d.sync_prompt_count}")

    print("\n" + "=" * 70)
    print("STEP 4: Try auto-heal again — should NOT send (limit=1)")
    print("=" * 70)
    healed_again = engine.auto_heal_accepted_drifts()
    print(f"Auto-healed drifts (2nd attempt): {len(healed_again)}")
    print("(Expected: 0 — already sent 1 sync-prompt)")

    print("\n" + "=" * 70)
    print("STEP 5: Simulate node-delta updating to v2.1.0")
    print("=" * 70)
    engine._node_registry["node-delta"].version = "2.1.0"
    # Re-detect: a drift resolved-dé válik
    engine.detect_drifts()
    # Manually resolve
    if new_drifts:
        resolved = engine.resolve_drift(new_drifts[0].drift_id)
        if resolved:
            print(f"Drift resolved: {resolved.drift_id} -> status={resolved.status}")

    print("\n" + "=" * 70)
    print("FINAL REPORT")
    print("=" * 70)
    print(engine.generate_report())

    # Sync-prompt napló megjelenítése
    print("\n" + "=" * 70)
    print("SYNC-PROMPT LOG (JSONL)")
    print("=" * 70)
    if os.path.exists(SYNC_PROMPT_LOG):
        with open(SYNC_PROMPT_LOG, "r", encoding="utf-8") as f:
            for line in f:
                entry = json.loads(line.strip())
                print(json.dumps(entry, indent=2, ensure_ascii=False))
    else:
        print("(no sync-prompts logged)")


if __name__ == "__main__":
    _demo()