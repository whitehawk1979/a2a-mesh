def normalize_timestamp(value) -> float | None:
    """SQLite-ból jövő timestamp értéket epoch másodperccé alakít."""
    if value is None:
        return None
    if isinstance(value, (int, float)):
        # Ha 10 jegyű: másodperc, ha 13: millisec
        if value > 1e12:
            return value / 1000.0
        return float(value)
    if isinstance(value, str):
        s = value.strip()
        # ISO formátum próbálkozás
        for fmt in (
            "%Y-%m-%d %H:%M:%S",
            "%Y-%m-%d %H:%M:%S.%f",
            "%Y-%m-%dT%H:%M:%S",
            "%Y-%m-%dT%H:%M:%S.%f",
            "%Y-%m-%dT%H:%M:%SZ",
            "%Y-%m-%dT%H:%M:%S.%fZ",
        ):
            try:
                dt = datetime.strptime(s.replace("Z", ""), fmt.split("Z")[0])
                return dt.replace(tzinfo=timezone.utc).timestamp()
            except ValueError:
                continue
        # Próbáljuk fromisoformat
        try:
            dt = datetime.fromisoformat(s.replace("Z", "+00:00"))
            if dt.tzinfo is None:
                dt = dt.replace(tzinfo=timezone.utc)
            return dt.timestamp()
        except ValueError:
            pass
    return None


def cleanup_table(
    conn: sqlite3.Connection,
    table: str,
    max_age_hours: int,
    dry_run: bool,
) -> dict:
    """Törli a lejárt sorokat egy táblából. Visszatér statisztikával."""
    expiry_col = get_expiry_column(conn, table)
    created_col = get_created_column(conn, table)

    now = datetime.now(timezone.utc)
    cutoff = now - timedelta(hours=max_age_hours)
    cutoff_epoch = cutoff.timestamp()

    cur = conn.cursor()

    if expiry_col:
        # Elsődleges: explicit lejárati oszlop
        # Különbséget tesz epoch és ISO között dinamikusan
        cur.execute(f"SELECT COUNT(*) FROM {table};")
        total = cur.fetchone()[0]

        # Próbáljuk numerikus összehasonlítással (ha epoch)
        try:
            cur.execute(
                f"SELECT COUNT(*) FROM {table} WHERE CAST({expiry_col} AS REAL) < ?;",
                (cutoff_epoch,),
            )
            expired_count = cur.fetchone()[0]
        except sqlite3.OperationalError:
            expired_count = 0

        # Ha 0 jött ki, lehet ISO formátum — szoftveres szűrés
        if expired_count == 0:
            cur.execute(f"SELECT rowid, {expiry_col} FROM {table};")
            expired_rowids = []
            for rowid, val in cur.fetchall():
                ts = normalize_timestamp(val)
                if ts is not None and ts < cutoff_epoch:
                    expired_rowids.append(rowid)
            expired_count = len(expired_rowids)
            if not dry_run and expired_rowids:
                placeholders = ",".join("?" * len(expired_rowids))
                cur.execute(
                    f"DELETE FROM {table} WHERE rowid IN ({placeholders});",
                    expired_rowids,
                )
        else:
            if not dry_run:
                cur.execute(
                    f"DELETE FROM {table} WHERE CAST({expiry_col} AS REAL) < ?;",
                    (cutoff_epoch,),
                )

    elif created_col:
        # Nincs explicit lejárat — created_at + max_age alapján
        cur.execute(f"SELECT COUNT(*) FROM {table};")
        total = cur.fetchone()[0]

        try:
            cur.execute(
                f"SELECT COUNT(*) FROM {table} WHERE CAST({created_col} AS REAL) < ?;",
                (cutoff_epoch,),
            )
            expired_count = cur.fetchone()[0]
        except sqlite3.OperationalError:
            expired_count = 0

        if expired_count == 0:
            cur.execute(f"SELECT rowid, {created_col} FROM {table};")
            expired_rowids = []
            for rowid, val in cur.fetchall():
                ts = normalize_timestamp(val)
                if ts is not None and ts < cutoff_epoch:
                    expired_rowids.append(rowid)
            expired_count = len(expired_rowids)
            if not dry_run and expired_rowids:
                placeholders = ",".join("?" * len(expired_rowids))
                cur.execute(
                    f"DELETE FROM {table} WHERE rowid IN ({placeholders});",
                    expired_rowids,
                )
        else:
            if not dry_run:
                cur.execute(
                    f"DELETE FROM {table} WHERE CAST({created_col} AS REAL) < ?;",
                    (cutoff_epoch,),
                )
    else:
        return {"table": table, "skipped": True, "total": 0, "deleted": 0}

    if not dry_run:
        conn.commit()

    cur.execute(f"SELECT COUNT(*) FROM {table};")
    remaining = cur.fetchone()[0]

    return {
        "table": table,
        "skipped": False,
        "total_before": total,
        "deleted": expired_count if not dry_run else 0,
        "would_delete": expired_count if dry_run else 0,
        "remaining": remaining,
        "dry_run": dry_run,
    }


def vacuum_if_needed(conn: sqlite3.Connection, threshold_bytes: int = 1_000_000):
    """VACUUM ha a DB elég nagy és sok sor lett törölve."""
    cur = conn.cursor()
    cur.execute("PRAGMA page_count;")
    pages = cur.fetchone()[0]
    cur.execute("PRAGMA page_size;")
    page_size = cur.fetchone()[0]
    db_size = pages * page_size
    if db_size > threshold_bytes:
        try:
            conn.execute("VACUUM;")
            return True
        except sqlite3.OperationalError:
            return False
    return False


