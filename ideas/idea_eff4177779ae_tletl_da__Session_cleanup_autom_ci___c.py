def discover_session_tables(conn: sqlite3.Connection) -> list[str]:
    """Visszaadja azokat a táblákat, amik tartalmaznak lejárathoz kapcsolódó oszlopot."""
    cur = conn.cursor()
    cur.execute(
        "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%';"
    )
    tables = [row[0] for row in cur.fetchall()]

    session_tables = []
    for table in tables:
        cur.execute(f"PRAGMA table_info('{table}');")
        cols = {row[1].lower() for row in cur.fetchall()}
        # Keresünk lejárat / timestamp oszlopokat
        has_expiry = any(
            kw in cols
            for kw in ("expires_at", "expires", "expiry", "valid_until", "token_expires")
        )
        has_created = any(kw in cols for kw in ("created_at", "created", "timestamp", "ts"))
        if has_expiry or has_created:
            session_tables.append(table)

    return session_tables


def get_expiry_column(conn: sqlite3.Connection, table: str) -> str | None:
    cur = conn.cursor()
