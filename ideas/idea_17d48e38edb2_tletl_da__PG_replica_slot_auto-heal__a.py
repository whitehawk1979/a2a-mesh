# Core auto-heal logic
# ---------------------------------------------------------------------------

def evaluate_and_heal(
    conn,
    expected: List[Dict[str, Any]],
    dry_run: bool = False,
) -> Tuple[List[HealAction], Dict[str, Dict[str, Any]], List[SlotInfo]]:
    actions: List[HealAction] = []
    wal_validations: Dict[str, Dict[str, Any]] = {}
    existing = list_slots(conn)
    existing_names = {s.slot_name for s in existing}
    current_lsn = current_wal_lsn(conn)

    # 1. Validate WAL for existing slots
    for slot in existing:
        wal_validations[slot.slot_name] = validate_slot_wal(conn, slot, current_lsn)

    # 2. Detect missing slots and auto-create
    for spec in expected:
        name = spec["slot_name"]
        stype = spec.get("slot_type", "logical")
        plugin = spec.get("plugin", "pgoutput")
        database = spec.get("database", "a2a_mesh")

        if name not in existing_names:
            if dry_run:
                actions.append(HealAction(
                    action="create_slot",
                    slot_name=name,
                    reason="missing_slot",
                    details={
                        "slot_type": stype,
                        "plugin": plugin,
                        "database": database,
                        "dry_run": True,
                    },
                ))
                log.info("[DRY-RUN] Would create %s slot '%s'", stype, name)
            else:
                try:
                    if stype == "logical":
                        create_logical_slot(conn, name, plugin, database)
                    else:
                        create_physical_slot(conn, name)
                    actions.append(HealAction(
                        action="create_slot",
                        slot_name=name,
                        reason="missing_slot",
                        details={
                            "slot_type": stype,
                            "plugin": plugin,
                            "database": database,
                            "dry_run": False,
                            "success": True,
                        },
                    ))
                except Exception as exc:
                    log.error("Failed to create slot %s: %s", name, exc)
                    actions.append(HealAction(
                        action="create_slot",
                        slot_name=name,
                        reason="missing_slot",
                        details={
                            "slot_type": stype,
                            "plugin": plugin,
                            "database": database,
                            "dry_run": False,
                            "success": False,
                            "error": str(exc),
                        },
                    ))
        else:
            # Slot exists — check WAL health
            wv = wal_validations.get(name, {})
            if wv.get("wal_lost_risk"):
                # If WAL is lost/unreserved, the slot is effectively broken.
                # Drop and recreate to reset to current LSN.
                if dry_run:
                    actions.append(HealAction(
                        action="drop_recreate",
                        slot_name=name,
                        reason="wal_lost_or_unreserved",
                        details={"wal_status": wv.get("wal_status"), "dry_run": True},
                    ))
                    log.info("[DRY-RUN] Would drop+recreate slot '%s' (wal_status=%s)",
                             name, wv.get("wal_status"))
                else:
                    try:
                        drop_slot(conn, name)
                        if stype == "logical":
                            create_logical_slot(conn, name, plugin, database)
                        else:
                            create_physical_slot(conn, name)
                        actions.append(HealAction(
                            action="drop_recreate",
                            slot_name=name,
                            reason="wal_lost_or_unreserved",
                            details={
                                "wal_status": wv.get("wal_status"),
                                "success": True,
                            },
                        ))
                    except Exception as exc:
                        log.error("Failed to drop+recreate slot %s: %s", name, exc)
                        actions.append(HealAction(
                            action="drop_recreate",
                            slot_name=name,
                            reason="wal_lost_or_unreserved",
                            details={
                                "wal_status": wv.get("wal_status"),
                                "success": False,
                                "error": str(exc),
                            },
                        ))
            elif wv.get("status") == "warning" and stype == "logical":
                # Lag is building up but WAL is still reserved.
                # Advance the slot to current LSN to release old WAL.
                if dry_run:
                    actions.append(HealAction(
                        action="advance_slot",
                        slot_name=name,
                        reason="wal_lag_warning",
                        details={
                            "lag_mb": wv.get("lag_mb"),
                            "target_lsn": current_lsn,
                            "dry_run": True,
                        },
                    ))
                    log.info("[DRY-RUN] Would advance slot '%s' to %s (lag=%.1fMB)",
                             name, current_lsn, wv.get("lag_mb", 0))
                else:
                    try:
                        advance_logical_slot(conn, name, current_lsn)
                        actions.append(HealAction(
                            action="advance_slot",
                            slot_name=name,
                            reason="wal_lag_warning",
                            details={
                                "lag_mb": wv.get("lag_mb"),
                                "target_lsn": current_lsn,
                                "success": True,
                            },
                        ))
                    except Exception as exc:
                        log.error("Failed to advance slot %s: %s", name, exc)
                        actions.append(HealAction(
                            action="advance_slot",
                            slot_name=name,
                            reason="wal_lag_warning",
                            details={
                                "lag_mb": wv.get("lag_mb"),
                                "success": False,
                                "error": str(exc),
                            },
                        ))

    # Re-inspect after heal
    if actions and not dry_run:
        existing = list_slots(conn)
        current_lsn = current_wal_lsn(conn)
        for slot in existing:
            wal_validations[slot.slot_name] = validate_slot_wal(conn, slot, current_lsn)

    return actions, wal_validations, existing


