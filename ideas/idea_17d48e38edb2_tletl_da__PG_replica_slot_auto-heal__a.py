@dataclasses.dataclass
class SlotInfo:
    slot_name: str
    slot_type: str
    active: bool
    database: Optional[str]
    plugin: Optional[str]
    restart_lsn: Optional[str]
    confirmed_flush_lsn: Optional[str]
    wal_status: Optional[str]
    safe_wal_size: Optional[int]
    held: bool

    @classmethod
    def from_row(cls, row: Dict[str, Any]) -> "SlotInfo":
        return cls(
            slot_name=row.get("slot_name", ""),
            slot_type=row.get("slot_type", ""),
            active=bool(row.get("active", False)),
            database=row.get("database"),
            plugin=row.get("plugin"),
            restart_lsn=row.get("restart_lsn"),
            confirmed_flush_lsn=row.get("confirmed_flush_lsn"),
            wal_status=row.get("wal_status"),
            safe_wal_size=row.get("safe_wal_size"),
            held=bool(row.get("held", False)),
        )


@dataclasses.dataclass
class HealAction:
    action: str  # "create_slot" | "advance_slot" | "drop_recreate" | "noop"
    slot_name: str
    reason: str
    details: Dict[str, Any]
    timestamp: str = dataclasses.field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )


@dataclasses.dataclass
class HealReport:
    timestamp: str
    dsn_masked: str
    expected_slots: List[str]
    existing_slots: List[str]
    missing_slots: List[str]
    wal_validations: Dict[str, Dict[str, Any]]
    actions: List[HealAction]
    dry_run: bool
    healthy: bool


