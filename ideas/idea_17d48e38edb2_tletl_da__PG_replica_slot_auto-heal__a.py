def create_logical_slot(conn, slot_name: str, plugin: str, database: str) -> bool:
    """Create a logical replication slot."""
    sql = "SELECT pg_create_logical_replication_slot(%s, %s);"
    with conn.cursor() as cur:
        # Ensure we're on the right database for logical slots
        cur.execute("SELECT current_database();")
        db_row = cur.fetchone()
        current_db = db_row[0] if db_row else ""
        if current_db != database:
            log.warning(
                "Logical slot %s targets db '%s' but connected to '%s'. "
                "Logical slots are database-scoped; creating on current db.",
                slot_name, database, current_db,
            )
        cur.execute(sql, (slot_name, plugin))
        result = cur.fetchone()
    conn.commit()
    log.info("Created logical slot %s (plugin=%s): %s", slot_name, plugin, result)
    return True


def create_physical_slot(conn, slot_name: str) -> bool:
    sql = "SELECT pg_create_physical_replication_slot(%s);"
    with conn.cursor() as cur:
        cur.execute(sql, (slot_name,))
        result = cur.fetchone()
    conn.commit()
    log.info("Created physical slot %s: %s", slot_name, result)
    return True


def drop_slot(conn, slot_name: str) -> bool:
    with conn.cursor() as cur:
        cur.execute("SELECT pg_drop_replication_slot(%s);", (slot_name,))
    conn.commit()
    log.info("Dropped slot %s", slot_name)
    return True


def advance_logical_slot(conn, slot_name: str, target_lsn: str) -> bool:
    """Advance a logical slot's confirmed_flush_lsn to target."""
    with conn.cursor() as cur:
        cur.execute(
            "SELECT pg_replication_slot_advance(%s, %s);",
            (slot_name, target_lsn),
        )
        result = cur.fetchone()
    conn.commit()
    log.info("Advanced slot %s to %s: %s", slot_name, target_lsn, result)
    return True


