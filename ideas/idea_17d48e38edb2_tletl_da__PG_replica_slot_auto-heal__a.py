def notify_mesh_health(report: HealReport) -> None:
    """Best-effort POST to the mesh health endpoint."""
    if not _HAS_REQUESTS:
        log.debug("requests not available; skipping mesh health notification")
        return
    payload = {
        "component": "pg_replica_slot_autoheal",
        "agent": "runa",
        "timestamp": report.timestamp,
        "healthy": report.healthy,
        "missing_slots": report.missing_slots,
        "actions": [dataclasses.asdict(a) for a in report.actions],
        "wal_validations": report.wal_validations,
    }
    try:
        resp = requests.post(MESH_HEALTH_URL, json=payload, timeout=5)
        log.debug("Mesh health notification: %s %s", resp.status_code, resp.text[:200])
    except Exception as exc:
        log.debug("Mesh health notification failed (non-fatal): %s", exc)


