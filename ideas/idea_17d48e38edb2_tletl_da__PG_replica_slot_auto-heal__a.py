def mask_dsn(dsn: str) -> str:
    """Mask password in DSN for safe logging."""
    if "@" in dsn and "://" in dsn:
        try:
            scheme, rest = dsn.split("://", 1)
            creds, hostpart = rest.split("@", 1)
            if ":" in creds:
                user, _pw = creds.split(":", 1)
                return f"{scheme}://{user}:***@{hostpart}"
            return f"{scheme}://{creds}:***@{hostpart}"
        except Exception:
            return "***masked***"
    return dsn


def get_connection(dsn: str):
    if not _HAS_PSYCOPG:
        raise RuntimeError(
            "psycopg2 is not installed. Install with: pip install psycopg2-binary"
        )
    return psycopg2.connect(dsn)


def server_version(conn) -> int:
    with conn.cursor() as cur:
        cur.execute("SHOW server_version_num;")
        row = cur.fetchone()
        return int(row[0]) if row else 0


def is_primary(conn) -> bool:
    """Return True if the connected node is a primary (not in recovery)."""
    with conn.cursor() as cur:
        cur.execute("SELECT pg_is_in_recovery();")
        row = cur.fetchone()
        return not bool(row[0]) if row else True


