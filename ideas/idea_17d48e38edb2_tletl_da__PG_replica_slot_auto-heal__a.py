# WAL validation
# ---------------------------------------------------------------------------

def lsn_to_bytes(lsn: str) -> int:
    """Convert a Postgres LSN like '0/16B3748' to byte offset."""
    if not lsn:
        return 0
    parts = lsn.split("/")
    if len(parts) != 2:
        return 0
    try:
        high = int(parts[0], 16)
        low = int(parts[1], 16)
        return (high << 32) | low
    except ValueError:
        return 0


def current_wal_lsn(conn) -> str:
    with conn.cursor() as cur:
        cur.execute("SELECT pg_current_wal_lsn()::text;")
        row = cur.fetchone()
        return row[0] if row else ""


def wal_lag_mb(current_lsn: str, slot_lsn: str) -> float:
    cur_bytes = lsn_to_bytes(current_lsn)
    slot_bytes = lsn_to_bytes(slot_lsn)
    delta = max(cur_bytes - slot_bytes, 0)
    return round(delta / (1024 * 1024), 2)


def validate_slot_wal(conn, slot: SlotInfo, current_lsn: str) -> Dict[str, Any]:
    """Validate WAL retention and lag for a given slot."""
    ref_lsn = slot.confirmed_flush_lsn or slot.restart_lsn or current_lsn
    lag_mb = wal_lag_mb(current_lsn, ref_lsn)

    status = "ok"
    if lag_mb >= WAL_CRIT_LAG_MB:
        status = "critical"
    elif lag_mb >= WAL_WARN_LAG_MB:
        status = "warning"

    # safe_wal_size is the bytes of WAL reserved for the slot (PG 13+).
    # If it's None or very low, the slot may lose WAL.
    safe_mb: Optional[float] = None
    if slot.safe_wal_size is not None:
        safe_mb = round(slot.safe_wal_size / (1024 * 1024), 2)

    wal_lost_risk = False
    if slot.wal_status in ("lost", "unreserved"):
        wal_lost_risk = True
        status = "critical"
    if safe_mb is not None and safe_mb < WAL_MIN_RETAIN_MB:
        wal_lost_risk = True
        if status != "critical":
            status = "warning"

    return {
        "slot_name": slot.slot_name,
        "current_lsn": current_lsn,
        "slot_lsn": ref_lsn,
        "lag_mb": lag_mb,
        "wal_status": slot.wal_status,
        "safe_wal_size_mb": safe_mb,
        "wal_lost_risk": wal_lost_risk,
        "status": status,
    }


