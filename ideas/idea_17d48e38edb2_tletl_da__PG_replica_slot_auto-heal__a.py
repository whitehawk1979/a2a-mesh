def run(dsn: str, dry_run: bool = False, expected: Optional[List[Dict[str, Any]]] = None) -> HealReport:
    expected = expected or EXPECTED_SLOTS
    ts = datetime.now(timezone.utc).isoformat()

    if not _HAS_PSYCOPG:
        log.error("psycopg2 not installed — cannot connect to PostgreSQL.")
        return HealReport(
            timestamp=ts,
            dsn_masked=mask_dsn(dsn),
            expected_slots=[s["slot_name"] for s in expected],
            existing_slots=[],
            missing_slots=[s["slot_name"] for s in expected],
            wal_validations={},
            actions=[HealAction(
                action="noop",
                slot_name="*",
                reason="psycopg2_missing",
                details={"error": "psycopg2 not installed"},
            )],
            dry_run=dry_run,
            healthy=False,
        )

    conn = None
    try:
        conn = get_connection(dsn)
        conn.autocommit = False

        if not is_primary(conn):
            log.warning("Connected node is in recovery (replica). "
                        "Slot creation should happen on primary. Skipping heal.")
            return HealReport(
                timestamp=ts,
                dsn_masked=mask_dsn(dsn),
                expected_slots=[s["slot_name"] for s in expected],
                existing_slots=[s.slot_name for s in list_slots(conn)],
                missing_slots=[],
                wal_validations={},
                actions=[HealAction(
                    action="noop",
                    slot_name="*",
                    reason="node_in_recovery",
                    details={"message": "Cannot create slots on a replica node"},
                )],
                dry_run=dry_run,
                healthy=True,
            )

        ver = server_version(conn)
        log.info("Connected to primary (PG server_version_num=%s)", ver)

        actions, wal_validations, existing = evaluate_and_heal(conn, expected, dry_run)
        existing_names = {s.slot_name for s in existing}
        missing = [s["slot_name"] for s in expected if s["slot_name"] not in existing_names]

        # Determine overall health
        wal_ok = all(
            v.get("status") in ("ok", "warning") for v in wal_validations.values()
        )
        healthy = len(missing) == 0 and wal_ok

        report = HealReport(
            timestamp=ts,
            dsn_masked=mask_dsn(dsn),
            expected_slots=[s["slot_name"] for s in expected],
            existing_slots=sorted(existing_names),
            missing_slots=missing,
            wal_validations=wal_validations,
            actions=actions,
            dry_run=dry_run,
            healthy=healthy,
        )

        # Persist state
        state = load_state()
        state["runs"].append({
            "timestamp": ts,
            "dry_run": dry_run,
            "healthy": healthy,
            "missing": missing,
            "actions": [dataclasses.asdict(a) for a in actions],
        })
        state["runs"] = state["runs"][-50:]  # keep last 50
        state["last_heal"] = ts
        save_state(state)

        # Best-effort mesh notification
        notify_mesh_health(report)

        return report

    except Exception as exc:
        log.error("Auto-heal run failed: %s", exc)
        return HealReport(
            timestamp=ts,
            dsn_masked=mask_dsn(dsn),
            expected_slots=[s["slot_name"] for s in expected],
            existing_slots=[],
            missing_slots=[s["slot_name"] for s in expected],
            wal_validations={},
            actions=[HealAction(
                action="noop",
                slot_name="*",
                reason="exception",
                details={"error": str(exc)},
            )],
            dry_run=dry_run,
            healthy=False,
        )
    finally:
        if conn is not None:
            try:
                conn.close()
            except Exception:
                pass


def print_report(report: HealReport) -> None:
    print("=" * 72)
    print(f"PG Replica Slot Auto-Heal Report  ({'DRY-RUN' if report.dry_run else 'LIVE'})")
    print("=" * 72)
    print(f"Timestamp:     {report.timestamp}")
    print(f"DSN:           {report.dsn_masked}")
    print(f"Healthy:       {report.healthy}")
    print(f"Expected slots: {report.expected_slots}")
    print(f"Existing slots: {report.existing_slots}")
    print(f"Missing slots:  {report.missing_slots}")
    print("-" * 72)
    print("WAL Validations:")
    if not report.wal_validations:
        print("  (none)")
    for name, v in sorted(report.wal_validations.items()):
        print(f"  {name:20s} status={v.get('status'):8s} "
              f"lag={v.get('lag_mb')}MB  wal_status={v.get('wal_status')}  "
              f"safe={v.get('safe_wal_size_mb')}MB  risk={v.get('wal_lost_risk')}")
    print("-" * 72)
    print("Actions:")
    if not report.actions:
        print("  (no actions needed)")
    for a in report.actions:
        ok = a.details.get("success", True)
        tag = "OK" if ok else "FAIL"
        print(f"  [{tag}] {a.action:14s} {a.slot_name:20s} reason={a.reason}")
        if a.details.get("error"):
            print(f"         error: {a.details['error']}")
    print("=" * 72)


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description="PG replica slot auto-heal for A2A Mesh (runa agent)"
    )
    parser.add_argument(
        "--dsn",
        default=None,
        help=f"PostgreSQL DSN. Defaults to ${DEFAULT_DSN_ENV} or {DEFAULT_DSN_FALLBACK}",
    )
    parser.add_argument("--dry-run", action="store_true", help="Evaluate only, no changes")
    parser.add_argument("--json", action="store_true", help="Output report as JSON")
    parser.add_argument("--once", action="store_true", help="Run once and exit (default)")
    parser.add_argument(
        "--interval",
        type=int,
        default=0,
        help="Run every N seconds (0 = once)",
    )
    parser.add_argument("--verbose", "-v", action="store_true", help="Debug logging")
    args = parser.parse_args(argv)

    if args.verbose:
        logging.getLogger().setLevel(logging.DEBUG)

    dsn = args.dsn or os.environ.get(DEFAULT_DSN_ENV) or DEFAULT_DSN_FALLBACK

    def _do_run() -> int:
        report = run(dsn, dry_run=args.dry_run)
        if args.json:
            print(json.dumps(dataclasses.asdict(report), indent=2, default=str))
        else:
            print_report(report)
        return 0 if report.healthy else 1

    if args.interval and args.interval > 0:
        log.info("Starting continuous mode: every %ds", args.interval)
        rc = 0
        while True:
            try:
                rc = _do_run()
            except KeyboardInterrupt:
                log.info("Interrupted, exiting.")
                break
            time.sleep(args.interval)
        return rc
    else:
        return _do_run()


