def demo_create_task_with_validation():
    """Task létrehozás azonnali validációval."""
    print("=" * 70)
    print("DEMO 3: Task létrehozás pre-validációval")
    print("=" * 70)

    validator = DAGPreValidator()

    # Első task — nincs függőség
    task1, result1 = validator.create_task(
        name="Gyökér task",
        agent="root_agent",
        estimated_duration=5.0,
    )
    print(f"Létrehozva: {task1.task_id} ({task1.name})")
    print(result1.summary())
    print()

    # Második task — függ az elsőtől
    task2, result2 = validator.create_task(
        name="Függő task",
        agent="worker_agent",
        dependencies=[task1.task_id],
        estimated_duration=3.0,
    )
    print(f"Létrehozva: {task2.task_id} ({task2.name})")
    print(result2.summary())
    print()

    # Harmadik task — megpróbál ciklust létrehozni
    task3, result3 = validator.create_task(
        name="Ciklikus task",
        agent="bad_agent",
        dependencies=[task2.task_id, task1.task_id],  # task1 -> task2 -> task3 -> task1?
        estimated_duration=1.0,
    )
    # Most hozzáadjuk task1 függőségét task3-hoz, hogy ciklust okozzon
    validator.tasks[task1.task_id].dependencies.append(task3.task_id)
    result_cycle = validator.validate()
    print(f"Létrehozva: {task3.task_id} ({task3.name}) — státusz: {task3.status.value}")
    print(result_cycle.summary())
    print()
    return result3


