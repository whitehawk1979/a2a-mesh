# DAG Pre-Validator
# ---------------------------------------------------------------------------

class DAGPreValidator:
    """
    DAG pre-validáció task-létrehozáskor.

    Funkciók:
      1. Ciklusdetektálás — mélységi bejárással (DFS) + Tarjan algoritmus
         erősen összefüggő komponensek (SCC) keresésére.
      2. Kritikus út számítás — topológiai rendezés + leghosszabb út
         dinamikus programozással.
      3. Hiányzó függőségek detektálása.
      4. Izolált taskok figyelmeztetése.
    """

    def __init__(self):
        self.tasks: Dict[str, Task] = {}

    # --- Task kezelés ---

    def add_task(self, task: Task) -> None:
        """Task hozzáadása a DAG-hoz (még validálás nélkül)."""
        if task.task_id in self.tasks:
            raise ValueError(f"Task '{task.task_id}' már létezik")
        self.tasks[task.task_id] = task

    def create_task(
        self,
        name: str,
        agent: str,
        dependencies: Optional[List[str]] = None,
        estimated_duration: float = 1.0,
        metadata: Optional[Dict] = None,
    ) -> Tuple[Task, ValidationResult]:
        """
        Új task létrehozása azonnali pre-validációval.

        Visszaadja a létrehozott taskot és a validációs eredményt.
        Ha a DAG érvénytelen (ciklust okoz), a task 'blocked' státuszba kerül.
        """
        task_id = f"task_{uuid.uuid4().hex[:12]}"
        deps = dependencies or []
        task = Task(
            task_id=task_id,
            name=name,
            agent=agent,
            estimated_duration=estimated_duration,
            dependencies=deps,
            metadata=metadata or {},
        )

        # Pre-validáció: még nem adjuk hozzá véglegesen, csak ideiglenesen
        self.tasks[task_id] = task
        result = self.validate()

        if not result.is_valid:
            task.status = TaskStatus.BLOCKED
            # Ha ciklust okoz, eltávolítjuk a DAG-ból
            cycles_involving_new = [
                c for c in result.cycles if task_id in c
            ]
            if cycles_involving_new:
                del self.tasks[task_id]
                result.errors.append(
                    f"Task '{task_id}' ({name}) ciklust okozna — létrehozás megtagadva."
                )
                result.is_valid = False
                return task, result

        return task, result

    # --- Validáció ---

    def validate(self) -> ValidationResult:
        """Teljes DAG validáció: ciklusdetektálás + kritikus út + topológiai sorrend."""
        result = ValidationResult()

        # 1. Hiányzó függőségek ellenőrzése
        self._check_missing_dependencies(result)

        # 2. Ciklusdetektálás (Tarjan SCC)
        cycles = self._detect_cycles_tarjan()
        result.cycles = cycles
        if cycles:
            result.is_valid = False
            for cycle in cycles:
                result.errors.append(
                    f"Ciklus detektálva: {' -> '.join(cycle)} -> {cycle[0]}"
                )
            # Ha van ciklus, a kritikus út nem számolható megbízhatóan
            return result

        # 3. Topológiai rendezés (Kahn algoritmus)
        topo_order = self._topological_sort_kahn()
        if topo_order is None:
            # Ez nem fordulhat elő, ha a ciklusdetektálás nem talált ciklust,
            # de biztonsági ellenőrzésként itt hagyjuk.
            result.is_valid = False
            result.errors.append("Topológiai rendezés sikertelen (váratlan ciklus).")
            return result
        result.topological_order = topo_order

        # 4. Kritikus út számítás
        critical_path, duration = self._compute_critical_path(topo_order)
        result.critical_path = critical_path
        result.critical_path_duration = duration

        # 5. Figyelmeztetések
        self._check_warnings(result)

        result.is_valid = len(result.errors) == 0
        return result

    # --- Belső metódusok ---

    def _check_missing_dependencies(self, result: ValidationResult) -> None:
        """Ellenőrzi, hogy minden függőség létezik-e a DAG-ban."""
        for task_id, task in self.tasks.items():
            for dep in task.dependencies:
                if dep not in self.tasks:
                    result.errors.append(
                        f"Task '{task_id}' hiányzó függőségre hivatkozik: '{dep}'"
                    )

    def _build_adjacency(self) -> Dict[str, List[str]]:
        """Épít egy szomszédsági listát (task -> függőségek = kimenő élek)."""
        adj: Dict[str, List[str]] = {}
        for task_id, task in self.tasks.items():
            adj[task_id] = list(task.dependencies)
        return adj

    def _build_reverse_adjacency(self) -> Dict[str, List[str]]:
        """Épít egy fordított szomszédsági listát (task -> tőle függő taskok)."""
        rev: Dict[str, List[str]] = defaultdict(list)
        for task_id, task in self.tasks.items():
            for dep in task.dependencies:
                rev[dep].append(task_id)
        return dict(rev)

    def _detect_cycles_tarjan(self) -> List[List[str]]:
        """
        Tarjan algoritmus erősen összefüggő komponensek (SCC) keresésére.
        Egy SCC, amely egynél több node-ot tartalmaz = ciklus.
        Egyetlen node, amely önmagára mutat = szintén ciklus (bár a Task
        konstruktor ezt kizárja).
        """
        adj = self._build_adjacency()
        nodes = list(self.tasks.keys())

        index_counter = [0]
        stack: List[str] = []
        lowlink: Dict[str, int] = {}
        index: Dict[str, int] = {}
        on_stack: Dict[str, bool] = {}
        sccs: List[List[str]] = []

        def strongconnect(v: str):
            index[v] = index_counter[0]
            lowlink[v] = index_counter[0]
            index_counter[0] += 1
            stack.append(v)
            on_stack[v] = True

            for w in adj.get(v, []):
                if w not in self.tasks:
                    continue  # hiányzó függőség, máshol kezeljük
                if w not in index:
                    strongconnect(w)
                    lowlink[v] = min(lowlink[v], lowlink[w])
                elif on_stack.get(w, False):
                    lowlink[v] = min(lowlink[v], index[w])

            if lowlink[v] == index[v]:
                scc: List[str] = []
                while True:
                    w = stack.pop()
                    on_stack[w] = False
                    scc.append(w)
                    if w == v:
                        break
                sccs.append(scc)

        for node in nodes:
            if node not in index:
                strongconnect(node)

        # Ciklusok = egynél több elemű SCC-k
        cycles: List[List[str]] = []
        for scc in sccs:
            if len(scc) > 1:
                # Rendezzük úgy, hogy a ciklus olvasható legyen
                cycles.append(self._order_cycle(scc, adj))
            elif len(scc) == 1:
                # Önhurok ellenőrzése
                node = scc[0]
                if node in adj.get(node, []):
                    cycles.append([node])

        return cycles

    def _order_cycle(self, scc: List[str], adj: Dict[str, List[str]]) -> List[str]:
        """Rendezi az SCC elemeit úgy, hogy a ciklus sorrendje olvasható legyen."""
        scc_set = set(scc)
        start = scc[0]
        ordered: List[str] = []
        visited: Set[str] = set()
        current = start

        while current not in visited:
            visited.add(current)
            ordered.append(current)
            # Keressük a következő node-ot az SCC-n belül
            next_node = None
            for dep in adj.get(current, []):
                if dep in scc_set and dep not in visited:
                    next_node = dep
                    break
            if next_node is None:
                break
            current = next_node

        # Ha nem mindenkit jártunk be, hozzáadjuk a maradékot
        for node in scc:
            if node not in visited:
                ordered.append(node)

        return ordered

    def _topological_sort_kahn(self) -> Optional[List[str]]:
        """
        Kahn algoritmus topológiai rendezésre.
        Visszatér None-nal, ha ciklus van (bár a Tarjan már detektálja).
        """
        adj = self._build_adjacency()
        rev = self._build_reverse_adjacency()

        # In-degree számítás: hány függősége van (bejövő élek a függőség irányában)
        in_degree: Dict[str, int] = {}
        for task_id in self.tasks:
            in_degree[task_id] = len([
                d for d in self.tasks[task_id].dependencies if d in self.tasks
            ])

        queue: deque = deque()
        for task_id, deg in in_degree.items():
            if deg == 0:
                queue.append(task_id)

        order: List[str] = []
        while queue:
            node = queue.popleft()
            order.append(node)
            # Minden task, amely függ ettől a node-tól
            for dependent in rev.get(node, []):
                in_degree[dependent] -= 1
                if in_degree[dependent] == 0:
                    queue.append(dependent)

        if len(order) != len(self.tasks):
            return None  # ciklus

        return order

    def _compute_critical_path(
        self, topo_order: List[str]
    ) -> Tuple[List[str], float]:
        """
        Kritikus út számítás: leghosszabb út a DAG-ban,
        a taskok becsült idejével súlyozva.

        Dinamikus programozás topológiai sorrendben.
        """
        rev = self._build_reverse_adjacency()

        # earliest_finish[task] = max(earliest_finish[dep]) + task.duration
        # ahol dep a task függőségei
        earliest_finish: Dict[str, float] = {}
        predecessor: Dict[str, Optional[str]] = {}

        for task_id in topo_order:
            task = self.tasks[task_id]
            max_dep_finish = 0.0
            best_pred = None
            for dep in task.dependencies:
                if dep not in self.tasks:
                    continue
                if earliest_finish.get(dep, 0.0) > max_dep_finish:
                    max_dep_finish = earliest_finish[dep]
                    best_pred = dep
            earliest_finish[task_id] = max_dep_finish + task.estimated_duration
            predecessor[task_id] = best_pred

        # A kritikus út vége = a legnagyobb earliest_finish-ű task
        if not earliest_finish:
            return [], 0.0

        end_node = max(earliest_finish, key=lambda k: earliest_finish[k])
        total_duration = earliest_finish[end_node]

        # Visszakövetés
        path: List[str] = []
        current: Optional[str] = end_node
        while current is not None:
            path.append(current)
            current = predecessor.get(current)
        path.reverse()

        return path, total_duration

    def _check_warnings(self, result: ValidationResult) -> None:
        """Különböző figyelmeztetések generálása."""
        # Izolált taskok (nincs bejövő sem kimenő él)
        rev = self._build_reverse_adjacency()
        for task_id, task in self.tasks.items():
            has_deps = len([d for d in task.dependencies if d in self.tasks]) > 0
            has_dependents = len(rev.get(task_id, [])) > 0
            if not has_deps and not has_dependents and len(self.tasks) > 1:
                result.warnings.append(
                    f"Task '{task_id}' ({task.name}) izolált — nincs függősége "
                    f"és senki nem függ tőle."
                )

        # Nagyon hosszú kritikus út figyelmeztetés
        if result.critical_path_duration > 100.0:
            result.warnings.append(
                f"A kritikus út nagyon hosszú ({result.critical_path_duration:.1f}s) — "
                f"érdemes lehet párhuzamosítani."
            )

        # Túl sok függőség egyetlen taskon
        for task_id, task in self.tasks.items():
            real_deps = [d for d in task.dependencies if d in self.tasks]
            if len(real_deps) > 10:
                result.warnings.append(
                    f"Task '{task_id}' ({task.name}) túl sok függőséggel rendelkezik "
                    f"({len(real_deps)}) — lehetséges szűk keresztmetszet."
                )

    # --- Lekérdezések ---

    def get_ready_tasks(self) -> List[str]:
        """Visszaadja azokat a taskokat, amelyek minden függősége teljesült."""
        ready = []
        for task_id, task in self.tasks.items():
            if task.status != TaskStatus.PENDING:
                continue
            if all(
                self.tasks[dep].status == TaskStatus.COMPLETED
                for dep in task.dependencies
                if dep in self.tasks
            ):
                ready.append(task_id)
        return ready

    def to_dict(self) -> dict:
        return {
            tid: {
                "task_id": t.task_id,
                "name": t.name,
                "agent": t.agent,
                "estimated_duration": t.estimated_duration,
                "dependencies": t.dependencies,
                "status": t.status.value,
                "metadata": t.metadata,
            }
            for tid, t in self.tasks.items()
        }


