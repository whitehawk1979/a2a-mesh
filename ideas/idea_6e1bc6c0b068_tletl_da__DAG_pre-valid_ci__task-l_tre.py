# ---------------------------------------------------------------------------
# Adatmodell
# ---------------------------------------------------------------------------

class TaskStatus(str, Enum):
    PENDING = "pending"
    READY = "ready"
    RUNNING = "running"
    COMPLETED = "completed"
    FAILED = "failed"
    BLOCKED = "blocked"  # ciklus miatt blokkolt


@dataclass
class Task:
    """Egy A2A Mesh task a DAG-ban."""
    task_id: str
    name: str
    agent: str
    estimated_duration: float = 1.0  # másodpercben (kritikus úthoz)
    dependencies: List[str] = field(default_factory=list)
    status: TaskStatus = TaskStatus.PENDING
    metadata: Dict = field(default_factory=dict)

    def __post_init__(self):
        # Önmagától való függőség kizárása
        if self.task_id in self.dependencies:
            raise ValueError(
                f"Task '{self.task_id}' nem függhet önmagától: {self.dependencies}"
            )
        # Duplikációk eltávolítása
        self.dependencies = list(dict.fromkeys(self.dependencies))


@dataclass
class ValidationResult:
    """A DAG pre-validáció eredménye."""
    is_valid: bool
    cycles: List[List[str]] = field(default_factory=list)
    critical_path: List[str] = field(default_factory=list)
    critical_path_duration: float = 0.0
    topological_order: List[str] = field(default_factory=list)
    warnings: List[str] = field(default_factory=list)
    errors: List[str] = field(default_factory=list)

    def to_dict(self) -> dict:
        return {
            "is_valid": self.is_valid,
            "cycles": self.cycles,
            "critical_path": self.critical_path,
            "critical_path_duration": self.critical_path_duration,
            "topological_order": self.topological_order,
            "warnings": self.warnings,
            "errors": self.errors,
        }

    def summary(self) -> str:
        lines = []
        lines.append(f"  Érvényes DAG: {'IGEN' if self.is_valid else 'NEM'}")
        if self.cycles:
            lines.append(f"  Ciklusok ({len(self.cycles)}):")
            for c in self.cycles:
                lines.append(f"    -> {' -> '.join(c)} -> {c[0]}")
        if self.critical_path:
            lines.append(f"  Kritikus út: {' -> '.join(self.critical_path)}")
            lines.append(f"  Kritikus út hossza: {self.critical_path_duration:.2f}s")
        if self.topological_order:
            lines.append(f"  Topológiai sorrend: {', '.join(self.topological_order)}")
        if self.warnings:
            lines.append(f"  Figyelmeztetések ({len(self.warnings)}):")
            for w in self.warnings:
                lines.append(f"    ! {w}")
        if self.errors:
            lines.append(f"  Hibák ({len(self.errors)}):")
            for e in self.errors:
                lines.append(f"    X {e}")
        return "\n".join(lines)


