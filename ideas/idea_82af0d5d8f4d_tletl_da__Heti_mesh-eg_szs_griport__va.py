def get_last_week_trend(conn, node_name: str) -> dict:
    """Get last week's report for comparison."""
    cur = conn.cursor()
    cur.execute("""
        SELECT mem_used_pct, swap_used_pct, disk_used_pct, pg_repl_lag_sec,
               offline_queue_depth, heartbeat_misses
        FROM mesh_health_reports
        WHERE node_name = %s
          AND report_time < NOW() - INTERVAL '6 days'
        ORDER BY report_time DESC
        LIMIT 1
    """, (node_name,))
    row = cur.fetchone()
    cur.close()
    if not row:
        return {}
    return {
        "mem_used_pct": row[0],
        "swap_used_pct": row[1],
        "disk_used_pct": row[2],
        "pg_repl_lag_sec": row[3],
        "offline_queue_depth": row[4],
        "heartbeat_misses": row[5],
    }


def format_trend(current: float, previous: float, unit: str = "") -> str:
    """Format a trend indicator."""
    if current is None or previous is None:
        return ""
    diff = current - previous
    if abs(diff) < 0.1:
        return "→"
    elif diff > 0:
        return f"↑{diff:.1f}{unit}"
    else:
        return f"↓{abs(diff):.1f}{unit}"


