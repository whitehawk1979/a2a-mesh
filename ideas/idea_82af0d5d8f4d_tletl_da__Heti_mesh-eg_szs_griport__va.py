def store_json_fallback(all_states: list, all_alerts: list):
    """Store report as JSON file when PostgreSQL is unavailable."""
    fallback_dir = REPO_ROOT / "data" / "health_reports"
    fallback_dir.mkdir(parents=True, exist_ok=True)
