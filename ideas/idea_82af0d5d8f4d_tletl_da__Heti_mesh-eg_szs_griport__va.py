def collect_memory_swap(host: str) -> dict:
    """Collect memory and swap usage percentages."""
    output = _run(host, "free -b")
    if not output:
        return {"mem_used_pct": None, "swap_used_pct": None, "mem_total_mb": None,
                "mem_used_mb": None, "swap_total_mb": None, "swap_used_mb": None}

    lines = output.splitlines()
    mem_total = mem_used = swap_total = swap_used = 0
    try:
        for line in lines:
            parts = line.split()
            if len(parts) < 2:
                continue
            if parts[0] == "Mem:" and len(parts) >= 3:
                mem_total = int(parts[1])
                mem_used = int(parts[2])
            elif parts[0] == "Swap:" and len(parts) >= 3:
                swap_total = int(parts[1])
                swap_used = int(parts[2])

        mem_pct = round((mem_used / mem_total * 100), 1) if mem_total > 0 else 0
        swap_pct = round((swap_used / swap_total * 100), 1) if swap_total > 0 else 0

        return {
            "mem_used_pct": mem_pct,
            "swap_used_pct": swap_pct,
            "mem_total_mb": round(mem_total / 1048576),
            "mem_used_mb": round(mem_used / 1048576),
            "swap_total_mb": round(swap_total / 1048576),
            "swap_used_mb": round(swap_used / 1048576),
        }
    except (ValueError, IndexError) as e:
        log.warning("Failed to parse free output on %s: %s", host, e)
        return {"mem_used_pct": None, "swap_used_pct": None, "mem_total_mb": None,
                "mem_used_mb": None, "swap_total_mb": None, "swap_used_mb": None}


def collect_disk(host: str) -> dict:
    """Collect disk usage for root filesystem."""
    output = _run(host, "df -B1 /")
    if not output:
        return {"disk_used_pct": None, "disk_total_gb": None, "disk_used_gb": None,
                "disk_free_gb": None}

    lines = output.strip().splitlines()
    if len(lines) < 2:
        return {"disk_used_pct": None, "disk_total_gb": None, "disk_used_gb": None,
                "disk_free_gb": None}

    try:
        parts = lines[1].split()
        total = int(parts[1])
        used = int(parts[2])
        pct_str = parts[4].rstrip("%")
        pct = float(pct_str)

        return {
            "disk_used_pct": pct,
            "disk_total_gb": round(total / 1073741824, 1),
            "disk_used_gb": round(used / 1073741824, 1),
            "disk_free_gb": round((total - used) / 1073741824, 1),
        }
    except (ValueError, IndexError) as e:
        log.warning("Failed to parse df output on %s: %s", host, e)
        return {"disk_used_pct": None, "disk_total_gb": None, "disk_used_gb": None,
                "disk_free_gb": None}


def collect_pg_replication_lag(host: str, pg_port: int) -> dict:
    """Collect PostgreSQL replication lag."""
    # Try to get replication lag via psql on the remote host
    sql = (
        "SELECT COALESCE("
        "  EXTRACT(EPOCH FROM (now() - pg_last_xact_replay_timestamp())), 0"
        ") AS lag_sec, "
        "COALESCE(pg_wal_lsn_diff(pg_current_wal_lsn(), pg_last_wal_replay_lsn()) / 1048576.0, 0) AS lag_mb, "
        "CASE WHEN pg_is_in_recovery() THEN 'standby' ELSE 'primary' END AS role;"
    )
    psql_cmd = f"psql -p {pg_port} -U {PG_CONFIG['user']} -d {PG_CONFIG['dbname']} -t -A -c \"{sql}\""
    output = _run(host, psql_cmd)

    if not output:
        return {"pg_repl_lag_sec": None, "pg_repl_lag_mb": None, "pg_role": "unknown"}

    try:
        parts = output.split("|")
        lag_sec = float(parts[0]) if parts[0] else 0.0
        lag_mb = float(parts[1]) if parts[1] else 0.0
        role = parts[2].strip() if len(parts) > 2 else "unknown"
        return {
            "pg_repl_lag_sec": round(lag_sec, 1),
            "pg_repl_lag_mb": round(lag_mb, 1),
            "pg_role": role,
        }
    except (ValueError, IndexError) as e:
        log.warning("Failed to parse PG replication output on %s: %s", host, e)
        return {"pg_repl_lag_sec": None, "pg_repl_lag_mb": None, "pg_role": "unknown"}


def collect_offline_queue(host: str) -> dict:
    """Count files in the offline queue directory."""
    # Use find to count files (works locally and remotely)
    cmd = f"find {OFFLINE_QUEUE_DIR} -type f 2>/dev/null | wc -l"
    output = _run(host, cmd)
    try:
        count = int(output.strip()) if output.strip() else 0
    except ValueError:
        count = 0
    return {"offline_queue_depth": count}


def collect_heartbeat_misses(host: str) -> dict:
    """Count heartbeat misses in the last hour from the heartbeat log."""
    # Look for lines with 'MISS' or 'TIMEOUT' in the last hour
    cmd = (
        f"awk -v cutoff=$(date -d '1 hour ago' '+%Y-%m-%dT%H:%M:%S') "
        f"'{{if ($0 ~ /MISS|TIMEOUT|FAIL/ && $1 >= cutoff) count++}} END {{print count+0}}' "
        f"{HEARTBEAT_LOG} 2>/dev/null"
    )
    output = _run(host, cmd)
    try:
        misses = int(output.strip()) if output.strip() else 0
    except ValueError:
        misses = 0
    return {"heartbeat_misses": misses}


