def _ssh_run(host: str, command: str, timeout: int = 30) -> str:
    """Run a command on a remote host via SSH. Returns stdout or empty string on failure."""
    ssh_cmd = [
        "ssh", "-i", SSH_KEY,
        "-p", str(SSH_PORT),
        "-o", "StrictHostKeyChecking=no",
        "-o", "ConnectTimeout=10",
        "-o", "BatchMode=yes",
        f"{SSH_USER}@{host}",
        command,
    ]
    try:
        result = subprocess.run(
            ssh_cmd, capture_output=True, text=True, timeout=timeout
        )
        if result.returncode != 0:
            log.warning("SSH command failed on %s: %s", host, result.stderr.strip())
            return ""
        return result.stdout.strip()
    except subprocess.TimeoutExpired:
        log.warning("SSH timeout on %s", host)
        return ""
    except FileNotFoundError:
        log.warning("ssh not available, skipping remote collection on %s", host)
        return ""
    except Exception as e:
        log.warning("SSH error on %s: %s", host, e)
        return ""


def _local_run(command: str, timeout: int = 30) -> str:
    """Run a command locally."""
    try:
        result = subprocess.run(
            command, shell=True, capture_output=True, text=True, timeout=timeout
        )
        return result.stdout.strip() if result.returncode == 0 else ""
    except Exception as e:
        log.warning("Local command failed '%s': %s", command, e)
        return ""


def _is_local(host: str) -> bool:
    """Check if a host refers to the local machine."""
    try:
        resolved = socket.gethostbyname(host)
        local_ips = {"127.0.0.1", "0.0.0.0", "::1"}
        try:
            local_ips.add(socket.gethostbyname(socket.gethostname()))
        except Exception:
            pass
        return resolved in local_ips or host in ("localhost", "127.0.0.1")
    except socket.gaierror:
        return False


def _run(host: str, command: str) -> str:
    """Run command on host (local or remote)."""
    if _is_local(host):
        return _local_run(command)
    return _ssh_run(host, command)


