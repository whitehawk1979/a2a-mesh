def check_thresholds(state: dict) -> list:
    """Check a node's state against thresholds. Returns list of alert messages."""
    alerts = []
    name = state["node_name"]

    if not state.get("reachable", True):
        alerts.append(f"🔴 {name}: NODE UNREACHABLE")
        return alerts

    mem = state.get("mem_used_pct")
    if mem is not None and mem > THRESHOLDS["mem_used_pct"]:
        alerts.append(f"🟠 {name}: memory {mem}% > {THRESHOLDS['mem_used_pct']}%")

    swap = state.get("swap_used_pct")
    if swap is not None and swap > THRESHOLDS["swap_used_pct"]:
        alerts.append(f"🟠 {name}: swap {swap}% > {THRESHOLDS['swap_used_pct']}%")

    disk = state.get("disk_used_pct")
    if disk is not None and disk > THRESHOLDS["disk_used_pct"]:
        alerts.append(f"🟠 {name}: disk {disk}% > {THRESHOLDS['disk_used_pct']}%")

    lag_sec = state.get("pg_repl_lag_sec")
    if lag_sec is not None and lag_sec > THRESHOLDS["pg_repl_lag_sec"]:
        alerts.append(f"🟠 {name}: PG repl lag {lag_sec}s > {THRESHOLDS['pg_repl_lag_sec']}s")

    lag_mb = state.get("pg_repl_lag_mb")
    if lag_mb is not None and lag_mb > THRESHOLDS["pg_repl_lag_mb"]:
        alerts.append(f"🟠 {name}: PG repl lag {lag_mb}MB > {THRESHOLDS['pg_repl_lag_mb']}MB")

    queue = state.get("offline_queue_depth")
    if queue is not None and queue > THRESHOLDS["offline_queue"]:
        alerts.append(f"🟠 {name}: offline queue {queue} > {THRESHOLDS['offline_queue']}")

    hb = state.get("heartbeat_misses")
    if hb is not None and hb > THRESHOLDS["heartbeat_misses"]:
        alerts.append(f"🟠 {name}: heartbeat misses {hb} > {THRESHOLDS['heartbeat_misses']}")

    return alerts


