    filepath = fallback_dir / f"health_report_{ts}.json"
    report = {
        "report_time": datetime.now(timezone.utc).isoformat(),
        "nodes": all_states,
        "alerts": all_alerts,
        "thresholds": THRESHOLDS,
    }
