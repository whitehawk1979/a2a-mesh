def generate_report(nodes: list, dry_run: bool = False) -> dict:
    """Generate the weekly health report for all nodes."""
    log.info("=" * 60)
    log.info("Starting weekly mesh health report")
    log.info("Timestamp: %s", datetime.now(timezone.utc).isoformat())
    log.info("Nodes: %s", [n["name"] for n in nodes])
    log.info("=" * 60)

    all_states = []
    all_alerts = []

    # Collect metrics from all nodes
    for node in nodes:
        state = collect_node_state(node)
        alerts = check_thresholds(state)
        all_states.append(state)
        all_alerts.extend(alerts)

    # Try to store in PostgreSQL
    pg_available = False
    conn = None
    if not dry_run:
        try:
            import psycopg2
            conn = psycopg2.connect(**PG_CONFIG)
            ensure_schema(conn)
            for i, state in enumerate(all_states):
                # Find alerts for this node
                node_alerts = [a for a in all_alerts if a.startswith(("🔴", "🟠")) and state["node_name"] in a]
                store_report(conn, state, node_alerts)
            pg_available = True
            log.info("Reports stored in PostgreSQL successfully")
        except ImportError:
            log.warning("psycopg2 not installed, using JSON fallback")
        except Exception as e:
            log.error("PostgreSQL storage failed: %s", e)

    # JSON fallback
    if not pg_available and not dry_run:
        store_json_fallback(all_states, all_alerts)

    # Trend analysis
    trends = {}
    if conn:
        for state in all_states:
            trends[state["node_name"]] = get_last_week_trend(conn, state["node_name"])

    # Build summary
    summary_lines = [
        f"<b>🏥 A2A Mesh Heti Egészségriport</b>",
        f"📅 {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}",
        "",
    ]

    for state in all_states:
        name = state["node_name"]
        trend = trends.get(name, {})
        status = "✅" if not any(name in a for a in all_alerts) else "⚠️"

        summary_lines.append(f"<b>{status} {name}</b> ({state['host']})")

        if not state.get("reachable", True):
            summary_lines.append("  🔴 UNREACHABLE")
            summary_lines.append("")
            continue

        mem = state.get("mem_used_pct")
        mem_t = format_trend(mem, trend.get("mem_used_pct"), "%") if trend else ""
        summary_lines.append(f"  RAM: {mem}% {mem_t}" if mem is not None else "  RAM: N/A")

        swap = state.get("swap_used_pct")
        summary_lines.append(f"  Swap: {swap}%" if swap is not None else "  Swap: N/A")

        disk = state.get("disk_used_pct")
        disk_t = format_trend(disk, trend.get("disk_used_pct"), "%") if trend else ""
        summary_lines.append(f"  Disk: {disk}% {disk_t}" if disk is not None else "  Disk: N/A")

        lag = state.get("pg_repl_lag_sec")
        role = state.get("pg_role", "?")
        summary_lines.append(f"  PG: {role}, lag={lag}s" if lag is not None else f"  PG: {role}")

        queue = state.get("offline_queue_depth")
        summary_lines.append(f"  Queue: {queue}" if queue is not None else "  Queue: N/A")

        hb = state.get("heartbeat_misses")
        summary_lines.append(f"  HB misses: {hb}" if hb is not None else "  HB misses: N/A")
        summary_lines.append("")

    if all_alerts:
        summary_lines.append("<b>🚨 ALERTS:</b>")
        for alert in all_alerts:
            summary_lines.append(f"  {alert}")
    else:
        summary_lines.append("<b>✅ All nodes healthy — no alerts.</b>")

    summary = "\n".join(summary_lines)

    # Send Telegram alert ONLY if there are issues
    if all_alerts and not dry_run:
        log.info("Sending Telegram alert (%d issues found)", len(all_alerts))
        send_telegram(summary)
    elif not all_alerts:
        log.info("All nodes healthy — silent (no Telegram alert sent)")

    # Close PG connection
    if conn:
        conn.close()

    log.info("Weekly health report complete.")
    log.info("=" * 60)

    return {
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "nodes": all_states,
        "alerts": all_alerts,
        "summary": summary,
        "pg_stored": pg_available,
    }


