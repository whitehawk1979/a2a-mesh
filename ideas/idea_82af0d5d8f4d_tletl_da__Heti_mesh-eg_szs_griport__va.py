def ensure_schema(conn):
    """Create the health report table if it doesn't exist."""
    cur = conn.cursor()
    cur.execute("""
        CREATE TABLE IF NOT EXISTS mesh_health_reports (
            id              SERIAL PRIMARY KEY,
            report_time     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
            node_name       TEXT NOT NULL,
            host            TEXT NOT NULL,
            reachable       BOOLEAN NOT NULL,
            mem_used_pct    REAL,
            mem_total_mb    INTEGER,
            mem_used_mb     INTEGER,
            swap_used_pct   REAL,
            swap_total_mb   INTEGER,
            swap_used_mb    INTEGER,
            disk_used_pct   REAL,
            disk_total_gb   REAL,
            disk_used_gb    REAL,
            disk_free_gb    REAL,
            pg_repl_lag_sec REAL,
            pg_repl_lag_mb  REAL,
            pg_role         TEXT,
            offline_queue_depth INTEGER,
            heartbeat_misses    INTEGER,
            alerts          TEXT[],
            raw_json        JSONB
        );
    """)
    cur.execute("""
        CREATE INDEX IF NOT EXISTS idx_health_reports_time
        ON mesh_health_reports (report_time DESC);
    """)
    cur.execute("""
        CREATE INDEX IF NOT EXISTS idx_health_reports_node
        ON mesh_health_reports (node_name, report_time DESC);
    """)
    conn.commit()
    cur.close()


