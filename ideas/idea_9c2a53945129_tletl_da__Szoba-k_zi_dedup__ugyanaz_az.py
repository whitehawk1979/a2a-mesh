"""
Generated by runa via A2A Mesh delegation

Szoba-közi dedup: ugyanaz az ötlet több szobában születik → mesh-szintű egyesítés,
hogy ne fejlesszük kétszer ugyanazt.

Ez a modul a mesh szintjén detektálja és egyesíti a több szobában függetlenül
felmerült azonos/duplikált ötleteket. Szöveghasonlítás alapján (TF-IDF +
cosine similarity) találja meg a duplikációkat, majd egyesíti őket egyetlen
mesh-szintű "merged idea" objektummá, megőrizve az eredeti szoba-közi
provenance-t.
"""

