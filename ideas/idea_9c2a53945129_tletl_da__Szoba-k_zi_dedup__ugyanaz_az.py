def main():
    parser = argparse.ArgumentParser(
        description="Szoba-közi dedup: mesh-szintű ötlet-egyesítés"
    )
    parser.add_argument(
        "--threshold",
        type=float,
        default=0.65,
        help="Hasonlósági küszöb (0.0-1.0), alapértelmezett: 0.65",
    )
    parser.add_argument(
        "--seed",
        action="store_true",
        help="Demo adatok betöltése a dedup bemutatásához",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Csak jelzi a duplikációkat, nem módosítja az adatbázist",
    )
    parser.add_argument(
        "--report",
        action="store_true",
        help="Jelentés az eddigi egyesítésekről",
    )
    parser.add_argument(
        "--data-dir",
        type=str,
        default=None,
        help="Adatkönyvtár (alapértelmezett: ./data/dedup)",
    )

    args = parser.parse_args()

    dedup = CrossRoomDeduplicator(
        threshold=args.threshold,
        data_dir=args.data_dir,
        merged_by="runa",
    )

    if args.seed:
        # Ha már vannak adatok, nem seedelünk újra
        existing = dedup.load_ideas()
        if existing:
            print(f"[dedup] Már {len(existing)} ötlet van, seed kihagyva.")
        else:
            _seed_demo_data(dedup)

    if args.report:
        print(dedup.get_merge_report())
        return

    # Alapértelmezett művelet: dedup futtatása
    print(f"[dedup] Küszöb: {args.threshold:.2f}")
    print(f"[dedup] Dry-run: {args.dry_run}")
    print()

    # Először mutatjuk a talált duplikációkat
    dup_groups = dedup.find_duplicates()
    if dup_groups:
        print(f"[dedup] {len(dup_groups)} duplikált csoport található:\n")
        for idx, (group, sim) in enumerate(dup_groups, 1):
            rooms = set(i.room_id for i in group)
            print(f"  Csoport {idx} (hasonlóság: {sim:.2%}):")
            for idea in group:
                print(f"    [{idea.room_id}] {idea.idea_id}: {idea.title}")
            print()
    else:
        print("[dedup] Nincs duplikált ötlet a szobák között.")
        return

    # Egyesítés
    merged = dedup.merge_duplicates(dry_run=args.dry_run)
    if merged:
        print(f"\n[dedup] Összesen {len(merged)} egyesítés történt.")
        print("\n" + "=" * 60)
        print(dedup.get_merge_report())


if __name__ == "__main__":
    main()