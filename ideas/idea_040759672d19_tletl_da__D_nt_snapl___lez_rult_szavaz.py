def main():
    print("""
╔══════════════════════════════════════════════╗
║  Döntésnapló — A2A Mesh                     ║
║  Lezárult szavazások → kereshető archívum   ║
║  Generated by runa via A2A Mesh delegation   ║
╚══════════════════════════════════════════════╝
""")

    log = DecisionLog(storage_path="decision_log.json")

    commands = {
        "create": cmd_create,
        "list": cmd_list,
        "vote": cmd_vote,
        "close": cmd_close,
        "search": cmd_search,
        "ref": cmd_ref,
        "stats": cmd_stats,
        "archive": cmd_archive,
        "demo": cmd_demo,
        "help": lambda l, a: cmd_help(),
    }

    cmd_help()

    while True:
        try:
            line = input("döntésnapló> ").strip()
        except (EOFError, KeyboardInterrupt):
            print("\nViszlát!")
            break
        if not line:
            continue
        parts = line.split()
        cmd = parts[0].lower()
        args = parts[1:]

        if cmd in ("quit", "exit", "q"):
            print("Viszlát!")
            break
        elif cmd in commands:
            commands[cmd](log, args)
        else:
            print(f"Ismeretlen parancs: {cmd} (help a súgóért)")


if __name__ == "__main__":
    main()