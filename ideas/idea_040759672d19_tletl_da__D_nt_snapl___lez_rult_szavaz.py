    # 3. Lezárás + archiválás
    print("3. Szavazás lezárása — automatikus archiválás...")
    d1 = log.close_vote(v1.id, rationale="Közösségi konszenzus a v2.0 mellett.")
    print(f"   Döntés: {d1.decision}")
    print(f"   Citation: {d1.citation_id}")
    print()

