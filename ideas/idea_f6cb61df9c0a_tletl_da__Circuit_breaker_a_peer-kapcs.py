import time
import random
import threading
import logging
from dataclasses import dataclass, field
from enum import Enum
from typing import Dict, Optional, Callable, Any
from collections import defaultdict

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s: %(message)s"
)
logger = logging.getLogger("circuit_breaker")


class CircuitState(Enum):
    CLOSED = "closed"       # normál működés, kérések engedélyezve
    OPEN = "open"           # peer offline, kérések blokkolva, backoff várakozás
    HALF_OPEN = "half_open" # próbálkozás: egyetlen teszt-kérés engedélyezve


@dataclass
class PeerCircuit:
    """Egy peer kapcsolat circuit-breaker állapota."""
    peer_id: str
    state: CircuitState = CircuitState.CLOSED
    consecutive_failures: int = 0
    consecutive_successes: int = 0
    last_failure_time: float = 0.0
    last_success_time: float = 0.0
    next_retry_time: float = 0.0
    total_failures: int = 0
    total_successes: int = 0
    total_blocked: int = 0
    # backoff paraméterek
    base_delay: float = 1.0       # másodperc
    max_delay: float = 300.0      # 5 perc max
    jitter_factor: float = 0.25   # ±25% jitter
    # átmeneti küszöbök
    failure_threshold: int = 3    # hány failure után OPEN
    success_threshold: int = 2    # hány success HALF_OPEN-ból CLOSED
    # half-open lock
    half_open_probe_in_flight: bool = False
    _lock: threading.Lock = field(default_factory=threading.Lock, repr=False)

    def compute_backoff(self) -> float:
        """Exponenciális backoff jitter-rel."""
        exponent = min(self.consecutive_failures - 1, 20)  # cap a túlcsordulás ellen
        delay = self.base_delay * (2 ** exponent)
        delay = min(delay, self.max_delay)
        # jitter: ±jitter_factor * delay
        jitter = delay * self.jitter_factor * (2 * random.random() - 1)
        return max(0.1, delay + jitter)

    def record_failure(self) -> None:
        with self._lock:
            self.consecutive_failures += 1
            self.consecutive_successes = 0
            self.total_failures += 1
            self.last_failure_time = time.time()
            self.half_open_probe_in_flight = False

            if self.state == CircuitState.HALF_OPEN:
                # half-open probe fail -> vissza OPEN
                self.state = CircuitState.OPEN
                self.next_retry_time = time.time() + self.compute_backoff()
                logger.warning(
                    "Peer %s: half-open probe SIKERTELEN, vissza OPEN "
                    "(failures=%d, next_retry=%.1fs)",
                    self.peer_id, self.consecutive_failures,
                    self.next_retry_time - time.time()
                )
            elif self.consecutive_failures >= self.failure_threshold:
                if self.state != CircuitState.OPEN:
                    self.state = CircuitState.OPEN
                    self.next_retry_time = time.time() + self.compute_backoff()
                    logger.warning(
                        "Peer %s: circuit OPEN (failures=%d, backoff=%.1fs)",
                        self.peer_id, self.consecutive_failures,
                        self.next_retry_time - time.time()
                    )
                else:
                    # már OPEN, frissítjük a backoff-ot
                    self.next_retry_time = time.time() + self.compute_backoff()
                    logger.debug(
                        "Peer %s: backoff frissítve (failures=%d, next=%.1fs)",
                        self.peer_id, self.consecutive_failures,
                        self.next_retry_time - time.time()
                    )

    def record_success(self) -> None:
        with self._lock:
            self.consecutive_successes += 1
            self.consecutive_failures = 0
            self.total_successes += 1
            self.last_success_time = time.time()
            self.half_open_probe_in_flight = False

            if self.state == CircuitState.HALF_OPEN:
                if self.consecutive_successes >= self.success_threshold:
                    self.state = CircuitState.CLOSED
                    logger.info(
                        "Peer %s: circuit CLOSED (gyógyult, successes=%d)",
                        self.peer_id, self.consecutive_successes
                    )
                else:
                    logger.info(
                        "Peer %s: half-open success (%d/%d)",
                        self.peer_id, self.consecutive_successes,
                        self.success_threshold
                    )
            elif self.state == CircuitState.OPEN:
                # váratlan success OPEN-ből -> CLOSED
                self.state = CircuitState.CLOSED
                logger.info(
                    "Peer %s: circuit CLOSED (váratlan success OPEN-ből)",
                    self.peer_id
                )

    def can_attempt(self) -> bool:
        """Visszaadja, hogy engedélyezett-e a kapcsolódási kísérlet."""
        with self._lock:
            now = time.time()
            if self.state == CircuitState.CLOSED:
                return True
            elif self.state == CircuitState.OPEN:
                if now >= self.next_retry_time:
                    # backoff ablak letelt -> half-open
                    if not self.half_open_probe_in_flight:
                        self.state = CircuitState.HALF_OPEN
                        self.half_open_probe_in_flight = True
                        logger.info(
                            "Peer %s: circuit -> HALF_OPEN (backoff letelt, probe indul)",
                            self.peer_id
                        )
                        return True
                    else:
                        # már van egy probe folyamatban
                        return False
                else:
                    self.total_blocked += 1
                    return False
            elif self.state == CircuitState.HALF_OPEN:
                if self.half_open_probe_in_flight:
                    return False  # csak egy probe egyszerre
                self.half_open_probe_in_flight = True
                return True
            return False

    def time_until_retry(self) -> float:
        """Hány másodperc a következő retry-ig (OPEN állapotban)."""
        with self._lock:
            if self.state == CircuitState.OPEN:
                return max(0.0, self.next_retry_time - time.time())
            return 0.0

    def stats(self) -> Dict[str, Any]:
        with self._lock:
            return {
                "peer_id": self.peer_id,
                "state": self.state.value,
                "consecutive_failures": self.consecutive_failures,
                "consecutive_successes": self.consecutive_successes,
                "total_failures": self.total_failures,
                "total_successes": self.total_successes,
                "total_blocked": self.total_blocked,
                "next_retry_in_s": round(self.time_until_retry(), 2),
                "last_failure_ago_s": round(time.time() - self.last_failure_time, 2)
                    if self.last_failure_time > 0 else None,
                "last_success_ago_s": round(time.time() - self.last_success_time, 2)
                    if self.last_success_time > 0 else None,
            }


class PeerCircuitBreaker:
    """
    Központi circuit-breaker menedzser az összes peer kapcsolathoz.

    Használat a keepalive loop-ban:
        breaker = PeerCircuitBreaker()
        if breaker.can_attempt(peer_id):
            try:
                result = keepalive_check(peer_id)
                breaker.record_success(peer_id)
            except ConnectionError:
                breaker.record_failure(peer_id)
        else:
            # skip, backoff várakozás
            pass
    """

    def __init__(
        self,
        base_delay: float = 1.0,
        max_delay: float = 300.0,
        failure_threshold: int = 3,
        success_threshold: int = 2,
        jitter_factor: float = 0.25,
    ):
        self._circuits: Dict[str, PeerCircuit] = {}
        self._global_lock = threading.Lock()
        self._base_delay = base_delay
        self._max_delay = max_delay
        self._failure_threshold = failure_threshold
        self._success_threshold = success_threshold
        self._jitter_factor = jitter_factor

    def _get_or_create(self, peer_id: str) -> PeerCircuit:
        with self._global_lock:
            if peer_id not in self._circuits:
                self._circuits[peer_id] = PeerCircuit(
                    peer_id=peer_id,
                    base_delay=self._base_delay,
                    max_delay=self._max_delay,
                    failure_threshold=self._failure_threshold,
                    success_threshold=self._success_threshold,
                    jitter_factor=self._jitter_factor,
                )
            return self._circuits[peer_id]

    def can_attempt(self, peer_id: str) -> bool:
        circuit = self._get_or_create(peer_id)
        return circuit.can_attempt()

    def record_success(self, peer_id: str) -> None:
        circuit = self._get_or_create(peer_id)
        circuit.record_success()

    def record_failure(self, peer_id: str) -> None:
        circuit = self._get_or_create(peer_id)
        circuit.record_failure()

    def get_state(self, peer_id: str) -> CircuitState:
        circuit = self._get_or_create(peer_id)
        return circuit.state

    def time_until_retry(self, peer_id: str) -> float:
        circuit = self._get_or_create(peer_id)
        return circuit.time_until_retry()

    def get_circuit(self, peer_id: str) -> Optional[PeerCircuit]:
        with self._global_lock:
            return self._circuits.get(peer_id)

    def all_stats(self) -> Dict[str, Dict[str, Any]]:
        with self._global_lock:
            return {pid: c.stats() for pid, c in self._circuits.items()}

    def reset(self, peer_id: str) -> None:
        """Kézi reset: circuit CLOSED-ba, számlálók nullázása."""
        circuit = self._get_or_create(peer_id)
        with circuit._lock:
            circuit.state = CircuitState.CLOSED
            circuit.consecutive_failures = 0
            circuit.consecutive_successes = 0
            circuit.next_retry_time = 0.0
            circuit.half_open_probe_in_flight = False
        logger.info("Peer %s: circuit manuálisan resetelve", peer_id)

    def get_offline_peers(self) -> list:
        """Visszaadja az OPEN/HALF_OPEN állapotú peer-ek ID-ját."""
        with self._global_lock:
            return [
                pid for pid, c in self._circuits.items()
                if c.state in (CircuitState.OPEN, CircuitState.HALF_OPEN)
            ]


