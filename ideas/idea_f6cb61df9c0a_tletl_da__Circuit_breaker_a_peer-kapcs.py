class SimulatedPeer:
    """Szimulált peer, ami váratlanul offline/online lesz."""

    def __init__(self, peer_id: str):
        self.peer_id = peer_id
        self._online = True
        self._lock = threading.Lock()

    def set_online(self, online: bool) -> None:
        with self._lock:
            self._online = online
        status = "ONLINE" if online else "OFFLINE"
        logger.info("Peer %s állapot: %s", self.peer_id, status)

    def is_online(self) -> bool:
        with self._lock:
            return self._online

    def keepalive(self) -> bool:
        """Szimulált keepalive ping. True ha a peer válaszol."""
        if not self.is_online():
            raise ConnectionError(f"Peer {self.peer_id} nem válaszol (offline)")
        # szimulált hálózati késleltetés
        time.sleep(0.01)
        return True


def run_keepalive_with_circuit_breaker(
    peers: list,
    breaker: PeerCircuitBreaker,
    duration_s: float = 30.0,
    interval_s: float = 0.5,
) -> None:
    """
    Keepalive loop circuit breaker-rel.

    Hagyományos megközelítés (circuit breaker NÉLKÜL):
      - minden interval-ban próbálkozik minden peer-rel
      - offline peer-nél minden alkalommal ConnectionError
      -> folyamatos retry, erőforrás-pazarlás

    Circuit breaker-rel:
      - ha egy peer OPEN, a backoff ablakig nem is próbálkozik
      - exponenciális backoff: 1s, 2s, 4s, 8s, 16s, 32s, 64s, 128s, 256s, 300s (cap)
      - amikor a backoff letelt, egyetlen probe (half-open)
      - ha a probe sikeres -> CLOSED; ha nem -> újra OPEN, hosszabb backoff
    """
    start = time.time()
    tick = 0

    logger.info("=== Keepalive loop indul (duration=%.0fs, interval=%.1fs) ===",
                duration_s, interval_s)

    while time.time() - start < duration_s:
        tick += 1
        now = time.time()
        elapsed = now - start

        for peer in peers:
            pid = peer.peer_id
            circuit = breaker.get_circuit(pid)

            if circuit and circuit.state == CircuitState.OPEN:
                wait = breaker.time_until_retry(pid)
                if wait > 0:
                    # nem próbálkozunk, spórolunk
                    if tick % 10 == 0:  # ritkábban logolunk
                        logger.debug(
                            "  [%.1fs] Peer %s: OPEN, skip (%.1fs a retry-ig, "
                            "blocked=%d)",
                            elapsed, pid, wait, circuit.total_blocked
                        )
                    continue

            if breaker.can_attempt(pid):
                try:
                    peer.keepalive()
                    breaker.record_success(pid)
                except ConnectionError as e:
                    breaker.record_failure(pid)
            # else: blocked, nem próbálkozunk

        # riport minden 5 másodpercben
        if tick % int(5.0 / interval_s) == 0 and tick > 0:
            _print_report(breaker, elapsed)

        time.sleep(interval_s)

    logger.info("=== Keepalive loop vége ===")
    _print_report(breaker, time.time() - start)


def _print_report(breaker: PeerCircuitBreaker, elapsed: float) -> None:
    logger.info("--- Riport [%.1fs] ---", elapsed)
    stats = breaker.all_stats()
    for pid in sorted(stats.keys()):
        s = stats[pid]
        logger.info(
            "  %s: state=%s, fail=%d (consec=%d), ok=%d, blocked=%d, "
            "retry_in=%.1fs",
            pid, s["state"], s["total_failures"], s["consecutive_failures"],
            s["total_successes"], s["total_blocked"], s["next_retry_in_s"]
        )
    offline = breaker.get_offline_peers()
    if offline:
        logger.info("  Offline/hibás peer-ek: %s", ", ".join(offline))
    else:
        logger.info("  Minden peer CLOSED (egészséges)")


def main():
    """
    Demonstráció: 3 peer, ahol a 2. és 3. peer különböző időpontokban
    offline lesz, majd visszajön. A circuit breaker exponenciális backoff-t
    használ, így nem folyamatosan retry-ozik.
    """
    print("=" * 70)
    print("Circuit Breaker Demo — exponenciális backoff peer-kapcsolatokra")
    print("Generated by morzsa via A2A Mesh delegation")
    print("=" * 70)

    # Peer-ek létrehozása
    peer_a = SimulatedPeer("node-alpha")
    peer_b = SimulatedPeer("node-beta")
    peer_c = SimulatedPeer("node-gamma")

    peers = [peer_a, peer_b, peer_c]

    # Circuit breaker inicializálása
    # base_delay=0.5s a demo gyorsasága miatt (production-ben 1.0+ ajánlott)
    breaker = PeerCircuitBreaker(
        base_delay=0.5,
        max_delay=8.0,        # demo: 8s max (production: 300s)
        failure_threshold=3,
        success_threshold=2,
        jitter_factor=0.2,
    )

    # Szimulációs idővonal (külön szálak, amelyek peer állapotokat váltanak)
    def timeline():
        # 0s: mindenki online
        time.sleep(2.0)
        logger.info(">>> node-beta offline lesz...")
        peer_b.set_online(False)

        time.sleep(6.0)
        logger.info(">>> node-gamma is offline lesz...")
        peer_c.set_online(False)

        time.sleep(8.0)
        logger.info(">>> node-beta visszajön online...")
        peer_b.set_online(True)

        time.sleep(5.0)
        logger.info(">>> node-gamma visszajön online...")
        peer_c.set_online(True)

    timeline_thread = threading.Thread(target=timeline, daemon=True)
    timeline_thread.start()

    # Keepalive loop futtatása 30 másodpercig
    run_keepalive_with_circuit_breaker(
        peers=peers,
        breaker=breaker,
        duration_s=30.0,
        interval_s=0.3,
    )

    # Végső riport
    print("\n" + "=" * 70)
    print("VÉGSŐ STATISZTIKA")
    print("=" * 70)
    stats = breaker.all_stats()
    for pid in sorted(stats.keys()):
        s = stats[pid]
        print(f"\n  {pid}:")
        for k, v in s.items():
            if k != "peer_id":
                print(f"    {k}: {v}")

    # Összehasonlítás: hagyományos (circuit breaker nélküli) megközelítés
    print("\n" + "=" * 70)
    print("ÖSSZEHASONLÍTÁS: circuit breaker nélkül")
    print("=" * 70)
    # Számoljuk ki, hány retry történt volna circuit breaker nélkül
    # node-beta: 14s offline / 0.3s interval = ~46 retry
    # node-gamma: 13s offline / 0.3s interval = ~43 retry
    # Összes: ~89 felesleges próbálkozás
    beta_offline_s = 14.0
    gamma_offline_s = 13.0
    interval = 0.3
    naive_retries = int(beta_offline_s / interval) + int(gamma_offline_s / interval)
    cb_blocked = sum(s["total_blocked"] for s in stats.values())
    cb_actual_failures = sum(s["total_failures"] for s in stats.values())

    print(f"  Hagyományos (folyamatos retry):  ~{naive_retries} próbálkozás")
    print(f"  Circuit breaker actual failures:  {cb_actual_failures} próbálkozás")
    print(f"  Circuit breaker blocked (skip):   {cb_blocked} skip")
    print(f"  Megspórolt hálózati kérések:      ~{naive_retries - cb_actual_failures}")
    print(f"  Csökkentés:                        "
          f"{(1 - cb_actual_failures / naive_retries) * 100:.1f}%")

    print("\nDemo befejeződött.")


if __name__ == "__main__":
    main()