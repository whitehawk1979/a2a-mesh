class DashboardServer:
    """HTTP szerver, ami a latencia dashboardot szolgálja ki."""

    def __init__(self, metrics: LatencyMetrics,
                 host: str = "127.0.0.1", port: int = 8765):
        self.metrics = metrics
        self.host = host
        self.port = port
        self._httpd: Optional[socketserver.TCPServer] = None
        self._thread: Optional[threading.Thread] = None

    def _make_handler(self):
        metrics = self.metrics

        class Handler(http.server.BaseHTTPRequestHandler):
            def log_message(self, fmt, *args):
                pass  # csendes log

            def do_GET(self):
                if self.path.startswith("/api/snapshot"):
                    from urllib.parse import urlparse, parse_qs
                    q = parse_qs(urlparse(self.path).query)
                    bucket = float(q.get("bucket", ["30"])[0])
                    snap = metrics.snapshot(bucket_seconds=bucket)
                    body = json.dumps(snap).encode("utf-8")
                    self.send_response(200)
                    self.send_header("Content-Type", "application/json")
                    self.send_header("Content-Length", str(len(body)))
                    self.send_header("Access-Control-Allow-Origin", "*")
                    self.end_headers()
                    self.wfile.write(body)
                elif self.path == "/" or self.path.startswith("/dashboard"):
                    body = DASHBOARD_HTML.encode("utf-8")
                    self.send_response(200)
                    self.send_header("Content-Type", "text/html; charset=utf-8")
                    self.send_header("Content-Length", str(len(body)))
                    self.end_headers()
                    self.wfile.write(body)
                else:
                    self.send_response(404)
                    self.end_headers()

        return Handler

    def start_background(self) -> None:
        self._httpd = socketserver.TCPServer(
            (self.host, self.port), self._make_handler()
        )
        self._httpd.allow_reuse_address = True
        self._thread = threading.Thread(
            target=self._httpd.serve_forever, daemon=True
        )
        self._thread.start()

    def stop(self) -> None:
        if self._httpd:
            self._httpd.shutdown()
            self._httpd.server_close()
            self._httpd = None
        if self._thread:
            self._thread.join(timeout=5)
            self._thread = None

    def serve_forever(self) -> None:
        """Blokkoló futtatás (fő szálban)."""
        with socketserver.TCPServer((self.host, self.port),
                                    self._make_handler()) as httpd:
            httpd.allow_reuse_address = True
            self._httpd = httpd
            print(f"[dashboard] http://{self.host}:{self.port}/")
            try:
                httpd.serve_forever()
            except KeyboardInterrupt:
                print("\n[dashboard] leállítás…")
            finally:
                httpd.server_close()


