class LatencyMetrics:
    """
    Szálbiztos latencia-metrika gyűjtő transportonként.

    Minden transporthoz egy (timestamp, latency_ms) minta-sorozatot tárol
    rolling ablakkal. P50/P95 értékeket tud számolni adott időablakra.
    """

    def __init__(self, max_samples_per_transport: int = 5000,
                 retention_seconds: float = 3600.0):
        self._lock = threading.Lock()
        self._samples: Dict[str, deque] = defaultdict(
            lambda: deque(maxlen=max_samples_per_transport)
        )
        self._retention = retention_seconds
        # transport -> szín (a dashboard számára)
        self._colors: Dict[str, str] = {}
        self._palette = [
            "#4dc9f6", "#f67019", "#f53794", "#537bc4",
            "#acc236", "#166a8f", "#00a950", "#58595b",
            "#8549ba", "#991b1b", "#0d9488", "#b45309",
        ]
        self._color_idx = 0

    def _color_for(self, transport: str) -> str:
        if transport not in self._colors:
            self._colors[transport] = self._palette[
                self._color_idx % len(self._palette)
            ]
            self._color_idx += 1
        return self._colors[transport]

    def record(self, transport: str, latency_ms: float,
               timestamp: Optional[float] = None) -> None:
        """Egy latencia-minta rögzítése egy adott transportra."""
        if timestamp is None:
            timestamp = time.time()
        with self._lock:
            self._color_for(transport)
            self._samples[transport].append((timestamp, float(latency_ms)))

    def _prune(self, transport: str, now: float) -> None:
        q = self._samples[transport]
        cutoff = now - self._retention
        while q and q[0][0] < cutoff:
            q.popleft()

    @staticmethod
    def _percentile(sorted_vals: List[float], p: float) -> float:
        if not sorted_vals:
            return 0.0
        if len(sorted_vals) == 1:
            return sorted_vals[0]
        k = (len(sorted_vals) - 1) * (p / 100.0)
        f = math.floor(k)
        c = math.ceil(k)
        if f == c:
            return sorted_vals[int(k)]
        d0 = sorted_vals[int(f)] * (c - k)
        d1 = sorted_vals[int(c)] * (k - f)
        return d0 + d1

    def transports(self) -> List[str]:
        with self._lock:
            return sorted(self._samples.keys())

    def percentile_series(self, transport: str, p: float,
                          bucket_seconds: float = 30.0,
                          now: Optional[float] = None
                          ) -> List[Tuple[float, float]]:
        """
        Visszaadja a p-edik percentilis időbeli alakját bucket-ekre bontva.
        Visszatér: [(bucket_center_time, percentile_value), ...]
        """
        if now is None:
            now = time.time()
        with self._lock:
            self._prune(transport, now)
            samples = list(self._samples[transport])
        if not samples:
            return []
        start = samples[0][0]
        end = samples[-1][0]
        if end <= start:
            return [(start, self._percentile([s[1] for s in samples], p))]
        buckets: Dict[float, List[float]] = defaultdict(list)
        for ts, lat in samples:
            b = math.floor((ts - start) / bucket_seconds) * bucket_seconds + start
            buckets[b].append(lat)
        result = []
        for b in sorted(buckets.keys()):
            vals = sorted(buckets[b])
            result.append((b + bucket_seconds / 2.0,
                           self._percentile(vals, p)))
        return result

    def snapshot(self, bucket_seconds: float = 30.0) -> dict:
        """
        JSON-serializálható pillanatkép a dashboard számára.
        Tartalmazza transportonként a P50 és P95 sorozatokat, színeket,
        és az aktuális (utolsó bucket) értékeket.
        """
        now = time.time()
        data = {"now": now, "transports": []}
        with self._lock:
            transports = sorted(self._samples.keys())
            for t in transports:
                self._prune(t, now)
        for t in transports:
            p50 = self.percentile_series(t, 50, bucket_seconds, now)
            p95 = self.percentile_series(t, 95, bucket_seconds, now)
            latest_p50 = p50[-1][1] if p50 else 0.0
            latest_p95 = p95[-1][1] if p95 else 0.0
            # trend: utolsó vs előző bucket
            trend_p50 = 0.0
            trend_p95 = 0.0
            if len(p50) >= 2:
                prev = p50[-2][1] or 1e-9
                trend_p50 = (p50[-1][1] - prev) / prev * 100.0
            if len(p95) >= 2:
                prev = p95[-2][1] or 1e-9
                trend_p95 = (p95[-1][1] - prev) / prev * 100.0
            data["transports"].append({
                "name": t,
                "color": self._color_for(t),
                "p50": [{"t": ts, "v": v} for ts, v in p50],
                "p95": [{"t": ts, "v": v} for ts, v in p95],
                "latest_p50": round(latest_p50, 2),
                "latest_p95": round(latest_p95, 2),
                "trend_p50": round(trend_p50, 2),
                "trend_p95": round(trend_p95, 2),
                "sample_count": len(self._samples[t]) if t in self._samples else 0,
            })
        return data


