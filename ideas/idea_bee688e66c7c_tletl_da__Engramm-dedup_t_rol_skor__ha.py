# Integrációs helper: batch dedup meglévő kapszulákból
# ---------------------------------------------------------------------------

def dedup_existing_capsules(
    capsules: List[Dict],
    threshold: float = 0.85,
) -> Tuple[List[Dict], Dict]:
    """
    Meglévő kapszulák batch dedup-ja.

    Bemenet: lista of dict, mindegyik tartalmaz 'content' (és opcionálisan
    'topic', 'agent', 'tags', 'metadata').

    Visszatérés: (unique_capsules, stats)
    """
    store = EngramDedupStore(threshold=threshold)
    unique = []
    for cap in capsules:
        accepted, reason, eng = store.store(
            content=cap.get("content", ""),
            topic=cap.get("topic", ""),
            agent=cap.get("agent", ""),
            tags=cap.get("tags", []),
            metadata=cap.get("metadata", {}),
        )
        if accepted and eng:
            unique.append(eng.to_dict())

    return unique, store.get_stats()


