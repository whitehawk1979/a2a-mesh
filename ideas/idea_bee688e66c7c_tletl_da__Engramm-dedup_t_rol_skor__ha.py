_STOPWORDS_HU = frozenset(
    """
    a az és vagy hogy nem igen is be ki el meg fel le fel rá meg
    ezt ezt azokat azt akik amely amelyek mint ha pedig tehát így
    csak még már is volt lesz van vannak egy egyes some the is are
    and or not but with for to of in on at by this that these those
    it its as was were be been being have has had do does did will
    would could should may might can shall
    """.split()
)


def tokenize(text: str) -> List[str]:
    """Szöveg tokenizálása: kisbetűsítés, írásjelek eltávolítása, stopword-szűrés."""
    if not text:
        return []
    text = text.lower()
    tokens = re.findall(r"[a-záéíóöőúüű]+|\d+", text, flags=re.UNICODE)
    return [t for t in tokens if t not in _STOPWORDS_HU and len(t) > 1]


def jaccard_similarity(set_a: set, set_b: set) -> float:
    """Jaccard hasonlóság két halmaz között."""
    if not set_a and not set_b:
        return 1.0
    if not set_a or not set_b:
        return 0.0
    inter = len(set_a & set_b)
    union = len(set_a | set_b)
    return inter / union if union else 0.0


def sequence_similarity(text_a: str, text_b: str) -> float:
    """difflib SequenceMatcher alapú hasonlóság."""
    if not text_a and not text_b:
        return 1.0
    if not text_a or not text_b:
        return 0.0
    return difflib.SequenceMatcher(None, text_a, text_b).ratio()


def combined_similarity(text_a: str, text_b: str) -> float:
    """
    Kombinált hasonlóság: Jaccard (token-szint) és SequenceMatcher
    (karakterszint) súlyozott átlaga. Ez jobban kezeli a
    szinonimás és a szó szerinti duplikációkat is.
    """
    if not text_a and not text_b:
        return 1.0
    if not text_a or not text_b:
        return 0.0

    tokens_a = tokenize(text_a)
    tokens_b = tokenize(text_b)

    jac = jaccard_similarity(set(tokens_a), set(tokens_b))
    seq = sequence_similarity(text_a.strip(), text_b.strip())

    # Súlyozás: 60% Jaccard (jelentés-szint), 40% SequenceMatcher (szó szerinti)
    return 0.6 * jac + 0.4 * seq


def content_hash(text: str) -> str:
    """SHA-256 hash a normalizált szövegből — szó szerinti duplikációhoz."""
    normalized = re.sub(r"\s+", " ", text.strip().lower())
    return hashlib.sha256(normalized.encode("utf-8")).hexdigest()


