@dataclass
class Engram:
    """Egy memóriakapszula (engramm)."""
    id: str
    content: str
    topic: str = ""
    agent: str = ""
    timestamp: float = field(default_factory=time.time)
    tags: List[str] = field(default_factory=list)
    metadata: Dict = field(default_factory=dict)

    def to_dict(self) -> dict:
        return asdict(self)

    @classmethod
    def from_dict(cls, d: dict) -> "Engram":
        return cls(
            id=d.get("id", ""),
            content=d.get("content", ""),
            topic=d.get("topic", ""),
            agent=d.get("agent", ""),
            timestamp=d.get("timestamp", time.time()),
            tags=d.get("tags", []),
            metadata=d.get("metadata", {}),
        )


# ---------------------------------------------------------------------------
# Dedup szűrő és tároló
# ---------------------------------------------------------------------------

class EngramDedupStore:
    """
    Engramm-tároló hasonlósági szűréssel.

    Működés:
      1. Szó szerinti duplikáció: content_hash alapján azonnal szűri.
      2. Hasonlósági duplikáció: combined_similarity a meglévő
         engrammokkal — ha bármelyik > threshold, elutasítja.
      3. Topic-szintű dedup: ugyanabban a topic-ban szigorúbb,
         más topic-ban lazább szűrés.
    """

    def __init__(
        self,
        threshold: float = 0.85,
        cross_topic_threshold: float = 0.92,
        max_per_topic: int = 50,
        persist_path: Optional[str] = None,
    ):
        self.threshold = threshold
        self.cross_topic_threshold = cross_topic_threshold
        self.max_per_topic = max_per_topic
        self.persist_path = persist_path

        self.engrams: List[Engram] = []
        self._hash_index: Dict[str, str] = {}  # hash -> engram_id
        self._topic_index: Dict[str, List[str]] = {}  # topic -> [engram_id]

        # Statisztika
        self.stats = {
            "total_attempts": 0,
            "accepted": 0,
            "rejected_exact": 0,
            "rejected_similar": 0,
            "rejected_topic_full": 0,
        }

        if persist_path and os.path.exists(persist_path):
            self.load()

    # --- Belső segédfüggvények ---

    def _find_similar(
        self, content: str, topic: str
    ) -> Tuple[Optional[str], float]:
        """
        Megkeresi a leginkább hasonló meglévő engrammot.
        Visszaadja (engramm_id, similarity) vagy (None, 0.0).
        """
        best_id = None
        best_sim = 0.0

        for eng in self.engrams:
            # Ugyanaz a topic -> threshold
            # Más topic -> cross_topic_threshold (szigorúbb)
            if topic and eng.topic == topic:
                current_threshold = self.threshold
            else:
                current_threshold = self.cross_topic_threshold

            sim = combined_similarity(content, eng.content)

            if sim > best_sim:
                best_sim = sim
                best_id = eng.id

            # Ha elérjük a releváns küszöböt, nem kell tovább keresni
            if sim >= current_threshold:
                return best_id, sim

        return best_id, best_sim

    def _topic_count(self, topic: str) -> int:
        if not topic:
            return len(self.engrams)
        return len(self._topic_index.get(topic, []))

    def _add_to_indexes(self, eng: Engram) -> None:
        h = content_hash(eng.content)
        self._hash_index[h] = eng.id
        if eng.topic:
            self._topic_index.setdefault(eng.topic, []).append(eng.id)

    def _remove_from_indexes(self, eng: Engram) -> None:
        h = content_hash(eng.content)
        self._hash_index.pop(h, None)
        if eng.topic and eng.topic in self._topic_index:
            try:
                self._topic_index[eng.topic].remove(eng.id)
            except ValueError:
                pass

    # --- Publikus API ---

    def store(
        self,
        content: str,
        topic: str = "",
        agent: str = "",
        tags: Optional[List[str]] = None,
        metadata: Optional[Dict] = None,
    ) -> Tuple[bool, str, Optional[Engram]]:
        """
        Megpróbálja tárolni az engrammot.

        Visszatérés:
          (accepted, reason, engram_or_none)
        """
        self.stats["total_attempts"] += 1

        if not content or not content.strip():
            return False, "empty_content", None

        # 1. Szó szerinti duplikáció
        h = content_hash(content)
        if h in self._hash_index:
            self.stats["rejected_exact"] += 1
            existing_id = self._hash_index[h]
            return False, f"exact_duplicate:{existing_id}", None

        # 2. Topic-szintű kapacitás ellenőrzés
        if topic and self._topic_count(topic) >= self.max_per_topic:
            self.stats["rejected_topic_full"] += 1
            return False, f"topic_full:{topic}", None

        # 3. Hasonlósági szűrés
        similar_id, sim = self._find_similar(content, topic)

        relevant_threshold = self.threshold if topic else self.cross_topic_threshold
        # Ha volt találat és a hasonlóság elég magas
        if similar_id and sim >= relevant_threshold:
            self.stats["rejected_similar"] += 1
            pct = round(sim * 100, 1)
            return False, f"similar_duplicate:{similar_id}:{pct}%", None

        # 4. Elfogadás és tárolás
        eng = Engram(
            id=hashlib.sha256(
                f"{content}{time.time()}".encode("utf-8")
            ).hexdigest()[:16],
            content=content.strip(),
            topic=topic,
            agent=agent,
            tags=tags or [],
            metadata=metadata or {},
        )

        self.engrams.append(eng)
        self._add_to_indexes(eng)
        self.stats["accepted"] += 1

        if self.persist_path:
            self.save()

        return True, "accepted", eng

    def store_engram(self, eng: Engram) -> Tuple[bool, str, Optional[Engram]]:
        """Engramm objektum közvetlen tárolása."""
        return self.store(
            content=eng.content,
            topic=eng.topic,
            agent=eng.agent,
            tags=eng.tags,
            metadata=eng.metadata,
        )

    def get(self, engram_id: str) -> Optional[Engram]:
        for eng in self.engrams:
            if eng.id == engram_id:
                return eng
        return None

    def list_by_topic(self, topic: str) -> List[Engram]:
        ids = self._topic_index.get(topic, [])
        id_set = set(ids)
        return [e for e in self.engrams if e.id in id_set]

    def all(self) -> List[Engram]:
        return list(self.engrams)

    def remove(self, engram_id: str) -> bool:
        for i, eng in enumerate(self.engrams):
            if eng.id == engram_id:
                self._remove_from_indexes(eng)
                self.engrams.pop(i)
                if self.persist_path:
                    self.save()
                return True
        return False

    def clear(self) -> None:
        self.engrams.clear()
        self._hash_index.clear()
        self._topic_index.clear()

    def get_stats(self) -> Dict:
        s = dict(self.stats)
        s["current_count"] = len(self.engrams)
        s["topics"] = len(self._topic_index)
        if s["total_attempts"] > 0:
            s["dedup_rate"] = round(
                (s["rejected_exact"] + s["rejected_similar"])
                / s["total_attempts"]
                * 100,
                1,
            )
        else:
            s["dedup_rate"] = 0.0
        return s

    # --- Persistencia ---

    def save(self) -> None:
        if not self.persist_path:
            return
        data = {
            "engrams": [e.to_dict() for e in self.engrams],
            "stats": self.stats,
            "config": {
                "threshold": self.threshold,
                "cross_topic_threshold": self.cross_topic_threshold,
                "max_per_topic": self.max_per_topic,
            },
        }
        with open(self.persist_path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)

    def load(self) -> None:
        if not self.persist_path or not os.path.exists(self.persist_path):
            return
        with open(self.persist_path, "r", encoding="utf-8") as f:
            data = json.load(f)
        self.engrams = [Engram.from_dict(d) for d in data.get("engrams", [])]
        self.stats.update(data.get("stats", {}))
        cfg = data.get("config", {})
        if "threshold" in cfg:
            self.threshold = cfg["threshold"]
        if "cross_topic_threshold" in cfg:
            self.cross_topic_threshold = cfg["cross_topic_threshold"]
        if "max_per_topic" in cfg:
            self.max_per_topic = cfg["max_per_topic"]
        # Indexek újraépítése
        self._hash_index.clear()
        self._topic_index.clear()
        for eng in self.engrams:
            self._add_to_indexes(eng)


