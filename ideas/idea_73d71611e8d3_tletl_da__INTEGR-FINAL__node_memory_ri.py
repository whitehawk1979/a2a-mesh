def _truncate(text: str, width: int) -> str:
    if len(text) <= width:
        return text
    return text[: width - 1] + "…"


def _format_table(rows: List[Dict[str, object]], title: str) -> str:
    """Format a list of process dicts as a text table."""
    header = (
        f"{'PID':<{COL_WIDTHS['pid']}} "
        f"{'PPID':<{COL_WIDTHS['ppid']}} "
        f"{'USER':<{COL_WIDTHS['user']}} "
        f"{'RSS(MB)':>{COL_WIDTHS['rss_mb']}} "
        f"{'VMS(MB)':>{COL_WIDTHS['vms_mb']}} "
        f"{'CPU%':>{COL_WIDTHS['cpu']}} "
        f"{'MEM%':>{COL_WIDTHS['mem_pct']}} "
        f"{'ELAPSED':<{COL_WIDTHS['etime']}} "
        f"{'COMMAND':<{COL_WIDTHS['command']}}"
    )

    lines = []
    lines.append("")
    lines.append(title)
    lines.append("=" * len(title))
    lines.append(header)
    lines.append("-" * len(header))

    for r in rows:
        line = (
            f"{str(r['pid']):<{COL_WIDTHS['pid']}} "
            f"{str(r['ppid']):<{COL_WIDTHS['ppid']}} "
            f"{_truncate(str(r['user']), COL_WIDTHS['user']):<{COL_WIDTHS['user']}} "
            f"{r['rss_mb']:>{COL_WIDTHS['rss_mb']}.1f} "
            f"{r['vms_mb']:>{COL_WIDTHS['vms_mb']}.1f} "
            f"{r['cpu_pct']:>{COL_WIDTHS['cpu']}.1f} "
            f"{r['mem_pct']:>{COL_WIDTHS['mem_pct']}.1f} "
            f"{_truncate(str(r['etime']), COL_WIDTHS['etime']):<{COL_WIDTHS['etime']}} "
            f"{_truncate(str(r['args']), COL_WIDTHS['command'])}"
        )
        lines.append(line)

    if not rows:
        lines.append("(no processes found)")

    lines.append("")
    return "\n".join(lines)


def _format_system_memory(mem: Dict[str, object]) -> str:
    """Format /proc/meminfo summary."""
    lines = []
    lines.append("")
    lines.append("System Memory Summary (/proc/meminfo)")
    lines.append("=" * 40)

    if not mem:
        lines.append("(not available on this platform)")
        lines.append("")
        return "\n".join(lines)

    total = mem.get("MemTotal", 0)
    free = mem.get("MemFree", 0)
    available = mem.get("MemAvailable", free)
    buffers = mem.get("Buffers", 0)
    cached = mem.get("Cached", 0)
    swap_total = mem.get("SwapTotal", 0)
    swap_free = mem.get("SwapFree", 0)

    used = round(total - free - buffers - cached, 1) if total else 0
    used_pct = round((used / total) * 100, 1) if total else 0.0

    lines.append(f"  Total:       {total:>10.1f} MB")
    lines.append(f"  Used:        {used:>10.1f} MB  ({used_pct}%)")
    lines.append(f"  Free:        {free:>10.1f} MB")
    lines.append(f"  Available:   {available:>10.1f} MB")
    lines.append(f"  Buffers:     {buffers:>10.1f} MB")
    lines.append(f"  Cached:      {cached:>10.1f} MB")
    if swap_total:
        swap_used = round(swap_total - swap_free, 1)
        lines.append(f"  Swap Total:  {swap_total:>10.1f} MB")
        lines.append(f"  Swap Used:   {swap_used:>10.1f} MB")
    lines.append("")
    return "\n".join(lines)


def format_text_report(report: Dict[str, object], top_n: int) -> str:
    """Format the full report as human-readable text."""
    out = []
    out.append("╔══════════════════════════════════════════════════════════════╗")
    out.append("║          A2A MESH — NODE MEMORY REPORT                       ║")
    out.append("╚══════════════════════════════════════════════════════════════╝")
    out.append(f"Timestamp:        {report['timestamp']}")
    out.append(f"Total processes:  {report['total_processes']}")
    out.append(f"Mesh nodes found: {report['mesh_node_count']}")

    # System memory
    out.append(_format_system_memory(report["system_memory"]))

    # Mesh nodes
    out.append(
        _format_table(
            report["mesh_nodes"],
            f"A2A Mesh Node Processes ({report['mesh_node_count']})",
        )
    )

    # Top processes by memory
    out.append(
        _format_table(
            report["top_by_memory"],
            f"Top {top_n} Processes by Memory (RSS)",
        )
    )

    # Aggregate mesh node memory
    if report["mesh_nodes"]:
        total_rss = sum(n["rss_mb"] for n in report["mesh_nodes"])
        total_vms = sum(n["vms_mb"] for n in report["mesh_nodes"])
        avg_rss = round(total_rss / len(report["mesh_nodes"]), 1)
        out.append("Mesh Node Memory Aggregate")
        out.append("=" * 40)
        out.append(f"  Total RSS: {total_rss:.1f} MB")
        out.append(f"  Total VMS: {total_vms:.1f} MB")
        out.append(f"  Avg RSS:   {avg_rss:.1f} MB")
        out.append("")

    return "\n".join(out)


def format_json_report(report: Dict[str, object]) -> str:
    """Format the report as JSON."""
    # Make a serializable copy
    return json.dumps(report, indent=2, default=str)


# ---------------------------------------------------------------------------
# Watch mode
# ---------------------------------------------------------------------------

def watch_loop(top_n: int, interval: int, as_json: bool) -> None:
    """Continuously refresh the report every `interval` seconds."""
    try:
        while True:
            # Clear screen on POSIX terminals
            if not as_json:
                os.system("clear" if os.name == "posix" else "cls")
            report = collect_processes(top_n)
            if as_json:
                print(format_json_report(report))
            else:
                print(format_text_report(report, top_n))
                print(f"Refreshing every {interval}s — press Ctrl+C to stop.")
            time.sleep(interval)
    except KeyboardInterrupt:
        print("\nStopped.")
        sys.exit(0)


