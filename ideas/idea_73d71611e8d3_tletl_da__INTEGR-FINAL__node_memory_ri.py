"""
Generated by runa via A2A Mesh delegation

INTEGR-FINAL: node memory riport modul
A2A Mesh - core/memory_report.py

A node-ok memoriahasznalatat riportalja a `ps` kimenete alapjan:
- Rendszer szintu memoria osszesito (RSS osszeg, szazalek)
- Top folyamatok memoria szerint rendezve
- Node-onkenti (user/process) bontas, ha alkalmazhato

Futtatas:
    python3 core/memory_report.py
    python3 core/memory_report.py --top 20
    python3 core/memory_report.py --json
    python3 core/memory_report.py --node-filter runa
"""

import argparse
import json
import os
import subprocess
import sys
from datetime import datetime, timezone
from typing import List, Dict, Any, Optional, Tuple


def _run_ps() -> List[Dict[str, Any]]:
    """Lefuttatja a `ps` parancsot es feldolgozza a kimenetet.

    Visszateresi ertek: process dict-ek listaja, kulcsok:
        pid, user, rss_kb, vsz_kb, pcpu, pmem, command, args
    """
    # -e: minden folyamat
    # -o: egyeni formatum
    # --no-headers: fejlec nelkul
    fmt = "pid,user,rss,vsz,pcpu,pmem,comm,args"
    try:
        result = subprocess.run(
            ["ps", "-e", "-o", fmt, "--no-headers"],
            capture_output=True,
            text=True,
            check=True,
            timeout=10,
        )
    except FileNotFoundError:
        print("HIBA: a `ps` parancs nem talalhato ezen a rendszeren.",
              file=sys.stderr)
        sys.exit(2)
    except subprocess.TimeoutExpired:
        print("HIBA: a `ps` parancs idotullepes.", file=sys.stderr)
        sys.exit(3)
    except subprocess.CalledProcessError as exc:
        print(f"HIBA: ps hiba: {exc.stderr}", file=sys.stderr)
        sys.exit(4)

    processes: List[Dict[str, Any]] = []
    for line in result.stdout.splitlines():
        line = line.strip()
        if not line:
            continue
        # A `args` mezo szokozoket tartalmazhat, ezert max 7 split.
        parts = line.split(None, 7)
        if len(parts) < 7:
            # args hianyzik - comm-ot hasznaljuk helyette
            parts = parts + [parts[-1] if parts else ""]
        try:
            pid = int(parts[0])
            user = parts[1]
            rss_kb = int(parts[2]) if parts[2].isdigit() else 0
            vsz_kb = int(parts[3]) if parts[3].isdigit() else 0
            pcpu = float(parts[4]) if _is_float(parts[4]) else 0.0
            pmem = float(parts[5]) if _is_float(parts[5]) else 0.0
            comm = parts[6]
            args = parts[7] if len(parts) > 7 else comm
        except (ValueError, IndexError):
            continue

        processes.append({
            "pid": pid,
            "user": user,
            "rss_kb": rss_kb,
            "vsz_kb": vsz_kb,
            "rss_mb": round(rss_kb / 1024.0, 2),
            "vsz_mb": round(vsz_kb / 1024.0, 2),
            "pcpu": pcpu,
            "pmem": pmem,
            "comm": comm,
            "args": args,
        })
    return processes


def _is_float(value: str) -> bool:
    try:
        float(value)
        return True
    except (ValueError, TypeError):
        return False


def _read_meminfo() -> Dict[str, int]:
    """Beolvassa a /proc/meminfo fajlt (Linux) es visszaadja KB-ban az ertekeket."""
    meminfo: Dict[str, int] = {}
    try:
        with open("/proc/meminfo", "r", encoding="utf-8") as fh:
            for line in fh:
                key, _, rest = line.partition(":")
                rest = rest.strip()
                # "12345 kB"
                num = rest.split()[0] if rest else "0"
                meminfo[key.strip()] = int(num) if num.isdigit() else 0
    except (FileNotFoundError, PermissionError, OSError):
        pass
    return meminfo


def _system_total_memory_kb() -> Optional[int]:
    """Visszaadja a rendszer teljes fizikai memoriat KB-ban, vagy None."""
    meminfo = _read_meminfo()
    if "MemTotal" in meminfo:
        return meminfo["MemTotal"]
    # Fallback: sysconf
    try:
        import resource
        pages = os.sysconf("SC_PHYS_PAGES")
        page_size = os.sysconf("SC_PAGE_SIZE")
        return int(pages * page_size / 1024)
    except (ValueError, AttributeError, OSError):
        return None


def _system_used_memory_kb() -> Optional[int]:
    """Visszaadja a hasznalt memoriat KB-ban (MemTotal - MemAvailable)."""
    meminfo = _read_meminfo()
    if "MemTotal" in meminfo and "MemAvailable" in meminfo:
        return meminfo["MemTotal"] - meminfo["MemAvailable"]
    if "MemTotal" in meminfo and "MemFree" in meminfo:
        return meminfo["MemTotal"] - meminfo["MemFree"]
    return None


def _kb_to_human(kb: float) -> str:
    """KB-t olvashato formatumba (MB/GB) alakitja."""
    if kb >= 1024 * 1024:
        return f"{kb / (1024 * 1024):.2f} GB"
    if kb >= 1024:
        return f"{kb / 1024:.2f} MB"
    return f"{kb:.0f} KB"


def _detect_node_name(processes: List[Dict[str, Any]]) -> str:
    """Megprobalja meghatarozni a node nevet a folyamatok alapjan.

    Keres a2a_mesh vagy node specifikus folyamatokat. Ha nem talal,
    a hostname-t hasznalja.
    """
    for p in processes:
        args_lower = p["args"].lower()
        if "a2a_mesh" in args_lower or "a2a-mesh" in args_lower:
            # Ha van egy node neves argumentum
            for flag in ("--node", "--name", "-n"):
                if flag in p["args"]:
                    parts = p["args"].split()
                    try:
                        idx = parts.index(flag)
                        return parts[idx + 1]
                    except (ValueError, IndexError):
                        pass
    try:
        return subprocess.run(
            ["hostname"], capture_output=True, text=True, timeout=5
        ).stdout.strip() or "unknown-node"
    except Exception:
        return "unknown-node"


def build_report(processes: List[Dict[str, Any]],
                 top_n: int = 10,
                 node_filter: Optional[str] = None) -> Dict[str, Any]:
    """Osszeallitja a memoria riport dict-et."""
    if node_filter:
        nf_lower = node_filter.lower()
        processes = [
            p for p in processes
            if nf_lower in p["user"].lower()
            or nf_lower in p["comm"].lower()
            or nf_lower in p["args"].lower()
        ]

    total_rss_kb = sum(p["rss_kb"] for p in processes)
    total_vsz_kb = sum(p["vsz_kb"] for p in processes)
    sys_total_kb = _system_total_memory_kb()
    sys_used_kb = _system_used_memory_kb()

    # Top folyamatok RSS szerint
    sorted_procs = sorted(processes, key=lambda p: p["rss_kb"], reverse=True)
    top_procs = sorted_procs[:top_n]

    # User-onkenti aggregacio (node-onkenti, ha a user a node-ot reprezentalja)
    by_user: Dict[str, Dict[str, Any]] = {}
    for p in processes:
        u = p["user"]
        if u not in by_user:
            by_user[u] = {
                "user": u,
                "process_count": 0,
                "rss_kb": 0,
                "vsz_kb": 0,
            }
        by_user[u]["process_count"] += 1
        by_user[u]["rss_kb"] += p["rss_kb"]
        by_user[u]["vsz_kb"] += p["vsz_kb"]

    users_sorted = sorted(
        by_user.values(), key=lambda d: d["rss_kb"], reverse=True
    )
    for u in users_sorted:
        u["rss_mb"] = round(u["rss_kb"] / 1024.0, 2)
        u["rss_human"] = _kb_to_human(u["rss_kb"])

    # comm-onkenti aggregacio (milyen tipusu folyamatok esznek a legtobbet)
    by_comm: Dict[str, Dict[str, Any]] = {}
    for p in processes:
        c = p["comm"]
        if c not in by_comm:
            by_comm[c] = {
                "comm": c,
                "process_count": 0,
                "rss_kb": 0,
            }
        by_comm[c]["process_count"] += 1
        by_comm[c]["rss_kb"] += p["rss_kb"]

    comms_sorted = sorted(
        by_comm.values(), key=lambda d: d["rss_kb"], reverse=True
    )[:top_n]
    for c in comms_sorted:
        c["rss_human"] = _kb_to_human(c["rss_kb"])

    node_name = _detect_node_name(processes)

    report: Dict[str, Any] = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "node": node_name,
        "hostname": _safe_hostname(),
        "summary": {
            "total_processes": len(processes),
            "total_rss_kb": total_rss_kb,
            "total_rss_human": _kb_to_human(total_rss_kb),
            "total_vsz_kb": total_vsz_kb,
            "total_vsz_human": _kb_to_human(total_vsz_kb),
            "system_total_kb": sys_total_kb,
            "system_total_human": _kb_to_human(sys_total_kb) if sys_total_kb else None,
            "system_used_kb": sys_used_kb,
            "system_used_human": _kb_to_human(sys_used_kb) if sys_used_kb else None,
            "rss_percent_of_system": (
                round(total_rss_kb / sys_total_kb * 100, 2)
                if sys_total_kb else None
            ),
            "system_used_percent": (
                round(sys_used_kb / sys_total_kb * 100, 2)
                if sys_total_kb and sys_used_kb else None
            ),
        },
        "top_processes": top_procs,
        "by_user": users_sorted,
        "by_comm": comms_sorted,
    }
    return report


def _safe_hostname() -> str:
    try:
        import socket
        return socket.gethostname()
    except Exception:
        return "unknown"


def format_text_report(report: Dict[str, Any]) -> str:
    """Szoveges, olvashato riport formatum."""
    lines: List[str] = []
    s = report["summary"]
    lines.append("=" * 72)
    lines.append("A2A Mesh - Node Memory Report")
    lines.append("=" * 72)
    lines.append(f"Generated: {report['generated_at']}")
    lines.append(f"Node:      {report['node']}")
    lines.append(f"Hostname:  {report['hostname']}")
    lines.append("")
    lines.append("-" * 72)
    lines.append("OSSZESITO")
    lines.append("-" * 72)
    lines.append(f"  Osszes folyamat:        {s['total_processes']}")
    lines.append(f"  Osszes RSS:             {s['total_rss_human']}"
                 f" ({s['total_rss_kb']} KB)")
    lines.append(f"  Osszes VSZ:             {s['total_vsz_human']}"
                 f" ({s['total_vsz_kb']} KB)")
    if s["system_total_kb"]:
        lines.append(f"  Rendszer memoria:       {s['system_total_human']}"
                     f" ({s['system_total_kb']} KB)")
    if s["system_used_kb"] is not None:
        lines.append(f"  Rendszer hasznalt:      {s['system_used_human']}"
                     f" ({s['system_used_kb']} KB)")
    if s["system_used_percent"] is not None:
        lines.append(f"  Rendszer hasznalt %:    {s['system_used_percent']}%")
    if s["rss_percent_of_system"] is not None:
        lines.append(f"  RSS / rendszer:         {s['rss_percent_of_system']}%")
    lines.append("")

    lines.append("-" * 72)
    lines.append("TOP FOLYAMATOK (RSS szerint)")
    lines.append("-" * 72)
    header = f"{'PID':>7}  {'USER':<12} {'RSS':>10} {'%MEM':>6}  {'COMMAND':<24} ARGS"
    lines.append(header)
    lines.append("-" * 72)
    for p in report["top_processes"]:
        cmd = (p["comm"][:24]) if p["comm"] else ""
        args_short = p["args"][:60] + ("..." if len(p["args"]) > 60 else "")
        lines.append(
            f"{p['pid']:>7}  {p['user']:<12} "
            f"{_kb_to_human(p['rss_kb']):>10} {p['pmem']:>5.1f}%  "
            f"{cmd:<24} {args_short}"
        )
    lines.append("")

    lines.append("-" * 72)
    lines.append("USER (NODE) ONKENTI MEMORIA")
    lines.append("-" * 72)
    lines.append(f"{'USER':<16} {'PROCS':>6} {'RSS':>12} {'RSS (KB)':>14}")
    lines.append("-" * 72)
    for u in report["by_user"][:15]:
        lines.append(
            f"{u['user']:<16} {u['process_count']:>6} "
            f"{u['rss_human']:>12} {u['rss_kb']:>14}"
        )
    lines.append("")

    lines.append("-" * 72)
    lines.append("FOLYAMAT TIPUSONKENT (comm)")
    lines.append("-" * 72)
    lines.append(f"{'COMM':<24} {'PROCS':>6} {'RSS':>12}")
    lines.append("-" * 72)
    for c in report["by_comm"]:
        lines.append(
            f"{c['comm']:<24} {c['process_count']:>6} {c['rss_human']:>12}"
        )
    lines.append("")
    lines.append("=" * 72)
    return "\n".join(lines)


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description="A2A Mesh node memoria riport modul (ps alapjan)."
    )
    parser.add_argument(
        "--top", type=int, default=10,
        help="Top N folyamat megjelenitese (alapertelmezett: 10)."
    )
    parser.add_argument(
        "--json", action="store_true",
        help="JSON kimenet (gepgep olvashato)."
    )
    parser.add_argument(
        "--node-filter", type=str, default=None,
        help="Szures user/comm/args alapjan (pl. 'runa')."
    )
    parser.add_argument(
        "--output", "-o", type=str, default=None,
        help="Kimeneti fajl utvonal (alapertelmezett: stdout)."
    )
    args = parser.parse_args(argv)

    processes = _run_ps()
    if not processes:
        msg = "Nem sikerult folyamatadatot gyujteni."
        if args.json:
            payload = json.dumps({"error": msg}, indent=2)
        else:
            payload = msg
        _write_output(payload, args.output)
        return 1

    report = build_report(
        processes,
        top_n=args.top,
        node_filter=args.node_filter,
    )

    if args.json:
        output = json.dumps(report, indent=2, ensure_ascii=False)
    else:
        output = format_text_report(report)

    _write_output(output, args.output)
    return 0


def _write_output(content: str, path: Optional[str]) -> None:
    if path:
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(content)
            fh.write("\n")
        print(f"Riport kiirva: {path}", file=sys.stderr)
    else:
        print(content)


if __name__ == "__main__":
    sys.exit(main())