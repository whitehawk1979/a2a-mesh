def _run(cmd, timeout=10):
    """Run a shell command and return (stdout, stderr, returncode)."""
    try:
        proc = subprocess.run(
            cmd,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            timeout=timeout,
        )
        return proc.stdout, proc.stderr, proc.returncode
    except FileNotFoundError:
        return "", f"command not found: {' '.join(cmd)}", 127
    except subprocess.TimeoutExpired:
        return "", f"command timed out: {' '.join(cmd)}", 124
    except Exception as exc:  # pragma: no cover
        return "", str(exc), 1


def _parse_kb(value):
    """Parse a memory string like '12345', '12345 kB', '12M' into KB float."""
    if value is None:
        return 0.0
    s = str(value).strip().lower()
    if not s:
        return 0.0
    m = re.match(r"^([\d.]+)\s*([kmgt]?i?b?)?$", s)
    if not m:
        return 0.0
    num = float(m.group(1))
    unit = m.group(2) or ""
    if unit.startswith("g"):
        return num * 1024 * 1024
    if unit.startswith("m"):
        return num * 1024
    if unit.startswith("t"):
        return num * 1024 * 1024 * 1024
    return num  # bytes or kb; treat as kb for ps/rss


def get_meminfo():
    """Read /proc/meminfo on Linux; return dict of values in KB."""
    info = {}
    if os.path.exists("/proc/meminfo"):
        try:
            with open("/proc/meminfo", "r", encoding="utf-8") as fh:
                for line in fh:
                    parts = line.split(":")
                    if len(parts) != 2:
                        continue
                    key = parts[0].strip()
                    val = parts[1].strip()
                    m = re.match(r"^(\d+)\s*(kB|MB|GB)?", val)
                    if m:
                        num = float(m.group(1))
                        unit = (m.group(2) or "kB").upper()
                        if unit == "MB":
                            num *= 1024
                        elif unit == "GB":
                            num *= 1024 * 1024
                        info[key] = num
        except Exception as exc:
            info["_error"] = str(exc)
    return info


def get_ps_summary():
    """Return overall memory summary using `ps` output."""
    stdout, stderr, rc = _run(["ps", "-eo", "pid,rss,vsz,comm", "--no-headers"])
    processes = []
    total_rss = 0.0
    total_vsz = 0.0
    if rc == 0 and stdout:
        for line in stdout.splitlines():
            line = line.strip()
            if not line:
                continue
            parts = line.split(None, 3)
            if len(parts) < 4:
                continue
            try:
                pid = int(parts[0])
                rss = float(parts[1])
                vsz = float(parts[2])
                comm = parts[3]
            except ValueError:
                continue
            total_rss += rss
            total_vsz += vsz
            processes.append({
                "pid": pid,
                "rss_kb": rss,
                "vsz_kb": vsz,
                "command": comm,
            })
    else:
        # Fallback: try ps aux
        stdout2, _, rc2 = _run(["ps", "aux"])
        if rc2 == 0 and stdout2:
            lines = stdout2.splitlines()
            if lines:
                # skip header
                for line in lines[1:]:
                    parts = line.split(None, 10)
                    if len(parts) < 11:
                        continue
                    try:
                        pid = int(parts[1])
                        rss = float(parts[5])
                        vsz = float(parts[4])
                        comm = parts[10]
                    except ValueError:
                        continue
                    total_rss += rss
                    total_vsz += vsz
                    processes.append({
                        "pid": pid,
                        "rss_kb": rss,
                        "vsz_kb": vsz,
                        "command": comm,
                    })

    return {
        "total_rss_kb": total_rss,
        "total_vsz_kb": total_vsz,
        "process_count": len(processes),
        "processes": processes,
        "ps_error": stderr if rc != 0 else None,
    }


def get_top_processes(processes, top_n=10, sort_key="rss_kb"):
    """Return the top N processes sorted by sort_key descending."""
    if not processes:
        return []
    valid = [p for p in processes if sort_key in p]
    valid.sort(key=lambda p: p[sort_key], reverse=True)
    return valid[:top_n]


def build_report(top_n=10):
    """Build the full memory report dict."""
    meminfo = get_meminfo()
    ps_summary = get_ps_summary()
    top_by_rss = get_top_processes(ps_summary["processes"], top_n, "rss_kb")
    top_by_vsz = get_top_processes(ps_summary["processes"], top_n, "vsz_kb")

    total_kb = meminfo.get("MemTotal", 0)
    avail_kb = meminfo.get("MemAvailable", meminfo.get("MemFree", 0))
    free_kb = meminfo.get("MemFree", 0)
    buffers_kb = meminfo.get("Buffers", 0)
    cached_kb = meminfo.get("Cached", 0)
    swap_total_kb = meminfo.get("SwapTotal", 0)
    swap_free_kb = meminfo.get("SwapFree", 0)

    used_kb = max(total_kb - avail_kb, 0) if total_kb else ps_summary["total_rss_kb"]
    used_pct = (used_kb / total_kb * 100.0) if total_kb else 0.0
    swap_used_kb = max(swap_total_kb - swap_free_kb, 0)

    report = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "node": {
            "hostname": platform.node(),
            "platform": platform.platform(),
            "python_version": platform.python_version(),
            "pid": os.getpid(),
        },
        "memory": {
            "total_kb": total_kb,
            "available_kb": avail_kb,
            "free_kb": free_kb,
            "used_kb": used_kb,
            "used_percent": round(used_pct, 2),
            "buffers_kb": buffers_kb,
            "cached_kb": cached_kb,
            "swap_total_kb": swap_total_kb,
            "swap_free_kb": swap_free_kb,
            "swap_used_kb": swap_used_kb,
        },
        "processes_summary": {
            "total_rss_kb": ps_summary["total_rss_kb"],
            "total_vsz_kb": ps_summary["total_vsz_kb"],
            "process_count": ps_summary["process_count"],
        },
        "top_processes_by_rss": top_by_rss,
        "top_processes_by_vsz": top_by_vsz,
    }

    if ps_summary.get("ps_error"):
        report["ps_error"] = ps_summary["ps_error"]
    if meminfo.get("_error"):
        report["meminfo_error"] = meminfo["_error"]

    return report


def format_kb(kb):
    """Format KB into a human-readable string."""
    if kb is None:
        return "N/A"
    kb = float(kb)
    if kb >= 1024 * 1024:
        return f"{kb / (1024 * 1024):.2f} GB"
    if kb >= 1024:
        return f"{kb / 1024:.2f} MB"
    return f"{kb:.0f} KB"


