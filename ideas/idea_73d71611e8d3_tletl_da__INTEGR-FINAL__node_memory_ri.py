"""
Generated by runa via A2A Mesh delegation

core/memory_report.py
---------------------
A2A Mesh node memory report module.

Reports memory usage of the node based on `ps` output, including:
- Overall memory summary (total, used, free, available)
- Top processes by RSS memory usage
- A2A Mesh-related process detection (optional)

Runnable standalone:
    python3 core/memory_report.py
"""

import os
import sys
import json
import subprocess
import platform
import time
from datetime import datetime


def _run_cmd(cmd):
    """Run a shell command and return (stdout, stderr, returncode)."""
    try:
        proc = subprocess.run(
            cmd,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            check=False,
        )
        return proc.stdout, proc.stderr, proc.returncode
    except FileNotFoundError:
        return "", f"command not found: {cmd[0]}", 127
    except Exception as exc:  # pragma: no cover
        return "", str(exc), 1


def _parse_meminfo():
    """Parse /proc/meminfo on Linux. Returns dict or None."""
    if not os.path.exists("/proc/meminfo"):
        return None
    info = {}
    try:
        with open("/proc/meminfo", "r", encoding="utf-8") as fh:
            for line in fh:
                parts = line.split(":")
                if len(parts) != 2:
                    continue
                key = parts[0].strip()
                val = parts[1].strip()
                # value like "12345 kB"
                tokens = val.split()
                if not tokens:
                    continue
                try:
                    num = int(tokens[0])
                except ValueError:
                    continue
                unit = tokens[1] if len(tokens) > 1 else ""
                info[key] = {"value": num, "unit": unit}
        return info
    except Exception:
        return None


def _kb_to_human(kb):
    """Convert kilobytes to human-readable string."""
    if kb is None:
        return "N/A"
    units = ["KB", "MB", "GB", "TB"]
    val = float(kb)
    idx = 0
    while val >= 1024 and idx < len(units) - 1:
        val /= 1024.0
        idx += 1
    if idx == 0:
        return f"{int(val)} {units[idx]}"
    return f"{val:.2f} {units[idx]}"


def get_memory_summary():
    """Return a dict with memory summary info."""
    summary = {
        "platform": platform.system(),
        "node": platform.node(),
        "timestamp": datetime.utcnow().isoformat() + "Z",
        "total": None,
        "used": None,
        "free": None,
        "available": None,
        "buffers": None,
        "cached": None,
        "swap_total": None,
        "swap_used": None,
        "unit": "KB",
    }

    meminfo = _parse_meminfo()
    if meminfo:
        total = meminfo.get("MemTotal", {}).get("value")
        free = meminfo.get("MemFree", {}).get("value")
        available = meminfo.get("MemAvailable", {}).get("value")
        buffers = meminfo.get("Buffers", {}).get("value")
        cached = meminfo.get("Cached", {}).get("value")
        swap_total = meminfo.get("SwapTotal", {}).get("value")
        swap_free = meminfo.get("SwapFree", {}).get("value")

        summary["total"] = total
        summary["free"] = free
        summary["available"] = available
        summary["buffers"] = buffers
        summary["cached"] = cached
        summary["swap_total"] = swap_total
        summary["swap_used"] = (swap_total - swap_free) if (swap_total is not None and swap_free is not None) else None

        if total is not None and available is not None:
            summary["used"] = total - available
        elif total is not None and free is not None:
            summary["used"] = total - free
        return summary

    # Fallback: try `free -k` on Linux
    if platform.system() == "Linux":
        out, _, rc = _run_cmd(["free", "-k"])
        if rc == 0 and out:
            lines = out.strip().splitlines()
            for line in lines:
                parts = line.split()
                if parts and parts[0] == "Mem:":
                    try:
                        summary["total"] = int(parts[1])
                        summary["used"] = int(parts[2])
                        summary["free"] = int(parts[3])
                        if len(parts) > 6:
                            summary["available"] = int(parts[6])
                        if len(parts) > 4:
                            summary["buffers"] = int(parts[5]) if len(parts) > 5 else None
                    except (ValueError, IndexError):
                        pass
                elif parts and parts[0] == "Swap:":
                    try:
                        summary["swap_total"] = int(parts[1])
                        summary["swap_used"] = int(parts[2])
                    except (ValueError, IndexError):
                        pass
            return summary

    # Fallback: vm_stat on macOS
    if platform.system() == "Darwin":
        out, _, rc = _run_cmd(["vm_stat"])
        if rc == 0 and out:
            # crude parse
            page_size = 4096
            info = {}
            for line in out.strip().splitlines():
                if ":" in line:
                    k, v = line.split(":", 1)
                    v = v.strip().rstrip(".")
                    try:
                        info[k.strip()] = int(v)
                    except ValueError:
                        pass
            free_pages = info.get("Pages free", 0)
            active = info.get("Pages active", 0)
            inactive = info.get("Pages inactive", 0)
            wired = info.get("Pages wired down", 0)
            speculative = info.get("Pages speculative", 0)
            summary["free"] = free_pages * page_size // 1024
            summary["used"] = (active + wired) * page_size // 1024
            summary["available"] = (free_pages + inactive + speculative) * page_size // 1024
            # total via sysctl
            out2, _, _ = _run_cmd(["sysctl", "-n", "hw.memsize"])
            try:
                total_bytes = int(out2.strip())
                summary["total"] = total_bytes // 1024
            except ValueError:
                pass
            return summary

    return summary


def get_top_processes(limit=10):
    """Return top processes by RSS memory usage using `ps`."""
    # Use ps with explicit columns: pid, rss, pcpu, pmem, command
    # RSS is in KB on Linux, in KB on macOS as well (with rss).
    cmd = ["ps", "-eo", "pid,rss,pcpu,pmem,comm", "--no-headers"]
    out, _, rc = _run_cmd(cmd)
    if rc != 0 or not out:
        # macOS/BSD fallback
        cmd = ["ps", "-axo", "pid,rss,pcpu,pmem,comm"]
        out, _, rc = _run_cmd(cmd)
        if rc != 0 or not out:
            return []

    procs = []
    for line in out.strip().splitlines():
        line = line.strip()
        if not line:
            continue
        # Split into 5 fields; command may contain spaces.
        parts = line.split(None, 4)
        if len(parts) < 5:
            continue
        pid_s, rss_s, pcpu_s, pmem_s, comm = parts[0], parts[1], parts[2], parts[3], parts[4]
        try:
            pid = int(pid_s)
            rss = int(rss_s)
        except ValueError:
            continue
        try:
            pcpu = float(pcpu_s)
        except ValueError:
            pcpu = 0.0
        try:
            pmem = float(pmem_s)
        except ValueError:
            pmem = 0.0
        procs.append({
            "pid": pid,
            "rss_kb": rss,
            "rss_human": _kb_to_human(rss),
            "pcpu": pcpu,
            "pmem": pmem,
            "command": comm,
        })

    procs.sort(key=lambda p: p["rss_kb"], reverse=True)
    return procs[:limit]


def detect_mesh_processes(procs):
    """Identify processes that look like A2A Mesh nodes."""
    keywords = ["a2a_mesh", "a2a-mesh", "mesh_node", "runa", "core/node"]
    detected = []
    for p in procs:
        cmd_lower = p["command"].lower()
        if any(kw in cmd_lower for kw in keywords):
            detected.append(p)
    return detected


def build_report(top_n=10):
    """Build the full memory report dict."""
    summary = get_memory_summary()
    top = get_top_processes(limit=top_n)
    mesh_procs = detect_mesh_processes(top)

    # Also scan ALL processes for mesh ones (in case they aren't in top)
    all_procs = get_top_processes(limit=1000)
    mesh_all = detect_mesh_processes(all_procs)

    report = {
        "schema": "a2a.mesh.memory_report.v1",
        "generated_at": datetime.utcnow().isoformat() + "Z",
        "node": {
            "hostname": platform.node(),
            "platform": platform.system(),
            "python": platform.python_version(),
        },
        "memory": summary,
        "top_processes": top,
        "mesh_processes": mesh_all,
        "stats": {
            "top_process_count": len(top),
            "mesh_process_count": len(mesh_all),
        },
    }
    return report


def format_text_report(report):
    """Render the report as human-readable text."""
    lines = []
    lines.append("=" * 64)
    lines.append("A2A Mesh - Node Memory Report")
    lines.append("=" * 64)
    lines.append(f"Generated : {report['generated_at']}")
    lines.append(f"Hostname  : {report['node']['hostname']}")
    lines.append(f"Platform  : {report['node']['platform']} (Python {report['node']['python']})")
    lines.append("")

    mem = report["memory"]
    lines.append("-" * 64)
    lines.append("Memory Summary")
    lines.append("-" * 64)
    lines.append(f"  Total     : {_kb_to_human(mem.get('total'))}")
    lines.append(f"  Used      : {_kb_to_human(mem.get('used'))}")
    lines.append(f"  Free      : {_kb_to_human(mem.get('free'))}")
    lines.append(f"  Available : {_kb_to_human(mem.get('available'))}")
    lines.append(f"  Buffers   : {_kb_to_human(mem.get('buffers'))}")
    lines.append(f"  Cached    : {_kb_to_human(mem.get('cached'))}")
    lines.append(f"  Swap Total: {_kb_to_human(mem.get('swap_total'))}")
    lines.append(f"  Swap Used : {_kb_to_human(mem.get('swap_used'))}")

    if mem.get("total") and mem.get("used") is not None:
        pct = (mem["used"] / mem["total"]) * 100.0 if mem["total"] else 0.0
        lines.append(f"  Used %    : {pct:.1f}%")
    lines.append("")

    lines.append("-" * 64)
    lines.append(f"Top {len(report['top_processes'])} Processes by RSS")
    lines.append("-" * 64)
    header = f"{'PID':>7}  {'RSS':>10}  {'%CPU':>6}  {'%MEM':>6}  COMMAND"
    lines.append(header)
    lines.append("-" * 64)
    for p in report["top_processes"]:
        lines.append(
            f"{p['pid']:>7}  {p['rss_human']:>10}  {p['pcpu']:>6.1f}  {p['pmem']:>6.1f}  {p['command']}"
        )
    lines.append("")

    lines.append("-" * 64)
    lines.append("A2A Mesh Processes Detected")
    lines.append("-" * 64)
    mesh = report.get("mesh_processes", [])
    if not mesh:
        lines.append("  (none detected)")
    else:
        for p in mesh:
            lines.append(
                f"  PID {p['pid']:>7}  RSS {p['rss_human']:>10}  {p['command']}"
            )
    lines.append("")
    lines.append("=" * 64)
    return "\n".join(lines)


def main():
    import argparse

    parser = argparse.ArgumentParser(
        description="A2A Mesh node memory report (ps-based, top processes)."
    )
    parser.add_argument(
        "--format", choices=["text", "json"], default="text",
        help="Output format (default: text)."
    )
    parser.add_argument(
        "--top", type=int, default=10,
        help="Number of top processes to show (default: 10)."
    )
    parser.add_argument(
        "--watch", type=float, default=0.0,
        help="If >0, refresh every N seconds (text format only)."
    )
    args = parser.parse_args()

    def emit():
        report = build_report(top_n=args.top)
        if args.format == "json":
            print(json.dumps(report, indent=2, ensure_ascii=False))
        else:
            print(format_text_report(report))
            sys.stdout.flush()

    if args.watch > 0 and args.format == "text":
        try:
            while True:
                emit()
                time.sleep(args.watch)
        except KeyboardInterrupt:
            print("\nStopped.")
            return 0
    else:
        emit()
    return 0


if __name__ == "__main__":
    sys.exit(main())