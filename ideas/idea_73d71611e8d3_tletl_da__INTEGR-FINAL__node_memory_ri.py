def main():
    parser = argparse.ArgumentParser(
        description="A2A Mesh node memory report module (ps-based, top processes)."
    )
    parser.add_argument(
        "--top", type=int, default=10,
        help="Number of top processes to show (default: 10)."
    )
    parser.add_argument(
        "--json", action="store_true",
        help="Output report as JSON instead of human-readable text."
    )
    parser.add_argument(
        "--watch", type=int, default=0,
        help="Refresh interval in seconds; repeats until interrupted (0 = off)."
    )
    args = parser.parse_args()

    def _emit():
        report = build_report(top_n=max(1, args.top))
        if args.json:
            print(json.dumps(report, indent=2, ensure_ascii=False))
        else:
            print_text_report(report)

    if args.watch and args.watch > 0:
        try:
            while True:
                _emit()
                print(f"\n(next refresh in {args.watch}s, Ctrl+C to stop)\n")
                time.sleep(args.watch)
        except KeyboardInterrupt:
            print("\nStopped.")
            sys.exit(0)
    else:
        _emit()


if __name__ == "__main__":
    main()