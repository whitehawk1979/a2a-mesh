"""
Generated by runa via A2A Mesh delegation

core/memory_report.py
=====================

A2A Mesh node memory report module.

Reports memory usage of running A2A Mesh node processes by parsing
`ps` output. Shows per-node RSS/VMS/CPU and the top processes by
memory consumption.

Usage:
    python3 core/memory_report.py
    python3 core/memory_report.py --top 20
    python3 core/memory_report.py --json
    python3 core/memory_report.py --watch 5
"""

import argparse
import json
import os
import re
import subprocess
import sys
import time
from datetime import datetime
from typing import Dict, List, Optional, Tuple


# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

# Keywords used to identify A2A Mesh node processes in the ps output.
NODE_KEYWORDS: Tuple[str, ...] = (
    "a2a_mesh",
    "a2a-mesh",
    "core/node",
    "core\\node",
    "runa",
    "mesh_agent",
    "mesh-agent",
)

# Default number of top processes to display.
DEFAULT_TOP = 10

# Column widths for the text table output.
COL_WIDTHS = {
    "pid": 8,
    "ppid": 8,
    "user": 12,
    "rss_mb": 10,
    "vms_mb": 10,
    "cpu": 8,
    "mem_pct": 8,
    "etime": 12,
    "command": 48,
}


# ---------------------------------------------------------------------------
# Process collection
# ---------------------------------------------------------------------------

def _run_ps() -> List[Dict[str, str]]:
    """
    Run `ps` and return a list of process dictionaries.

    Uses `ps -eo` with a custom format so we get all the fields we need
    in a predictable, parseable layout.
    """
    fmt = "pid,ppid,user,rss,vsz,pcpu,pmem,etime,comm,args"
    try:
        result = subprocess.run(
            ["ps", "-eo", fmt, "--no-headers"],
            capture_output=True,
            text=True,
            timeout=10,
            check=True,
        )
    except FileNotFoundError:
        print("ERROR: 'ps' command not found on this system.", file=sys.stderr)
        sys.exit(1)
    except subprocess.TimeoutExpired:
        print("ERROR: 'ps' command timed out.", file=sys.stderr)
        sys.exit(1)
    except subprocess.CalledProcessError as exc:
        print(f"ERROR: 'ps' failed: {exc.stderr}", file=sys.stderr)
        sys.exit(1)

    processes: List[Dict[str, str]] = []
    for line in result.stdout.splitlines():
        line = line.strip()
        if not line:
            continue
        # Split into at most 9 fields — args can contain spaces.
        parts = line.split(None, 8)
        if len(parts) < 9:
            continue
        processes.append(
            {
                "pid": parts[0],
                "ppid": parts[1],
                "user": parts[2],
                "rss_kb": parts[3],
                "vms_kb": parts[4],
                "cpu_pct": parts[5],
                "mem_pct": parts[6],
                "etime": parts[7],
                "comm": parts[8].split()[0] if parts[8] else "",
                "args": parts[8],
            }
        )
    return processes


def _is_mesh_node(proc: Dict[str, str]) -> bool:
    """Return True if the process looks like an A2A Mesh node."""
    args_lower = proc.get("args", "").lower()
    comm_lower = proc.get("comm", "").lower()
    for kw in NODE_KEYWORDS:
        # Handle both forward and backslash variants.
        kw_lower = kw.lower()
        if kw_lower in args_lower or kw_lower in comm_lower:
            return True
    # Also check if the process is running from the a2a_mesh directory.
    if "a2a_mesh" in args_lower or "a2a-mesh" in args_lower:
        return True
    return False


def _kb_to_mb(kb_str: str) -> float:
    """Convert a kilobyte string to megabytes (float)."""
    try:
        return round(int(kb_str) / 1024.0, 1)
    except (ValueError, TypeError):
        return 0.0


def collect_processes(top_n: int = DEFAULT_TOP) -> Dict[str, object]:
    """
    Collect process data and return a structured report dict.

    Returns:
        {
            "timestamp": ISO string,
            "total_processes": int,
            "mesh_nodes": [ ... ],
            "top_by_memory": [ ... ],
            "system_memory": { ... }
        }
    """
    all_procs = _run_ps()

    # --- System memory summary via /proc/meminfo (Linux) ---
    system_mem: Dict[str, object] = {}
    meminfo_path = "/proc/meminfo"
    if os.path.exists(meminfo_path):
        try:
            with open(meminfo_path, "r") as f:
                for line in f:
                    parts = line.split()
                    if len(parts) >= 2:
                        key = parts[0].rstrip(":")
                        val_kb = int(parts[1])
                        system_mem[key] = round(val_kb / 1024.0, 1)
        except (OSError, ValueError):
            pass

    # --- Enrich each process ---
    enriched: List[Dict[str, object]] = []
    for p in all_procs:
        enriched.append(
            {
                "pid": int(p["pid"]) if p["pid"].isdigit() else 0,
                "ppid": int(p["ppid"]) if p["ppid"].isdigit() else 0,
                "user": p["user"],
                "rss_mb": _kb_to_mb(p["rss_kb"]),
                "vms_mb": _kb_to_mb(p["vms_kb"]),
                "cpu_pct": float(p["cpu_pct"]) if _is_float(p["cpu_pct"]) else 0.0,
                "mem_pct": float(p["mem_pct"]) if _is_float(p["mem_pct"]) else 0.0,
                "etime": p["etime"],
                "comm": p["comm"],
                "args": p["args"],
                "is_mesh_node": _is_mesh_node(p),
            }
        )

    mesh_nodes = [p for p in enriched if p["is_mesh_node"]]
    mesh_nodes_sorted = sorted(mesh_nodes, key=lambda x: x["rss_mb"], reverse=True)

    top_by_mem = sorted(enriched, key=lambda x: x["rss_mb"], reverse=True)[:top_n]

    return {
        "timestamp": datetime.now().isoformat(timespec="seconds"),
        "total_processes": len(enriched),
        "mesh_node_count": len(mesh_nodes_sorted),
        "mesh_nodes": mesh_nodes_sorted,
        "top_by_memory": top_by_mem,
        "system_memory": system_mem,
    }


def _is_float(val: str) -> bool:
    try:
        float(val)
        return True
    except (ValueError, TypeError):
        return False


