def main() -> None:
    parser = argparse.ArgumentParser(
        description="A2A Mesh node memory report — shows memory usage of "
        "running mesh node processes and top memory consumers.",
    )
    parser.add_argument(
        "--top",
        type=int,
        default=DEFAULT_TOP,
        help=f"Number of top processes to show (default: {DEFAULT_TOP}).",
    )
    parser.add_argument(
        "--json",
        action="store_true",
        help="Output report as JSON instead of text.",
    )
    parser.add_argument(
        "--watch",
        type=int,
        metavar="SECONDS",
        default=0,
        help="Refresh the report every N seconds (Ctrl+C to stop).",
    )
    args = parser.parse_args()

    if args.watch > 0:
        watch_loop(args.top, args.watch, args.json)
        return

    report = collect_processes(args.top)

    if args.json:
        print(format_json_report(report))
    else:
        print(format_text_report(report, args.top))


if __name__ == "__main__":
    main()