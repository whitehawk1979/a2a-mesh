def main(argv: List[str]) -> int:
    """Foprogram: betolti az adatokat, riportot general es kiirja."""
    use_sample = "--sample" in argv
    use_json = "--json" in argv
    quiet = "--quiet" in argv
    no_save = "--no-save" in argv

    delegations = load_delegations()

    if not delegations and not use_sample:
        # Probalunk minta adatokkal tovabb menni, de figyelmeztetunk
        print("[INFO] Nem talalhato shared_delegations adatforras.", file=sys.stderr)
        print("[INFO] Minta adatok hasznalata demo celbol (--sample a kikapcsolashoz).", file=sys.stderr)
        delegations = _generate_sample_delegations()
    elif use_sample:
        delegations = _generate_sample_delegations()

    report = build_weekly_report(delegations)
    text_report = render_text_report(report)
    json_report = render_json_report(report)

    if not quiet:
        if use_json:
            print(json_report)
        else:
            print(text_report)

    if not no_save:
        text_path, json_path = save_report(text_report, json_report)
        if text_path and not quiet:
            print(f"\n[INFO] Szoveges riport mentve: {text_path}", file=sys.stderr)
        if json_path and not quiet:
            print(f"[INFO] JSON riport mentve: {json_path}", file=sys.stderr)

    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))