import json
import os
import sys
from datetime import datetime, timedelta
from collections import defaultdict, OrderedDict
from statistics import mean

# --- Konfiguracio ---

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHARED_DELEGATIONS_PATH = os.path.join(REPO_ROOT, "shared", "shared_delegations.json")
FALLBACK_DELEGATIONS_PATH = os.path.join(REPO_ROOT, "shared_delegations.json")
REPORT_OUTPUT_PATH = os.path.join(REPO_ROOT, "reports", "delegation_weekly_report.txt")
REPORT_OUTPUT_JSON = os.path.join(REPO_ROOT, "reports", "delegation_weekly_report.json")

# Allapotok, amiket a riportban figyelembe veszunk
KNOWN_STATUSES = ["pending", "accepted", "in_progress", "completed", "failed", "rejected", "timeout"]

# --- Adatforras kezeles ---

def _find_delegations_file():
    """Megkeresi a shared_delegations adatfajlt."""
    candidates = [
        SHARED_DELEGATIONS_PATH,
        FALLBACK_DELEGATIONS_PATH,
        os.path.join(REPO_ROOT, "data", "shared_delegations.json"),
        os.path.join(REPO_ROOT, "core", "shared_delegations.json"),
    ]
    for path in candidates:
        if os.path.isfile(path):
            return path
    return None


def _generate_sample_delegations():
    """
    Demo adatok, ha nincs meg shared_delegations fajl.
    Ez lehetove teszi a modul onallo futtatasat teszteles celjabol.
    """
    now = datetime.now()
    samples = []
    statuses = ["completed", "completed", "completed", "failed", "in_progress", "pending", "accepted", "timeout"]
    agents = ["agent_alpha", "agent_beta", "agent_gamma", "agent_delta"]

    for i in range(24):
        status = statuses[i % len(statuses)]
        created = now - timedelta(days=i % 7, hours=i % 12)
        delegation = {
            "id": f"deleg_{i:04d}",
            "task": f"task_{i}",
            "agent": agents[i % len(agents)],
            "status": status,
            "created_at": created.isoformat(),
        }
        if status in ("completed", "failed", "timeout"):
            completed = created + timedelta(minutes=5 + i * 3, seconds=i * 17)
            delegation["completed_at"] = completed.isoformat()
            if completed > now:
                delegation["completed_at"] = now.isoformat()
        samples.append(delegation)
    return samples


def load_delegations():
    """Betolti a delegaciokat a megfelelo forrasbol."""
    filepath = _find_delegations_file()
    if filepath:
        try:
            with open(filepath, "r", encoding="utf-8") as f:
                data = json.load(f)
            if isinstance(data, list):
                return data, filepath
            elif isinstance(data, dict) and "delegations" in data:
                return data["delegations"], filepath
            elif isinstance(data, dict):
                return list(data.values()), filepath
            else:
                print(f"[WARN] Nem varott adatformatum a {filepath} fajlban, demo adatokat hasznalok.")
                return _generate_sample_delegations(), None
        except (json.JSONDecodeError, IOError) as e:
            print(f"[WARN] Hiba a {filepath} beolvasasakor: {e}. Demo adatokat hasznalok.")
            return _generate_sample_delegations(), None
    else:
        print("[INFO] Nem talalhato shared_delegations fajl. Demo adatok generalasa teszteleshez.")
        return _generate_sample_delegations(), None


# --- Riport generator ---

def _parse_datetime(value):
    """Biztonsagos datum-ido parser."""
    if value is None:
        return None
    if isinstance(value, datetime):
        return value
    if isinstance(value, str):
        for fmt in (
            "%Y-%m-%dT%H:%M:%S.%f",
            "%Y-%m-%dT%H:%M:%S",
            "%Y-%m-%d %H:%M:%S",
            "%Y-%m-%d",
        ):
            try:
                return datetime.strptime(value.replace("Z", ""), fmt)
            except ValueError:
                continue
    return None


def _filter_this_week(delegations, reference_date=None):
    """Kivalogatja az aktualis heti delegaciokat."""
    if reference_date is None:
        reference_date = datetime.now()
    week_start = reference_date - timedelta(days=reference_date.weekday())
    week_start = week_start.replace(hour=0, minute=0, second=0, microsecond=0)
    week_end = week_start + timedelta(days=7)

    weekly = []
    for d in delegations:
        created = _parse_datetime(d.get("created_at"))
        if created is None:
            continue
        if week_start <= created < week_end:
            weekly.append(d)
    return weekly, week_start, week_end


def _compute_avg_execution_time(delegations):
    """Atlagos vegrehajtasi ido (percben) a befejezett feladatoknal."""
    durations = []
    for d in delegations:
        status = d.get("status", "").lower()
        if status not in ("completed", "failed", "timeout"):
            continue
        created = _parse_datetime(d.get("created_at"))
        completed = _parse_datetime(d.get("completed_at"))
        if created is None or completed is None:
            continue
        if completed < created:
            continue
        delta_minutes = (completed - created).total_seconds() / 60.0
        durations.append(delta_minutes)
    if not durations:
        return 0.0, 0, 0.0, 0.0
    return mean(durations), len(durations), min(durations), max(durations)


def _count_by_status(delegations):
    """Szamolja a feladatokat allapot szerint."""
    counts = OrderedDict()
    for s in KNOWN_STATUSES:
        counts[s] = 0
    other = 0
    for d in delegations:
        status = d.get("status", "unknown").lower()
        if status in counts:
            counts[status] += 1
        else:
            other += 1
    if other > 0:
        counts["other"] = other
    return counts


def _count_by_agent(delegations):
    """Szamolja a feladatokat agent szerint."""
    counts = defaultdict(int)
    for d in delegations:
        agent = d.get("agent", d.get("delegate", "unknown"))
        counts[agent] += 1
    return dict(sorted(counts.items(), key=lambda x: -x[1]))


def generate_report(delegations, reference_date=None):
    """Osszeallitja a heti riportot dict formaban."""
    if reference_date is None:
        reference_date = datetime.now()

    weekly, week_start, week_end = _filter_this_week(delegations, reference_date)
    status_counts = _count_by_status(weekly)
    agent_counts = _count_by_agent(weekly)
    avg_time, completed_count, min_time, max_time = _compute_avg_execution_time(weekly)

    total = len(weekly)
    completed = status_counts.get("completed", 0)
    failed = status_counts.get("failed", 0) + status_counts.get("timeout", 0)
    success_rate = (completed / total * 100) if total > 0 else 0.0

    report = {
        "report_type": "weekly_delegation_report",
        "generated_at": reference_date.isoformat(),
        "week_start": week_start.isoformat(),
        "week_end": week_end.isoformat(),
        "summary": {
            "total_delegations": total,
            "completed": completed,
            "failed_or_timeout": failed,
            "success_rate_percent": round(success_rate, 2),
        },
        "by_status": dict(status_counts),
        "by_agent": agent_counts,
        "execution_time_minutes": {
            "average": round(avg_time, 2),
            "min": round(min_time, 2),
            "max": round(max_time, 2),
            "sample_count": completed_count,
        },
    }
    return report


def format_report_text(report):
    """Szoveges (human-readable) riport formatum."""
    lines = []
    lines.append("=" * 70)
    lines.append("  HETI DELEGACIO RIPORT")
    lines.append("=" * 70)
    lines.append("")
    lines.append(f"  Generalva:        {report['generated_at']}")
    lines.append(f"  Het idoszak:      {report['week_start']}  ->  {report['week_end']}")
    lines.append("")
    lines.append("-" * 70)
    lines.append("  OSSZEGZO ADATOK")
    lines.append("-" * 70)
    s = report["summary"]
    lines.append(f"  Osszes delegacio:       {s['total_delegations']}")
    lines.append(f"  Befejezett (completed): {s['completed']}")
    lines.append(f"  Sikertelen/timeout:     {s['failed_or_timeout']}")
    lines.append(f"  Sikeressegi ar:         {s['success_rate_percent']}%")
    lines.append("")
    lines.append("-" * 70)
    lines.append("  FELADATOK SZAMA ALLAPOT SZERINT")
    lines.append("-" * 70)
    for status, count in report["by_status"].items():
        marker = " *" if count > 0 else ""
        lines.append(f"  {status:<20s} {count:>6d}{marker}")
    lines.append("")
    lines.append("-" * 70)
    lines.append("  FELADATOK SZAMA AGENT SZERINT")
    lines.append("-" * 70)
    if report["by_agent"]:
        for agent, count in report["by_agent"].items():
            lines.append(f"  {agent:<25s} {count:>6d}")
    else:
        lines.append("  (nincs adat)")
    lines.append("")
    lines.append("-" * 70)
    lines.append("  ATLAGOS VEGREHAJTASI IDO (percben)")
    lines.append("-" * 70)
    et = report["execution_time_minutes"]
    lines.append(f"  Atlag:     {et['average']}")
    lines.append(f"  Minimum:   {et['min']}")
    lines.append(f"  Maximum:   {et['max']}")
    lines.append(f"  Meresek:   {et['sample_count']} db")
    lines.append("")
    lines.append("=" * 70)
    lines.append("  Riport vege")
    lines.append("=" * 70)
    return "\n".join(lines)


def save_report(report, text_report):
    """Elmenti a riportot fajlba (szoveges + JSON)."""
    reports_dir = os.path.join(REPO_ROOT, "reports")
    os.makedirs(reports_dir, exist_ok=True)

    with open(REPORT_OUTPUT_PATH, "w", encoding="utf-8") as f:
        f.write(text_report)
    print(f"[OK] Szoveges riport mentve: {REPORT_OUTPUT_PATH}")

    with open(REPORT_OUTPUT_JSON, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2, ensure_ascii=False)
    print(f"[OK] JSON riport mentve:    {REPORT_OUTPUT_JSON}")


# --- Main ---

def main():
    print(">>> Heti delegacio riport generator")
    print(f">>> Repo root: {REPO_ROOT}")
    print()

    delegations, source_path = load_delegations()
