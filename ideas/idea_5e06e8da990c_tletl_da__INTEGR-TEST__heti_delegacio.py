def render_text_report(report: Dict[str, Any]) -> str:
    """Szoveges riportot general."""
    lines: List[str] = []
    sep = "=" * 72

    lines.append(sep)
    lines.append("  HETI DELEGACIO RIPORT  |  A2A Mesh")
    lines.append(f"  Generalva: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}")
    lines.append(sep)
    lines.append("")

    overall = report["overall"]
    if overall["total"] == 0:
        lines.append("  Nincs feldolgozhato delegacio az adatforrasban.")
        lines.append("")
        lines.append("  Vart adatforrasok:")
        for src in DATA_SOURCES:
            lines.append(f"    - {src}")
        lines.append("")
        lines.append(sep)
        return "\n".join(lines)

    # Osszesites
    lines.append("  >> OSSZESITES")
    lines.append("-" * 72)
    lines.append(f"  Osszes delegacio:        {overall['total']}")
    lines.append(f"  Sikeresen vegrehajtva:   {overall['completed_count']}")
    lines.append(f"  Sikeressegi arany:       {overall['success_rate']:.1f}%")
    avg = overall["avg_execution_time"]
    lines.append(f"  Atlagos vegrehajtasi ido: {format_duration(avg) if avg is not None else 'N/A'}")
    lines.append("")

    lines.append("  Statusz szerinti eloszlas (osszes):")
    for status, count in overall["by_status"].most_common():
        pct = count / overall["total"] * 100.0
        bar = "#" * int(pct / 2)
        lines.append(f"    {status:<16} {count:>5}  ({pct:5.1f}%)  {bar}")
    lines.append("")

    lines.append("  Agent szerinti eloszlas (osszes):")
    for agent, count in overall["by_agent"].most_common():
        pct = count / overall["total"] * 100.0
        lines.append(f"    {agent:<20} {count:>5}  ({pct:5.1f}%)")
    lines.append("")

    # Heti bontas
    lines.append(sep)
    lines.append("  >> HETI BONTAS")
    lines.append(sep)
    lines.append("")

    for key in report["weeks_sorted"]:
        w = report["weeks"][key]
        start_str = w["start"].strftime("%Y-%m-%d") if w["start"] else "?"
        end_str = (w["end"] - timedelta(days=1)).strftime("%Y-%m-%d") if w["end"] else "?"
        lines.append(f"  {w['label']}  ({start_str} .. {end_str})")
        lines.append(f"    Osszes feladat: {w['total']}")
        lines.append(f"    Vegrehajtva:    {w['completed_count']}")
        avg_t = w["avg_execution_time"]
        min_t = w["min_execution_time"]
        max_t = w["max_execution_time"]
        lines.append(
            f"    Atlagos ido:    {format_duration(avg_t) if avg_t is not None else 'N/A'}  "
            f"(min: {format_duration(min_t) if min_t is not None else 'N/A'}, "
            f"max: {format_duration(max_t) if max_t is not None else 'N/A'})"
        )
        lines.append("    Statuszok:")
        for status, count in w["by_status"].most_common():
            lines.append(f"      {status:<16} {count:>4}")
        lines.append("")

    lines.append(sep)
    lines.append("  Riport vege.")
    lines.append(sep)
    return "\n".join(lines)


def render_json_report(report: Dict[str, Any]) -> str:
    """JSON formatumu riportot general (szerializalhato)."""
    def serialize_counter(c: Counter) -> Dict[str, int]:
        return dict(c.most_common())

    def serialize_dt(dt: Optional[datetime]) -> Optional[str]:
        if dt is None:
            return None
        return dt.isoformat()

    out = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "overall": {
            "total": report["overall"]["total"],
            "completed_count": report["overall"]["completed_count"],
            "success_rate": round(report["overall"]["success_rate"], 2),
            "avg_execution_time_seconds": (
                round(report["overall"]["avg_execution_time"], 2)
                if report["overall"]["avg_execution_time"] is not None else None
            ),
            "by_status": serialize_counter(report["overall"]["by_status"]),
            "by_agent": serialize_counter(report["overall"]["by_agent"]),
        },
        "weeks": {},
    }

    for key in report["weeks_sorted"]:
        w = report["weeks"][key]
        out["weeks"][key] = {
            "label": w["label"],
            "start": serialize_dt(w["start"]),
            "end": serialize_dt(w["end"]),
            "total": w["total"],
            "completed_count": w["completed_count"],
            "avg_execution_time_seconds": (
                round(w["avg_execution_time"], 2) if w["avg_execution_time"] is not None else None
            ),
            "min_execution_time_seconds": (
                round(w["min_execution_time"], 2) if w["min_execution_time"] is not None else None
            ),
            "max_execution_time_seconds": (
                round(w["max_execution_time"], 2) if w["max_execution_time"] is not None else None
            ),
            "by_status": serialize_counter(w["by_status"]),
            "by_agent": serialize_counter(w["by_agent"]),
        }

    return json.dumps(out, indent=2, ensure_ascii=False)


def save_report(text: str, json_str: str) -> Tuple[Optional[Path], Optional[Path]]:
    """Riportokat fajlba menti a reports/ konyvtarba."""
    reports_dir = REPO_ROOT / "reports"
    try:
        reports_dir.mkdir(parents=True, exist_ok=True)
    except OSError:
        return None, None

    ts = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")
    text_path = reports_dir / f"delegation_report_{ts}.txt"
    json_path = reports_dir / f"delegation_report_{ts}.json"

    try:
        text_path.write_text(text, encoding="utf-8")
    except OSError:
        text_path = None
    try:
        json_path.write_text(json_str, encoding="utf-8")
    except OSError:
        json_path = None

    return text_path, json_path


