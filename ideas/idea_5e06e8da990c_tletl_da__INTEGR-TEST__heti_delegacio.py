def _parse_timestamp(value: Any) -> Optional[datetime]:
    """Tetszoleges timestamp formatumot datetime-ma alakit."""
    if value is None:
        return None
    if isinstance(value, (int, float)):
        # Epoch masodperc vagy millisec
        if value > 1e12:
            value = value / 1000.0
        try:
            return datetime.fromtimestamp(value, tz=timezone.utc)
        except (OverflowError, OSError, ValueError):
            return None
    if isinstance(value, str):
        # ISO formatum
        for fmt in (
            "%Y-%m-%dT%H:%M:%S.%fZ",
            "%Y-%m-%dT%H:%M:%SZ",
            "%Y-%m-%dT%H:%M:%S.%f",
            "%Y-%m-%dT%H:%M:%S",
            "%Y-%m-%d %H:%M:%S",
            "%Y-%m-%d",
        ):
            try:
                dt = datetime.strptime(value, fmt)
                if dt.tzinfo is None:
                    dt = dt.replace(tzinfo=timezone.utc)
                return dt
            except ValueError:
                continue
        # fromisoformat (Python 3.7+)
        try:
            dt = datetime.fromisoformat(value.replace("Z", "+00:00"))
            if dt.tzinfo is None:
                dt = dt.replace(tzinfo=timezone.utc)
            return dt
        except (ValueError, AttributeError):
            return None
    return None


def _normalize_delegation(raw: Dict[str, Any]) -> Dict[str, Any]:
    """Egy delegacio rekordot normalizal."""
    # Statusz
    status = (
        raw.get("status")
        or raw.get("state")
        or raw.get("result", {}).get("status") if isinstance(raw.get("result"), dict) else None
        or "unknown"
    )
    status = str(status).lower().strip()

    # Idobelyegek
    created = (
        raw.get("created_at")
        or raw.get("createdAt")
        or raw.get("started_at")
        or raw.get("submitted_at")
        or raw.get("timestamp")
    )
    completed = (
        raw.get("completed_at")
        or raw.get("completedAt")
        or raw.get("finished_at")
        or raw.get("resolved_at")
        or raw.get("ended_at")
    )
    if not completed and isinstance(raw.get("result"), dict):
        completed = raw["result"].get("completed_at") or raw["result"].get("timestamp")

    created_dt = _parse_timestamp(created)
    completed_dt = _parse_timestamp(completed)

    # Azonosito
    deleg_id = (
        raw.get("id")
        or raw.get("delegation_id")
        or raw.get("delegationId")
        or raw.get("task_id")
        or "<unknown>"
    )

    # Agent
    agent = (
        raw.get("agent")
        or raw.get("agent_id")
        or raw.get("delegate")
        or raw.get("target")
        or "<unknown>"
    )

    # Feladat leiras
    task = (
        raw.get("task")
        or raw.get("description")
        or raw.get("prompt")
        or raw.get("message")
        or ""
    )
    if isinstance(task, dict):
        task = task.get("description") or task.get("text") or str(task)
    task = str(task)[:80]

    return {
        "id": str(deleg_id),
        "status": status,
        "agent": str(agent),
        "task": task,
        "created_at": created_dt,
        "completed_at": completed_dt,
        "raw": raw,
    }


def load_delegations() -> List[Dict[str, Any]]:
    """Betolti a shared_delegations adatokat a repobol."""
    for source in DATA_SOURCES:
        if not source.exists():
            continue
        try:
            with open(source, "r", encoding="utf-8") as f:
                data = json.load(f)
        except (json.JSONDecodeError, OSError) as exc:
            print(f"[WARN] Nem sikerult olvasni: {source} ({exc})", file=sys.stderr)
            continue

        # Adat lehet lista vagy dict (pl. {"delegations": [...]} vagy {"items": [...]})
        if isinstance(data, list):
            items = data
        elif isinstance(data, dict):
            items = (
                data.get("delegations")
                or data.get("items")
                or data.get("records")
                or data.get("data")
                or []
            )
            if not items and all(k in data for k in ("id", "status")):
                items = [data]
        else:
            items = []

        normalized = []
        for raw in items:
            if not isinstance(raw, dict):
                continue
            try:
                normalized.append(_normalize_delegation(raw))
            except Exception as exc:
                print(f"[WARN] Hibas rekord atugorva: {exc}", file=sys.stderr)
        return normalized

    return []


def _generate_sample_delegations() -> List[Dict[str, Any]]:
    """Minta adatok, ha nincs valós adatforras (demo cel)."""
    now = datetime.now(timezone.utc)
    samples = []
    statuses_cycle = ["completed", "completed", "completed", "failed", "in_progress", "pending", "completed"]
    agents = ["agent_alpha", "agent_beta", "agent_gamma", "agent_delta"]

    for i in range(28):
        created = now - timedelta(days=i, hours=(i % 12))
        status = statuses_cycle[i % len(statuses_cycle)]
        completed = None
        if status in COMPLETED_STATUSES or status == "failed":
            completed = created + timedelta(minutes=5 + (i % 40))
        samples.append({
            "id": f"deleg_{i:04d}",
            "status": status,
            "agent": agents[i % len(agents)],
            "task": f"Sample delegation task #{i}",
            "created_at": created,
            "completed_at": completed,
            "raw": {},
        })
    return samples


