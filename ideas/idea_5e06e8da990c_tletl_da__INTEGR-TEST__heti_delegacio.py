def _iso_week(dt: datetime) -> Tuple[int, int]:
    """Visszaadja (ev, het) szamot."""
    iso = dt.isocalendar()
    return (iso[0], iso[1])


def _week_label(year: int, week: int) -> str:
    return f"{year}-W{week:02d}"


def _week_start(year: int, week: int) -> datetime:
    """A het elso napja (hetfo) UTC-ben."""
    # Jan 4 mindig az 1. hetben van ISO szerint
    jan4 = datetime(year, 1, 4, tzinfo=timezone.utc)
    week1_monday = jan4 - timedelta(days=jan4.weekday())
    return week1_monday + timedelta(weeks=week - 1)


def compute_execution_time_seconds(deleg: Dict[str, Any]) -> Optional[float]:
    """Vegrehajtasi ido masodpercben, ha szamithato."""
    c = deleg.get("created_at")
    f = deleg.get("completed_at")
    if not c or not f:
        return None
    delta = (f - c).total_seconds()
    if delta < 0:
        return None
    return delta


def format_duration(seconds: float) -> str:
    """Masodpercet olvashato idotartamma alakit."""
    if seconds is None:
        return "N/A"
    if seconds < 60:
        return f"{seconds:.1f}s"
    if seconds < 3600:
        return f"{seconds / 60:.1f}m"
    if seconds < 86400:
        return f"{seconds / 3600:.2f}h"
    return f"{seconds / 86400:.2f}d"


def build_weekly_report(delegations: List[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Heti riportot epit a delegaciokbol.

    Visszateresi struktura:
    {
        "weeks": {
            "2025-W03": {
                "label": str,
                "start": datetime,
                "end": datetime,
                "total": int,
                "by_status": Counter,
                "by_agent": Counter,
                "completed_count": int,
                "execution_times": [float, ...],
                "avg_execution_time": Optional[float],
                "min_execution_time": Optional[float],
                "max_execution_time": Optional[float],
            },
            ...
        },
        "overall": {
            "total": int,
            "by_status": Counter,
            "by_agent": Counter,
            "completed_count": int,
            "avg_execution_time": Optional[float],
            "success_rate": float,
        },
        "weeks_sorted": [str, ...],
    }
    """
    weeks: Dict[str, Dict[str, Any]] = defaultdict(lambda: {
        "label": "",
        "start": None,
        "end": None,
        "total": 0,
        "by_status": Counter(),
        "by_agent": Counter(),
        "completed_count": 0,
        "execution_times": [],
        "avg_execution_time": None,
        "min_execution_time": None,
        "max_execution_time": None,
    })

    overall_status = Counter()
    overall_agent = Counter()
    overall_exec_times: List[float] = []
    overall_completed = 0
    total = 0

    for deleg in delegations:
        total += 1
        status = deleg["status"]
        agent = deleg["agent"]
        overall_status[status] += 1
        overall_agent[agent] += 1

        created = deleg.get("created_at")
        if created is None:
            # Ha nincs idobelyeg, az aktualis hetbe rakjuk
            created = datetime.now(timezone.utc)
            deleg = {**deleg, "created_at": created}

        year, week = _iso_week(created)
        key = _week_label(year, week)
        w = weeks[key]
        w["label"] = key
        w["total"] += 1
        w["by_status"][status] += 1
        w["by_agent"][agent] += 1

        ws = _week_start(year, week)
        we = ws + timedelta(days=7)
        if w["start"] is None or ws < w["start"]:
            w["start"] = ws
        if w["end"] is None or we > w["end"]:
            w["end"] = we

        exec_time = compute_execution_time_seconds(deleg)
        if exec_time is not None and status in COMPLETED_STATUSES:
            w["completed_count"] += 1
            w["execution_times"].append(exec_time)
            overall_completed += 1
            overall_exec_times.append(exec_time)
        elif exec_time is not None and status in COMPLETED_STATUSES:
            w["completed_count"] += 1
            overall_completed += 1
            overall_exec_times.append(exec_time)

    # Heti aggregaciok
    for key, w in weeks.items():
        times = w["execution_times"]
        if times:
            w["avg_execution_time"] = statistics.mean(times)
            w["min_execution_time"] = min(times)
            w["max_execution_time"] = max(times)

    overall_avg = statistics.mean(overall_exec_times) if overall_exec_times else None
    success_rate = (overall_completed / total * 100.0) if total > 0 else 0.0

    weeks_sorted = sorted(weeks.keys())

    return {
        "weeks": dict(weeks),
        "overall": {
            "total": total,
            "by_status": overall_status,
            "by_agent": overall_agent,
            "completed_count": overall_completed,
            "avg_execution_time": overall_avg,
            "success_rate": success_rate,
        },
        "weeks_sorted": weeks_sorted,
    }


