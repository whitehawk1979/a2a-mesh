def _format_bytes(n: int) -> str:
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024:
            return f"{n:.1f} {unit}"
        n /= 1024
    return f"{n:.1f} TB"


def print_summary(report: StatsReport) -> None:
    """Olvashato osszefoglalo nyomtatasa a stdout-ra."""
    print("=" * 60)
    print("  A2A Mesh — P2P Statistics Summary")
    print("=" * 60)
    print(f"  Generated:    {report.generated_at}")
    print(f"  Total msgs:   {report.total_messages}")
    print(f"  Total bytes:  {_format_bytes(report.total_bytes)}")
    print(f"  Unique nodes: {report.unique_nodes}")
    if report.time_range:
        print(f"  Time range:   {report.time_range['earliest']} .. {report.time_range['latest']}")
    print("-" * 60)

    print("  By message type:")
    for t, c in sorted(report.by_type.items(), key=lambda x: -x[1]):
        bts = report.by_type_bytes.get(t, 0)
        print(f"    {t:<20s}  count={c:<6d}  bytes={_format_bytes(bts)}")

    print("-" * 60)
    print("  By status:")
    for s, c in sorted(report.by_status.items(), key=lambda x: -x[1]):
        print(f"    {s:<20s}  count={c}")

    print("-" * 60)
    print("  Top node pairs:")
    for entry in report.top_pairs[:5]:
        print(f"    {entry['pair']:<30s}  count={entry['count']}")

    print("-" * 60)
    print("  By source node:")
    for s, c in sorted(report.by_source.items(), key=lambda x: -x[1]):
        print(f"    {s:<20s}  sent={c}")

    print("  By target node:")
    for t, c in sorted(report.by_target.items(), key=lambda x: -x[1]):
        print(f"    {t:<20s}  recv={c}")

    print("=" * 60)


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description="A2A Mesh p2p statisztika osszefoglalo (JSON riport)."
    )
    parser.add_argument(
        "--logs-dir",
        type=str,
        default="./logs",
        help="Log konyvtar (.jsonl / .log fajlok). Alapertelmezett: ./logs",
    )
    parser.add_argument(
        "--output", "-o",
        type=str,
        default=None,
        help="JSON riport fajl neve (ha nincs megadva, stdout-ra ir).",
    )
    parser.add_argument(
        "--pretty",
        action="store_true",
        help="Pretty-print JSON (2-space indent).",
    )
    parser.add_argument(
        "--demo",
        action="store_true",
        help="Demo adatok hasznalata (log konyvtar ignorálása).",
    )
    parser.add_argument(
        "--summary",
        action="store_true",
        help="Olvashato osszefoglalo nyomtatasa a JSON melle.",
    )

    args = parser.parse_args(argv)

    # Adatok betoltese
    if args.demo:
        records = load_demo_records()
    else:
        logs_dir = Path(args.logs_dir)
        records = load_records(logs_dir)
        if not records:
            # Ha nincs log, probálkozunk a demo adatokkal, de jelzeljuk
            records = load_demo_records()
            print(
                f"[info] Nem talalhato log a '{args.logs_dir}' konyvtarban. "
                "Demo adatok hasznalata.",
                file=sys.stderr,
            )

    # Riport epites
    report = build_report(records)
    report_dict = report.to_dict()

    # JSON kimenet
    indent = 2 if args.pretty else None
    json_str = json.dumps(report_dict, ensure_ascii=False, indent=indent)

    if args.output:
        out_path = Path(args.output)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        with open(out_path, "w", encoding="utf-8") as fh:
            fh.write(json_str)
            if indent:
                fh.write("\n")
        print(f"[info] Riport mentve: {out_path}", file=sys.stderr)
    else:
        print(json_str)

    # Osszefoglalo (opcionális)
    if args.summary:
        print_summary(report)

    return 0


if __name__ == "__main__":
    sys.exit(main())