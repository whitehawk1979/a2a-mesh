def build_report(records: List[MessageRecord]) -> StatsReport:
    """MessageRecord listabol epiti fel az osszefoglalo riportot."""
    by_type: Counter = Counter()
    by_status: Counter = Counter()
    by_source: Counter = Counter()
    by_target: Counter = Counter()
    by_pair: Counter = Counter()
    by_type_bytes: Dict[str, int] = defaultdict(int)

    nodes: set = set()
    total_bytes = 0
    timestamps: List[str] = []

    for rec in records:
        by_type[rec.msg_type] += 1
        by_status[rec.status] += 1
        by_source[rec.source] += 1
        by_target[rec.target] += 1
        pair_key = f"{rec.source}->{rec.target}"
        by_pair[pair_key] += 1
        by_type_bytes[rec.msg_type] += rec.size_bytes
        total_bytes += rec.size_bytes
        nodes.add(rec.source)
        nodes.add(rec.target)
        if rec.timestamp:
            timestamps.append(rec.timestamp)

    time_range = None
    if timestamps:
        timestamps.sort()
        time_range = {"earliest": timestamps[0], "latest": timestamps[-1]}

    top_pairs = [
        {"pair": p, "count": c}
        for p, c in by_pair.most_common(10)
    ]
    top_types = [
        {"type": t, "count": c, "bytes": by_type_bytes.get(t, 0)}
        for t, c in by_type.most_common(10)
    ]

    return StatsReport(
        generated_at=datetime.now(timezone.utc).isoformat(),
        total_messages=len(records),
        total_bytes=total_bytes,
        unique_nodes=len(nodes),
        by_type=dict(by_type),
        by_status=dict(by_status),
        by_source=dict(by_source),
        by_target=dict(by_target),
        by_pair=dict(by_pair),
        by_type_bytes=dict(by_type_bytes),
        time_range=time_range,
        top_pairs=top_pairs,
        top_types=top_types,
    )


