@dataclass
class MessageRecord:
    """Egy p2p uzenet rekordja a logbol."""
    timestamp: str
    source: str
    target: str
    msg_type: str
    size_bytes: int = 0
    status: str = "ok"


@dataclass
class StatsReport:
    """Osszefoglalo riport."""
    generated_at: str
    total_messages: int
    total_bytes: int
    unique_nodes: int
    by_type: Dict[str, int] = field(default_factory=dict)
    by_status: Dict[str, int] = field(default_factory=dict)
    by_source: Dict[str, int] = field(default_factory=dict)
    by_target: Dict[str, int] = field(default_factory=dict)
    by_pair: Dict[str, int] = field(default_factory=dict)
    by_type_bytes: Dict[str, int] = field(default_factory=dict)
    time_range: Optional[Dict[str, str]] = None
    top_pairs: List[Dict[str, Any]] = field(default_factory=list)
    top_types: List[Dict[str, Any]] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


