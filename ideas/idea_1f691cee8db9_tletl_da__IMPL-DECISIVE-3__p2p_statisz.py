def _parse_log_line(line: str) -> Optional[MessageRecord]:
    """Egy JSON-lines log bejegyzest MessageRecord-da alakit."""
    line = line.strip()
    if not line:
        return None
    try:
        obj = json.loads(line)
    except json.JSONDecodeError:
        return None

    # Tobb lehetséges mezo-nevet is elfogadunk
    source = obj.get("source") or obj.get("from") or obj.get("src") or "unknown"
    target = obj.get("target") or obj.get("to") or obj.get("dst") or "unknown"
    msg_type = obj.get("type") or obj.get("msg_type") or obj.get("message_type") or "unknown"
    timestamp = obj.get("timestamp") or obj.get("ts") or obj.get("time") or ""
    size_bytes = int(obj.get("size_bytes", obj.get("size", 0)) or 0)
    status = obj.get("status", "ok") or "ok"

    return MessageRecord(
        timestamp=timestamp,
        source=str(source),
        target=str(target),
        msg_type=str(msg_type),
        size_bytes=size_bytes,
        status=str(status),
    )


def load_records(logs_dir: Path) -> List[MessageRecord]:
    """Betolti az osszes .jsonl / .log fajlt a konyvtarbol."""
    records: List[MessageRecord] = []
    if not logs_dir.exists():
        return records

    patterns = ("*.jsonl", "*.log", "*.ndjson")
    files: List[Path] = []
    for pat in patterns:
        files.extend(logs_dir.glob(pat))

    for fpath in sorted(files):
        try:
            with open(fpath, "r", encoding="utf-8", errors="replace") as fh:
                for line in fh:
                    rec = _parse_log_line(line)
                    if rec is not None:
                        records.append(rec)
        except OSError:
            continue

    return records


