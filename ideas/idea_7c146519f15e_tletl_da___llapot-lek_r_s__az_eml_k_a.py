class StateValidator:
    """
    A központi validátor: egy Marker state_check-jét lekérdezi a valós
    rendszertől, és összehasonlítja a jelöléssel.

    A Pimasz-eljárás: mielőtt egy leírt kérdést újra nyitottként kezelek,
    meg kell neveznem, MI VÁLTOZOTT VOLNA, és azt kell lekérdezni.
    """

    def __init__(self, markers: Optional[list[Marker]] = None):
        self.markers: dict[str, Marker] = {}
        if markers:
            for m in markers:
                self.markers[m.marker_id] = m
        self.log: list[dict] = []

    def add_marker(self, marker: Marker) -> None:
        self.markers[marker.marker_id] = marker

    def _log(self, marker_id: str, result: ValidationResult,
             real_value: Any, detail: str) -> None:
        entry = {
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "marker_id": marker_id,
            "result": result.value,
            "real_value": str(real_value),
            "detail": detail,
        }
        self.log.append(entry)
        print(f"  [validate] {marker_id}: {result.value} | {detail}")

    def validate_marker(self, marker: Marker) -> ValidationResult:
        """
        Egyetlen marker valós állapotának lekérdezése és összehasonlítása.
        """
        if marker.state_check is None:
            result = ValidationResult.NO_CHECK_DEFINED
            marker.last_validation = result
            marker.last_validated_at = time.time()
            self._log(marker.marker_id, result, None,
                      "nincs state_check definiálva — óvatosan nyitottként")
            return result

        check = marker.state_check
        real_value: Any = None

        if check.check_type == CheckType.CONFIG_VALUE:
            real_value = query_config_value(
                check.config_path or "", check.config_key or "")
            detail = (f"config[{check.config_path}]:{check.config_key} "
                      f"= {real_value!r} (várt nyitott: {check.open_value!r})")

        elif check.check_type == CheckType.FILE_MTIME:
            real_value = query_file_mtime(check.file_path or "")
            changed = (real_value is not None
                       and check.recorded_mtime is not None
                       and real_value > check.recorded_mtime)
            detail = (f"file[{check.file_path}] mtime={real_value} "
                      f"(rögzített: {check.recorded_mtime}, "
                      f"változott: {changed})")

        elif check.check_type == CheckType.API_RESPONSE:
            real_value = query_api_response(
                check.api_url or "", check.api_json_path or "",
                timeout=check.timeout)
            detail = (f"api[{check.api_url}]:{check.api_json_path} "
                      f"= {real_value!r} (várt nyitott: {check.open_value!r})")

        marker.last_real_value = real_value

        # --- Értékelés ---
        if real_value is None:
            result = ValidationResult.CHECK_FAILED
            self._log(marker.marker_id, result, real_value,
                      f"lekérdezés sikertelen — {detail}")
            marker.last_validation = result
            marker.last_validated_at = time.time()
            return result

        if check.check_type == CheckType.FILE_MTIME:
            # mtime esetén: ha a fájl újabb, mint a rögzített, akkor
            # a mögöttes állapot megváltozott (megválaszolva / módosítva)
            changed = (check.recorded_mtime is not None
                       and real_value > check.recorded_mtime)
            if marker.status == MarkerStatus.OPEN:
                result = (ValidationResult.STILL_OPEN if not changed
                          else ValidationResult.RESOLVED)
            else:
                result = (ValidationResult.STILL_CLOSED if not changed
                          else ValidationResult.REOPENED)
        else:
            # config / api: ha a valós érték megegyezik az open_value-val,
            # akkor még nyitott; ha eltér, akkor resolved.
            is_open = (real_value == check.open_value)
            if marker.status == MarkerStatus.OPEN:
                result = (ValidationResult.STILL_OPEN if is_open
                          else ValidationResult.RESOLVED)
            else:
                result = (ValidationResult.STILL_CLOSED if not is_open
                          else ValidationResult.REOPENED)

        self._log(marker.marker_id, result, real_value, detail)
        marker.last_validation = result
        marker.last_validated_at = time.time()
        return result

    def validate_all(self) -> dict[str, ValidationResult]:
        """Az összes marker validálása."""
        results = {}
        print(f"[StateValidator] {len(self.markers)} marker validálása...")
        for marker in self.markers.values():
            results[marker.marker_id] = self.validate_marker(marker)
        return results

    def should_treat_as_open(self, marker_id: str) -> bool:
        """
        Döntés: nyitottként kell-e kezelni a markert?
        A Pimasz-eljárás szerint: csak ha a valós állapot is nyitott.
        """
        marker = self.markers.get(marker_id)
        if marker is None:
            return False

        result = self.validate_marker(marker)

        if result == ValidationResult.STILL_OPEN:
            return True
        if result == ValidationResult.REOPENED:
            return True
        if result == ValidationResult.NO_CHECK_DEFINED:
            # óvatos: nyitottként kezeljük, de figyelmeztetünk
            return marker.status == MarkerStatus.OPEN
        if result == ValidationResult.CHECK_FAILED:
            # nem tudjuk lekérdezni — óvatosan nyitottként, de logolva
            return marker.status == MarkerStatus.OPEN
        # RESOLVED vagy STILL_CLOSED -> nem nyitott
        return False

    def export_log(self, path: str) -> None:
        """Validációs log exportálása JSON-be."""
        with open(path, "w", encoding="utf-8") as f:
            json.dump(self.log, f, indent=2, ensure_ascii=False)
        print(f"[StateValidator] log exportálva: {path} ({len(self.log)} bejegyzés)")


