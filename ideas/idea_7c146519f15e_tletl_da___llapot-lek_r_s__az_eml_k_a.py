class ScheduledTaskGuard:
    """
    Cron / kanban-figyelő integráció: mielőtt egy ütemezett feladat
    egy nyitott-jelölést újra nyitottként futtat, a guard validálja
    a mögöttes valós állapotot.
    """

    def __init__(self, validator: StateValidator):
        self.validator = validator
        self.skipped: list[str] = []
        self.executed: list[str] = []

    def guard_run(self, marker_id: str, action: Callable[[], None],
                  action_name: str = "") -> bool:
        """
        Egy ütemezett feladat futtatása guard-dal.
        Csak akkor fut az action, ha a marker valós állapotban is nyitott.
        Visszatér: True ha lefutott, False ha skip-pelt.
        """
        name = action_name or marker_id
        print(f"\n[guard] '{name}' ellenőrzése (marker: {marker_id})...")

        should_open = self.validator.should_treat_as_open(marker_id)

        if should_open:
            print(f"[guard] '{name}' -> FUT (valós állapot: nyitott)")
            action()
            self.executed.append(marker_id)
            return True
        else:
            marker = self.validator.markers.get(marker_id)
            result = marker.last_validation if marker else None
            print(f"[guard] '{name}' -> SKIP (valós állapot: {result})")
            self.skipped.append(marker_id)
            return False


