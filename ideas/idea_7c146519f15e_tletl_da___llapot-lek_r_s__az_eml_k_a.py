def _get_nested(data: dict, path: str) -> Any:
    """JSON path (pl. 'data.state') kinyerése dict-ből."""
    keys = path.split(".")
    val = data
    for k in keys:
        if isinstance(val, dict) and k in val:
            val = val[k]
        else:
            return None
    return val


def query_config_value(config_path: str, key: str) -> Any:
    """
    Lekérdezi egy config-fájl (JSON) adott kulcsának értékét.
    Ha a fájl nem létezik vagy nem parse-olható, None-t ad vissza.
    """
    p = Path(config_path)
    if not p.exists():
        return None
    try:
        with open(p, "r", encoding="utf-8") as f:
            data = json.load(f)
        return data.get(key)
    except (json.JSONDecodeError, OSError):
        return None


def query_file_mtime(file_path: str) -> Optional[float]:
    """
    Lekérdezi egy fájl mtime-ját.
    Ha a fájl nem létezik, None-t ad vissza.
    """
    p = Path(file_path)
    if not p.exists():
        return None
    try:
        return p.stat().st_mtime
    except OSError:
        return None


def query_api_response(url: str, json_path: str, timeout: float = 5.0) -> Any:
    """
    Lekérdezi egy API endpoint JSON-válaszának adott path-át.
    Hiba esetén None-t ad vissza.
    """
    try:
        req = urllib.request.Request(url, headers={"Accept": "application/json"})
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            body = resp.read().decode("utf-8")
            data = json.loads(body)
            return _get_nested(data, json_path)
    except (urllib.error.URLError, urllib.error.HTTPError,
            json.JSONDecodeError, OSError, TimeoutError):
        return None


