class CheckType(Enum):
    """Milyen típusú valós állapotot ellenőrzünk a jelölés helyett."""
    CONFIG_VALUE = "config_value"
    FILE_MTIME = "file_mtime"
    API_RESPONSE = "api_response"


class MarkerStatus(Enum):
    """A jelölés eredeti státusza (amikor leírták)."""
    OPEN = "open"
    CLOSED = "closed"
    UNKNOWN = "unknown"


class ValidationResult(Enum):
    """A validáció kimenetele."""
    STILL_OPEN = "still_open"          # a jelölés nyitott ÉS a valós állapot is nyitott
    RESOLVED = "resolved"              # a jelölés nyitott, de a valós állapot már megváltozott
    STILL_CLOSED = "still_closed"      # a jelölés zárt és a valós állapot is zárt
    REOPENED = "reopened"              # a jelölés zárt, de a valós állapot újra nyitott
    CHECK_FAILED = "check_failed"      # nem sikerült lekérdezni a valós állapotot
    NO_CHECK_DEFINED = "no_check"      # nincs ellenőrzés definiálva — óvatosan nyitottként


@dataclass
class StateCheck:
    """
    Egyetlen állapot-ellenőrzés definíciója.
    Ez válaszolja meg a kérdést: "MI VÁLTOZOTT VOLNA, ha közben megválaszolják?"
    """
    check_type: CheckType
    # config_value esetén: a config fájl útvonala + a kulcs + a várt "nyitott" érték
    config_path: Optional[str] = None
    config_key: Optional[str] = None
    open_value: Any = None
    # file_mtime esetén: a fájl útvonala + a jelölés idején mért mtime
    file_path: Optional[str] = None
    recorded_mtime: Optional[float] = None
    # api_response esetén: URL + a várt "nyitott" érték (JSON path: "status")
    api_url: Optional[str] = None
    api_json_path: Optional[str] = None  # pl. "status" vagy "data.state"
    timeout: float = 5.0

    def describe_change(self) -> str:
        """Visszaadja, mi változott volna, ha a kérdés megválaszolódott."""
        if self.check_type == CheckType.CONFIG_VALUE:
            return (f"config[{self.config_path}]:{self.config_key} "
                    f"érték '{self.open_value}' -> más érték")
        elif self.check_type == CheckType.FILE_MTIME:
            return (f"file[{self.file_path}] mtime {self.recorded_mtime} "
                    f"-> újabb mtime (változás történt)")
        elif self.check_type == CheckType.API_RESPONSE:
            return (f"api[{self.api_url}]:{self.api_json_path} "
                    f"érték '{self.open_value}' -> más érték")
        return "ismeretlen"


@dataclass
class Marker:
    """
    Egy "nyitott" jelölés — az emlék, ami a múltról szól.
    A jelölés csak azt bizonyítja, hogy amikor leírták, nyitva volt.
    """
    marker_id: str
    status: MarkerStatus
    recorded_at: float  # unix timestamp, amikor a jelölést leírták
    description: str = ""
    state_check: Optional[StateCheck] = None
    # validáció eredménye (cache-elt, a legutóbbi lekérdezés idején)
    last_validation: Optional[ValidationResult] = None
    last_validated_at: Optional[float] = None
    last_real_value: Any = None


