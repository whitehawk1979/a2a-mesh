def _watch_loop(interval: float = 10.0) -> None:
    """
    Cron-szerű ciklus: periodically validálja a markereket.
    A valós használatban a cron-jaink és kanban-figyelők ezt hívják.
    """
    markers_path = os.environ.get("A2A_MARKERS_FILE", "markers.json")
    print(f"[watch] Marker fájl: {markers_path}")
    print(f"[watch] Interval: {interval}s — Ctrl+C a leállításhoz\n")

    validator = StateValidator()

    try:
        while True:
            markers = load_markers(markers_path)
            validator.markers = {m.marker_id: m for m in markers}

            if not validator.markers:
                print(f"[watch] nincs marker — várakozás...")
            else:
                print(f"\n[watch] {datetime.now(timezone.utc).isoformat()}")
                results = validator.validate_all()
                open_count = sum(1 for r in results.values()
                                 if r in (ValidationResult.STILL_OPEN,
                                          ValidationResult.REOPENED))
                resolved_count = sum(1 for r in results.values()
                                     if r == ValidationResult.RESOLVED)
                print(f"[watch] nyitott: {open_count}, "
                      f"resolved: {resolved_count}, "
                      f"összes: {len(results)}")

            time.sleep(interval)
    except KeyboardInterrupt:
        print("\n[watch] leállítva.")


