def save_markers(markers: list[Marker], path: str) -> None:
    """Markerek mentése JSON-be."""
    data = []
    for m in markers:
        d = asdict(m)
        d["status"] = m.status.value
        if m.state_check:
            d["state_check"]["check_type"] = m.state_check.check_type.value
        d.pop("last_validation", None)
        d.pop("last_validated_at", None)
        d.pop("last_real_value", None)
        data.append(d)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
    print(f"[perszisztencia] {len(markers)} marker mentve: {path}")


def load_markers(path: str) -> list[Marker]:
    """Markerek betöltése JSON-ből."""
    if not Path(path).exists():
        return []
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)
    markers = []
    for d in data:
        sc = None
        if d.get("state_check"):
            scd = d["state_check"]
            sc = StateCheck(
                check_type=CheckType(scd["check_type"]),
                config_path=scd.get("config_path"),
                config_key=scd.get("config_key"),
                open_value=scd.get("open_value"),
                file_path=scd.get("file_path"),
                recorded_mtime=scd.get("recorded_mtime"),
                api_url=scd.get("api_url"),
                api_json_path=scd.get("api_json_path"),
                timeout=scd.get("timeout", 5.0),
            )
        markers.append(Marker(
            marker_id=d["marker_id"],
            status=MarkerStatus(d["status"]),
            recorded_at=d["recorded_at"],
            description=d.get("description", ""),
            state_check=sc,
        ))
    print(f"[perszisztencia] {len(markers)} marker betöltve: {path}")
    return markers


